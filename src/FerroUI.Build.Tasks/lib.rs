/// Every file below `directory`, with its rooted path below `root` (`/Assets/a.png`),
/// in the order of the names. Directories whose name starts with a dot and the
/// directory `target` of `root` are skipped.
fn collect(root: &Path, directory: &Path, found: &mut Vec<(String, PathBuf)>) -> Result<(), String> {
    let entries = fs::read_dir(directory).map_err(|error| format!("{}: {error}", directory.display()))?;
    let mut paths = Vec::new();
    for entry in entries {
        paths.push(entry.map_err(|error| format!("{}: {error}", directory.display()))?.path());
    }
    paths.sort();
    for path in paths {
        let name = path.file_name().map(|name| name.to_string_lossy().into_owned()).unwrap_or_default();
        if path.is_dir() {
            if !name.starts_with('.') && !(directory == root && name == "target") {
                collect(root, &path, found)?;
            }
            continue;
        }
        let relative = path.strip_prefix(root).map_err(|_| format!("{} is not below {}", path.display(), root.display()))?;
        let parts: Vec<String> = relative.components().map(|part| part.as_os_str().to_string_lossy().into_owned()).collect();
        found.push((format!("/{}", parts.join("/")), path));
    }
    Ok(())
}

/// Writes the instruction image before the source that references it. A group can stop
/// emitting programs when its documents or backend change.
fn write_compiled_file(path: &Path, source: &str, image: &BytecodeImage, errors: &mut Vec<String>) {
    let image_path = path.with_extension("fxc");
    let file_name = image_path.file_name().and_then(|s| s.to_str()).expect("generated module name");
    if let Some((bytes, declaration)) = image.artifact(file_name) {
        if let Err(error) = ferroui_build_scan::export::write_bytes_if_changed(&image_path, &bytes) {
            errors.push(error);
            return;
        }
        write_if_changed(path, &format!("{source}{declaration}"), errors);
    } else if let Err(error) = ferroui_build_scan::export::write_if_changed(path, source) {
        errors.push(error);
    } else if let Err(error) = fs::remove_file(&image_path) {
        if error.kind() != std::io::ErrorKind::NotFound {
            errors.push(format!("{}: {error}", image_path.display()));
        }
    }
}

fn write_if_changed(path: &Path, text: &str, errors: &mut Vec<String>) {
    if let Err(error) = ferroui_build_scan::export::write_if_changed(path, text) {
        errors.push(error);
    }
}

/// The text of `$OUT_DIR/xaml/mod.rs`, which `include_compiled_xaml!()` includes at the
/// root of the crate: the module of every group, and the module `compiled_markup`
/// with the asset table, the loader table of the crate (the checked-in tables, then
/// the groups, in order) and `register()`.
/// The parts tables of the themes the application trims (`parts`, #568) are statics of
/// `compiled_markup`, which `register()` registers.
/// Whether `{Binding}` compiles in the documents of a crate (#603): what its manifest states
/// (`compile-bindings`), else what its build script states ([`Build::default_compile_bindings`]),
/// else compiled bindings, the default.
fn compile_bindings_by_default(manifest: Option<bool>, build_script: Option<bool>) -> bool {
    // Deviation (DEVIATIONS.md, Build integration of markup): upstream's build task compiles
    // reflection bindings unless the project sets the default; compiled bindings are the default.
    manifest.or(build_script).unwrap_or(true)
}

