/// The file the crate includes, with the documents and the assets of the export plan
/// `applied` (#857): the loader table of every exported module and every asset without a plan.
fn crate_file_with_plan(
    assembly_name: &str,
    modules: &[Module],
    loaders: &[String],
    applied: &export_plan::Applied,
    parts: &[PartsTable],
) -> String {
    let assets = &applied.assets;
    let mut text = String::new();
    text.push_str("// @generated by ferroui-build (Build::run). Do not edit.\n");
    for Module { name: module, path, file, .. } in modules {
        text.push('\n');
        text.push_str(&format!("/// The compiled documents of the group `{module}`.\n"));
        text.push_str("#[doc(hidden)]\n");
        text.push_str("#[rustfmt::skip]\n");
        if *file {
            // The file of a class is a module file: it starts with attributes of the module.
            text.push_str(&format!("#[path = {}]\n", rust_string_literal(&path.display().to_string())));
            text.push_str(&format!("pub mod {module};\n"));
            continue;
        }
        // A document that is not public (`x:ClassModifier`) and that the documents of its
        // group only merge has a build function nothing calls: its content is in theirs.
        text.push_str("#[allow(dead_code)]\n");
        text.push_str(&format!("pub mod {module} {{\n"));
        text.push_str(&format!("    include!({});\n", rust_string_literal(&path.display().to_string())));
        text.push_str("}\n");
    }
    text.push('\n');
    text.push_str("/// The compiled markup and the embedded assets of the crate.\n");
    text.push_str("#[doc(hidden)]\n");
    text.push_str("#[rustfmt::skip]\n");
    text.push_str("pub mod compiled_markup {\n");
    text.push_str("    /// The assembly of the crate.\n");
    text.push_str(&format!("    pub const ASSEMBLY_NAME: &str = {};\n", rust_string_literal(assembly_name)));
    text.push('\n');
    text.push_str("    /// The embedded assets of the crate, by rooted path.\n");
    text.push_str("    pub static ASSETS: &[(&str, &[u8])] = &[\n");
    for (rooted, path) in assets {
        text.push_str(&format!(
            "        ({}, include_bytes!({})),\n",
            rust_string_literal(rooted),
            rust_string_literal(&path.display().to_string())
        ));
    }
    text.push_str("    ];\n");
    for table in parts {
        text.push('\n');
        text.push_str(&format!(
            "    /// The units of the theme `{}` the application keeps (#568): {} of {}, the closure of the\n",
            table.class,
            table.units.len(),
            table.total
        ));
        text.push_str("    /// roots of its documents and of `theme-roots` over the unit graph of the theme.\n");
        text.push_str(&format!(
            "    pub static {}: &[&::ferroui_markup_xaml::xaml_il::runtime::compiled::ThemeUnit] = &[\n",
            table.static_name
        ));
        for (path, name) in &table.units {
            text.push_str(&format!("        &{path}, // {}\n", name.replace(['\r', '\n'], " ")));
        }
        text.push_str("    ];\n");
    }
    text.push('\n');
    text.push_str("    /// The loader of the compiled markup of the crate: the object of the document with the URI\n");
    text.push_str("    /// `uri`, from the first table that has it; `Ok(None)` if none has.\n");
    text.push_str("    #[allow(unused_variables)]\n");
    text.push_str("    pub fn try_load(\n");
    text.push_str("        service_provider: ::core::option::Option<&::std::rc::Rc<dyn ::ferroui_base::metadata::IServiceProvider>>,\n");
    text.push_str("        uri: &str,\n");
    text.push_str("    ) -> ::core::result::Result<::core::option::Option<::ferroui_base::BoxedValue>, ::ferroui_markup_xaml::XamlLoadError> {\n");
    // A closed plan answers its documents only, after the checked-in tables (#857).
    let module_tables = match &applied.documents {
        None => modules
            .iter()
            .filter(|module| module.exported)
            .map(|module| format!("super::{}::try_load", module.name))
            .collect(),
        Some(_) => Vec::new(),
    };
    for table in loaders.iter().cloned().chain(module_tables) {
        text.push_str(&format!("        if let ::core::option::Option::Some(loaded) = {table}(service_provider, uri)? {{\n"));
        text.push_str("            return ::core::result::Result::Ok(::core::option::Option::Some(loaded));\n");
        text.push_str("        }\n");
    }
    if let Some(documents) = &applied.documents {
        text.push_str(&export_plan::loader_branches(documents, rust_string_literal));
    }
    text.push_str("        ::core::result::Result::Ok(::core::option::Option::None)\n");
    text.push_str("    }\n");
    text.push('\n');
    text.push_str("    /// Registers the assets and the compiled markup of the crate. The assembly is made known\n");
    text.push_str("    /// to the asset loader even without assets: a load by URI asks it for the assembly of the\n");
    text.push_str("    /// document.\n");
    text.push_str("    pub fn register() {\n");
    text.push_str("        ::ferroui_base::platform::register_assets(ASSEMBLY_NAME, ASSETS);\n");
    text.push_str("        ::ferroui_markup_xaml::FerroXamlLoader::register_compiled_xaml(ASSEMBLY_NAME, try_load);\n");
    for table in parts {
        text.push_str(&format!(
            "        ::ferroui_markup_xaml::xaml_il::runtime::compiled::register_wider_theme_parts({}, {});\n",
            rust_string_literal(&table.class),
            table.static_name
        ));
    }
    text.push_str("    }\n");
    text.push_str("}\n");
    text
}

