#!/usr/bin/env python3
"""Generate region/affix metadata from the official Unicode CLDR 48 npm archives.

Pass cldr-core-48.0.0.tgz, cldr-numbers-full-48.0.0.tgz and
cldr-localenames-full-48.0.0.tgz, followed by the output Rust path.
No network access or host locale influences generation.
"""
import hashlib
import json
import pathlib
import sys
import tarfile
import unicodedata

core_path, numbers_path, names_path, output = map(pathlib.Path, sys.argv[1:])
def archive(path):
    with tarfile.open(path) as tar:
        return {m.name: tar.extractfile(m).read() for m in tar if m.isfile()}
core, numbers, names = map(archive, (core_path, numbers_path, names_path))
def read(archive, path):
    return json.loads(archive['package/' + path])
def main(archive, locale, path):
    return read(archive, 'main/' + locale + '/' + path)['main'][locale]
def s(value):
    return ''.join('\\u{' + format(ord(c), '04x') + '}' if unicodedata.category(c) == 'Cf' else c
                   for c in json.dumps(str(value), ensure_ascii=False))
likely = read(core, 'supplemental/likelySubtags.json')['supplemental']['likelySubtags']
currencies = read(core, 'supplemental/currencyData.json')['supplemental']['currencyData']
english = main(names, 'en', 'territories.json')['localeDisplayNames']['territories']
region_currencies = {}
for region, items in currencies['region'].items():
    for item in items:
        for currency, value in item.items():
            if '_to' not in value and value.get('_tender', 'true') != 'false':
                region_currencies.setdefault(region, currency)

def region_for(locale):
    bits = locale.split('-')
    regions = [x for x in bits[1:] if len(x) == 2 or (len(x) == 3 and x.isdigit())]
    if regions: return regions[0]
    for key in [locale, bits[0], 'und']:
        if key in likely: return likely[key].split('-')[-1]
    return 'US'

name_paths = set(names)
lines = ['// @generated by tools/generate_locale_data.py; Unicode CLDR 48.0.0.',
         '// See NOTICE.md for the Unicode data license. Do not edit manually.']
for path in (core_path, numbers_path, names_path):
    lines.append('// ' + path.name + ' SHA-256: ' + hashlib.sha256(path.read_bytes()).hexdigest())
lines.extend(['#[rustfmt::skip]', 'pub(crate) static REGIONS: &[(&str, &str, &str, u8)] = &['])
for region, currency in sorted(region_currencies.items()):
    digits = currencies['fractions'].get(currency, currencies['fractions']['DEFAULT'])['_digits']
    lines.append(f'    ({s(region)}, {s(english.get(region, region))}, {s(currency)}, {digits}),')
lines.extend(['];', '', '#[rustfmt::skip]', 'pub(crate) static LOCALES: &[crate::region::LocaleData] = &['])
locales = sorted({p.split('/')[2] for p in numbers if p.endswith('/numbers.json')})
for locale in locales:
    n = main(numbers, locale, 'numbers.json')['numbers']
    region = region_for(locale)
    currency = region_currencies.get(region, 'XXX')
    symbols = main(numbers, locale, 'currencies.json')['numbers']['currencies']
    symbol = symbols.get(currency, {}).get('symbol', currency)
    native = english.get(region, region)
    candidates = [locale, locale.split('-')[0], 'en']
    for candidate in candidates:
        if 'package/main/' + candidate + '/territories.json' in name_paths:
            native = main(names, candidate, 'territories.json')['localeDisplayNames']['territories'].get(region, native)
            break
    ns = n['defaultNumberingSystem']
    currency_pattern = n.get('currencyFormats-numberSystem-' + ns, n['currencyFormats-numberSystem-latn'])['standard']
    percent_pattern = n.get('percentFormats-numberSystem-' + ns, n['percentFormats-numberSystem-latn'])['standard']
    percent_sign = n.get('symbols-numberSystem-' + ns, n['symbols-numberSystem-latn'])['percentSign']
    lines.append('    (' + ', '.join(map(s, [locale, region, native, symbol, currency_pattern, percent_pattern, percent_sign])) + '),')
lines.append('];')
lines.extend(['', '#[rustfmt::skip]', 'pub(crate) static NUMERIC_SYMBOLS: &[(&str, &str, bool, crate::formatting::NumericSymbols)] = &['])
for locale in locales:
    n = main(numbers, locale, 'numbers.json')['numbers']
    for key in sorted(k for k in n if k.startswith('symbols-numberSystem-')):
        ns = key.removeprefix('symbols-numberSystem-')
        symbols = n[key]
        fields = [('nan', 'nan'), ('infinity', 'infinity'), ('percent', 'percentSign'),
                  ('permille', 'perMille'), ('minus', 'minusSign'), ('plus', 'plusSign')]
        value = 'crate::formatting::NumericSymbols { ' + ', '.join(name + ': ' + s(symbols[source]) for name, source in fields) + ' }'
        lines.append('    (' + s(locale) + ', ' + s(ns) + ', ' + str(ns == n['defaultNumberingSystem']).lower() + ', ' + value + '),')
lines.append('];')
pathlib.Path(output).write_text('\n'.join(lines) + '\n')
print(f'Generated {len(region_currencies)} regions and {len(locales)} locale profiles')
