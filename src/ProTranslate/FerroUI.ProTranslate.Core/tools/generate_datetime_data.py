#!/usr/bin/env python3
"""Generate Gregorian names/patterns. Arguments: dates.tgz core.tgz output.rs."""
import hashlib
import json
import pathlib
import sys
import tarfile
import unicodedata

source, core_source, output = map(pathlib.Path, sys.argv[1:])
with tarfile.open(core_source) as archive:
    period_rules = json.load(archive.extractfile('package/supplemental/dayPeriods.json'))['supplemental']['dayPeriodRuleSet']
def minutes(value):
    hour, minute = value.split(':')
    return int(hour) * 60 + int(minute)
def flexible_periods(locale, names):
    key = locale
    while key not in period_rules and '-' in key: key = key.rsplit('-', 1)[0]
    rules = period_rules.get(key, {})
    result = []
    for name, rule in sorted(rules.items(), key=lambda item: ('_at' not in item[1], item[0])):
        if name not in names: continue
        exact = '_at' in rule
        start = minutes(rule.get('_at', rule.get('_from', '00:00')))
        end = start if exact else minutes(rule['_before'])
        result.append(f'({start}, {end}, {str(exact).lower()}, {s(names[name])})')
    return '&[' + ', '.join(result) + ']'
with tarfile.open(source) as archive:
    records = {member.name.split('/')[2]: json.load(archive.extractfile(member))
               for member in archive if member.name.endswith('/ca-gregorian.json')}
def s(value):
    if isinstance(value, dict): value = value['_value']
    return ''.join('\\u{' + format(ord(c), '04x') + '}' if unicodedata.category(c) == 'Cf' else c
                   for c in json.dumps(value, ensure_ascii=False))
def array(values):
    return '[' + ', '.join(map(s, values)) + ']'
lines = ['// @generated by tools/generate_datetime_data.py; Unicode CLDR 48.0.0.',
         '// Source: https://registry.npmjs.org/cldr-dates-full/-/cldr-dates-full-48.0.0.tgz',
         '// SHA-256: ' + hashlib.sha256(source.read_bytes()).hexdigest(),
         '// CLDR core SHA-256: ' + hashlib.sha256(core_source.read_bytes()).hexdigest(),
         '// See NOTICE.md for the Unicode data license.', '#[rustfmt::skip]',
         'pub(crate) static DATES: &[crate::datetime::DateData] = &[']
for locale, record in sorted(records.items()):
    g = record['main'][locale]['dates']['calendars']['gregorian']
    months = g['months']['format']
    alone = g['months']['stand-alone']
    days = g['days']['format']
    periods = g['dayPeriods']['format']['wide']
    available = g['dateTimeFormats']['availableFormats']
    values = {
        'locale': s(locale), 'short_date': s(g['dateFormats']['short']),
        'short_date_numbers': s(g['dateFormats']['short'].get('_numbers', '') if isinstance(g['dateFormats']['short'], dict) else ''),
        'long_date': s(g['dateFormats']['full']), 'short_time': s(g['timeFormats']['short']),
        'long_time': s(g['timeFormats']['medium']), 'join': s(g['dateTimeFormats']['medium']),
        'month_day': s(available.get('MMMMd', available.get('MMMd', 'MMMM d'))),
        'year_month': s(available.get('yMMMM', available.get('yMMM', 'MMMM y'))),
        'months': array([months['wide'][str(i)] for i in range(1, 13)]),
        'short_months': array([months['abbreviated'][str(i)] for i in range(1, 13)]),
        'standalone_months': array([alone['wide'][str(i)] for i in range(1, 13)]),
        'standalone_short_months': array([alone['abbreviated'][str(i)] for i in range(1, 13)]),
        'days': array([days['wide'][day] for day in ['sun','mon','tue','wed','thu','fri','sat']]),
        'short_days': array([days['abbreviated'][day] for day in ['sun','mon','tue','wed','thu','fri','sat']]),
        'am': s(periods.get('am', 'AM')), 'pm': s(periods.get('pm', 'PM')),
        'eras': array([g['eras']['eraAbbr'][era] for era in ['0', '1']]),
        'flexible_periods': flexible_periods(locale, periods),
    }
    if locale == 'en': invariant = values.copy()
    lines.append('    crate::datetime::DateData { ' + ', '.join(key + ': ' + value for key, value in values.items()) + ' },')
lines.append('];')
invariant.update({key: s(value) for key, value in {
    'locale': '', 'short_date': 'MM/dd/yyyy', 'short_date_numbers': '',
    'long_date': 'EEEE, dd MMMM yyyy', 'short_time': 'HH:mm', 'long_time': 'HH:mm:ss',
    'join': '{1} {0}', 'month_day': 'MMMM dd', 'year_month': 'yyyy MMMM',
}.items()})
lines.extend(['', '#[rustfmt::skip]', 'pub(crate) static INVARIANT: crate::datetime::DateData = crate::datetime::DateData { ' + ', '.join(key + ': ' + value for key, value in invariant.items()) + ' };'])
output.write_text('\n'.join(lines) + '\n')
print(f'Generated Gregorian profiles for {len(records)} locales')
