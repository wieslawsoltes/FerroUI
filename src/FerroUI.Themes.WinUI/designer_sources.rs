//! Opt-in source documents for component browsers and "Edit copy" workflows of designers.
//! Runtime themes continue to use compiled XAML; this catalog registers no assets.

/// The control theme documents of the theme (every document under `Controls/` that the theme
/// compiles), as `(resource URI, source text)`, in the order of their paths.
///
/// The `designer-sources` feature keeps these bytes out of normal application builds. Hosts may
/// register the catalog with a designer definition library; copied definitions are then owned by
/// the user document and authored through its ordinary transactions. The table is generated by
/// the build script from the documents of the crate, so it lists every new document.
pub fn designer_documents() -> &'static [(&'static str, &'static str)] {
    crate::assets::DESIGNER_DOCUMENTS
}

#[cfg(test)]
mod tests {
    use super::designer_documents;
    use crate::{assets, ASSEMBLY};

    #[test]
    fn designer_documents_are_the_compiled_control_theme_documents() {
        let prefix = format!("ferres://{}", ASSEMBLY.name);
        let expected: Vec<&str> = assets::documents()
            .iter()
            .map(|(path, _)| *path)
            .filter(|path| path.starts_with("/Controls/") && !assets::is_excluded(path))
            .collect();
        let listed: Vec<&str> = designer_documents()
            .iter()
            .map(|(uri, _)| uri.strip_prefix(prefix.as_str()).expect("the resource URI of the theme"))
            .collect();
        assert_eq!(listed, expected);
        for (uri, source) in designer_documents() {
            let path = uri.strip_prefix(prefix.as_str()).unwrap();
            assert_eq!(Some(source.as_bytes()), assets::document(path), "{uri}");
        }
        assert!(listed.contains(&"/Controls/NavigationView.xaml"));
    }
}
