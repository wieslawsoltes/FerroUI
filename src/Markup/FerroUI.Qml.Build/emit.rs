impl Rust for Modifiers {
    fn emit(&self, out: &mut Writer) {
        let Modifiers {
            required,
            readonly,
            default,
            final_,
            virtual_,
            override_,
        } = *self;
        if *self == Modifiers::default() {
            out.text.push_str("q::Modifiers::default()");
        } else {
            fields!(
                out,
                "q::Modifiers",
                required,
                readonly,
                default,
                final_,
                virtual_,
                override_
            );
        }
    }
}

// The constructors are exhaustive. A change to the IR must also compile here.
macro_rules! record {
    ($out:ident, $ty:ident::$variant:ident { $($field:ident),+ }) => {
        fields!($out, concat!("q::", stringify!($ty), "::", stringify!($variant)), $($field),+)
    };
}
macro_rules! tuple {
    ($out:ident, $ty:ident::$variant:ident ($first:expr $(, $next:expr)*)) => {{
        $out.text.push_str(concat!("q::", stringify!($ty), "::", stringify!($variant), "("));
        $first.emit($out);
        $( $out.text.push_str(", "); $next.emit($out); )*
        $out.text.push(')');
    }};
}

impl Rust for MemberKind {
    fn emit(&self, out: &mut Writer) {
        match self {
            Self::Id(id) => tuple!(out, MemberKind::Id(id)),
            Self::Property {
                name,
                ty,
                modifiers,
                value,
            } => record!(
                out,
                MemberKind::Property {
                    name,
                    ty,
                    modifiers,
                    value
                }
            ),
            Self::Binding { name, value } => record!(out, MemberKind::Binding { name, value }),
            Self::OnProperty { name, object } => {
                record!(out, MemberKind::OnProperty { name, object })
            }
            Self::Child(child) => tuple!(out, MemberKind::Child(child)),
            Self::Group { name, members } => record!(out, MemberKind::Group { name, members }),
            Self::Signal { name, parameters } => {
                record!(out, MemberKind::Signal { name, parameters })
            }
            Self::Function {
                name,
                parameters,
                return_type,
                body,
            } => record!(
                out,
                MemberKind::Function {
                    name,
                    parameters,
                    return_type,
                    body
                }
            ),
            Self::Handler {
                name,
                parameters,
                body,
            } => record!(
                out,
                MemberKind::Handler {
                    name,
                    parameters,
                    body
                }
            ),
            Self::Component { name, object } => {
                record!(out, MemberKind::Component { name, object })
            }
            Self::Enum { name, values } => record!(out, MemberKind::Enum { name, values }),
        }
    }
}
impl Rust for Binding {
    fn emit(&self, out: &mut Writer) {
        match self {
            Self::Expr(expr) => tuple!(out, Binding::Expr(expr)),
            Self::Object(object) => tuple!(out, Binding::Object(object)),
            Self::Objects(objects) => tuple!(out, Binding::Objects(objects)),
            Self::Script(script) => tuple!(out, Binding::Script(script)),
        }
    }
}
impl Rust for Expr {
    fn emit(&self, out: &mut Writer) {
        match self {
            Self::JavaScript(js) => tuple!(out, Expr::JavaScript(js)),
            Self::Native(index) => tuple!(out, Expr::Native(index)),
            Self::Null => out.text.push_str("q::Expr::Null"),
            Self::Undefined => out.text.push_str("q::Expr::Undefined"),
            Self::Number(n) => {
                write!(out.text, "q::Expr::Number(f64::from_bits({}))", n.to_bits()).unwrap();
            }
            Self::Bool(v) => tuple!(out, Expr::Bool(v)),
            Self::String(v) => tuple!(out, Expr::String(v)),
            Self::Name(v) => tuple!(out, Expr::Name(v)),
            Self::ResolvedId { name, target } => record!(out, Expr::ResolvedId { name, target }),
            Self::ScopedName { name, root } => record!(out, Expr::ScopedName { name, root }),
            Self::Array(v) => tuple!(out, Expr::Array(v)),
            Self::Record(v) => tuple!(out, Expr::Record(v)),
            Self::Member(base, name) => tuple!(out, Expr::Member(base, name)),
            Self::Index(base, index) => tuple!(out, Expr::Index(base, index)),
            Self::Unary(op, input) => tuple!(out, Expr::Unary(op, input)),
            Self::Binary(op, l, r) => tuple!(out, Expr::Binary(op, l, r)),
            Self::Conditional(test, yes, no) => tuple!(out, Expr::Conditional(test, yes, no)),
            Self::Call(callee, args) => tuple!(out, Expr::Call(callee, args)),
        }
    }
}
impl Rust for Stmt {
    fn emit(&self, out: &mut Writer) {
        match self {
            Self::JavaScript(js) => tuple!(out, Stmt::JavaScript(js)),
            Self::Native(index) => tuple!(out, Stmt::Native(index)),
            Self::While {
                test,
                body,
                post_test,
            } => record!(
                out,
                Stmt::While {
                    test,
                    body,
                    post_test
                }
            ),
            Self::For {
                init,
                test,
                update,
                body,
            } => record!(
                out,
                Stmt::For {
                    init,
                    test,
                    update,
                    body
                }
            ),
            Self::Break => out.text.push_str("q::Stmt::Break"),
            Self::Continue => out.text.push_str("q::Stmt::Continue"),
            Self::Expr(e) => tuple!(out, Stmt::Expr(e)),
            Self::Return(value) => tuple!(out, Stmt::Return(value)),
            Self::Assign { target, op, value } => record!(out, Stmt::Assign { target, op, value }),
            Self::Let { name, value } => record!(out, Stmt::Let { name, value }),
            Self::If {
                test,
                then_body,
                else_body,
            } => record!(
                out,
                Stmt::If {
                    test,
                    then_body,
                    else_body
                }
            ),
            Self::Block(body) => tuple!(out, Stmt::Block(body)),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn data_strings_round_trip_as_rust_literals() {
        let value = "text\"\\\r\n\t\0☃\u{202e}\"), panic!(\"bad\")".to_owned();
        let mut writer = Writer {
            text: String::new(),
            indent: 0,
        };
        value.emit(&mut writer);
        let call: syn::ExprCall = syn::parse_str(&writer.text).unwrap();
        let syn::Expr::Lit(expr) = &call.args[0] else {
            panic!("string literal expected")
        };
        let syn::Lit::Str(lit) = &expr.lit else {
            panic!("string literal expected")
        };
        assert_eq!(lit.value(), value);
    }
}
