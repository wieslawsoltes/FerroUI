//! Write typed IR as Rust constructors directly into the output buffer. Only
//! executable Rust goes through the token builder, parser and pretty-printer.
use ferroui_qml_compiler::*;
use quote::quote;
use std::fmt::Write;

pub(crate) fn module(mut document: Document) -> Result<String, String> {
    let functions = crate::native::lower(&mut document)?;
    let expressions = functions.expressions;
    let first_reads = functions.first_reads;
    let scripts = functions.scripts;
    let tables = quote! {
        static FUNCTIONS: &[::ferroui_qml::compiled::Evaluator] = &[#(#expressions),*];
        static SCRIPTS: &[::ferroui_qml::compiled::Script] = &[#(#scripts),*];
        static FIRST_READS: &[::ferroui_qml::compiled::FirstRead] = &[#(#first_reads),*];
    };
    let file = syn::parse2(tables).map_err(|e| format!("invalid generated Rust function: {e}"))?;
    let mut out = Writer {
        text: String::from(
            r#"// Generated by ferroui-qmlc.
#[allow(unused_assignments, unused_braces, clippy::needless_return, clippy::needless_question_mark)]
pub fn compiled_qml() -> ::ferroui_qml::CompiledComponent {
    use ::ferroui_qml::ir as q;
    #[allow(unused_imports)]
    use ::std::{boxed::Box, string::String, vec, vec::Vec, result::Result::Ok, option::Option::{Some, None}};
    #[allow(unused_imports)]
    use ::ferroui_qml::{compiled as c, Value as V};
    #[allow(unused_variables, unused_mut)]
    let mut script_imports = ::ferroui_qml::compiled::ScriptImportTables::default();
"#,
        ),
        indent: 1,
    };
    for line in prettyplease::unparse(&file).lines() {
        writeln!(out.text, "    {line}").unwrap();
    }
    out.text.push_str("    let document = ");
    document.emit(&mut out);
    out.text.push_str(";\n    ::ferroui_qml::CompiledComponent::new(document, FUNCTIONS, SCRIPTS).with_first_reads(FIRST_READS)\n}\n");
    Ok(out.text)
}

struct Writer {
    text: String,
    indent: usize,
}
impl Writer {
    fn new_line(&mut self) {
        self.text.push('\n');
        for _ in 0..self.indent {
            self.text.push_str("    ");
        }
    }
}
trait Rust {
    const BLOCK: bool = false;
    fn emit(&self, out: &mut Writer);
}
impl<T: Rust> Rust for Option<T> {
    fn emit(&self, out: &mut Writer) {
        if let Some(value) = self {
            out.text.push_str("Some(");
            value.emit(out);
            out.text.push(')');
        } else {
            out.text.push_str("None");
        }
    }
}
impl<T: Rust> Rust for Box<T> {
    fn emit(&self, out: &mut Writer) {
        out.text.push_str("Box::new(");
        (**self).emit(out);
        out.text.push(')');
    }
}
impl<T: Rust> Rust for Vec<T> {
    fn emit(&self, out: &mut Writer) {
        out.text.push_str("vec![");
        out.indent += 1;
        for (i, item) in self.iter().enumerate() {
            if i != 0 {
                out.text.push_str(", ");
            }
            if T::BLOCK {
                out.new_line();
            }
            item.emit(out);
        }
        out.indent -= 1;
        if T::BLOCK && !self.is_empty() {
            out.new_line();
        }
        out.text.push(']');
    }
}
impl<T: Rust> Rust for std::collections::BTreeMap<String, T> {
    fn emit(&self, out: &mut Writer) {
        out.text.push_str("::std::collections::BTreeMap::from([");
        for (i, (key, value)) in self.iter().enumerate() {
            if i != 0 {
                out.text.push_str(", ");
            }
            out.text.push('(');
            key.emit(out);
            out.text.push_str(", ");
            value.emit(out);
            out.text.push(')');
        }
        out.text.push_str("])");
    }
}
impl Rust for std::sync::Arc<Vec<Import>> {
    fn emit(&self, out: &mut Writer) {
        out.text.push_str("::std::sync::Arc::new(");
        self.as_ref().emit(out);
        out.text.push(')');
    }
}
impl Rust for std::sync::Arc<std::collections::BTreeMap<String, String>> {
    fn emit(&self, out: &mut Writer) {
        out.text.push_str("script_imports.intern(&[");
        for (i, (name, url)) in self.iter().enumerate() {
            if i != 0 {
                out.text.push_str(", ");
            }
            write!(out.text, "({name:?}, {url:?})").unwrap();
        }
        out.text.push_str("])");
    }
}
impl Rust for String {
    fn emit(&self, out: &mut Writer) {
        write!(out.text, "String::from({self:?})").unwrap();
    }
}
impl<A: Rust, B: Rust> Rust for (A, B) {
    fn emit(&self, out: &mut Writer) {
        out.text.push('(');
        self.0.emit(out);
        out.text.push_str(", ");
        self.1.emit(out);
        out.text.push(')');
    }
}
macro_rules! primitive {
    ($($ty:ty),*) => {$(
        impl Rust for $ty {
            fn emit(&self, out: &mut Writer) { write!(out.text, "{self}").unwrap(); }
        }
    )*};
}
primitive!(bool, i32, usize, u32);
macro_rules! fields {
    ($out:ident, $name:expr, $first:ident $(, $next:ident)*) => {{
        $out.text.push_str(concat!($name, " { ", stringify!($first), ": "));
        $first.emit($out);
        $( $out.text.push_str(concat!(", ", stringify!($next), ": ")); $next.emit($out); )*
        $out.text.push_str(" }");
    }};
}
macro_rules! structure {
    (block $ty:ident { $($field:ident),+ }) => { structure!(true, $ty { $($field),+ }); };
    ($ty:ident { $($field:ident),+ }) => { structure!(false, $ty { $($field),+ }); };
    ($block:expr, $ty:ident { $($field:ident),+ }) => {
        impl Rust for $ty {
            const BLOCK: bool = $block;
            fn emit(&self, out: &mut Writer) {
                let Self { $($field),+ } = self;
                fields!(out, concat!("q::", stringify!($ty)), $($field),+);
            }
        }
    };
}
macro_rules! tag {
    ($ty:ident { $($variant:ident),+ }) => {
        impl Rust for $ty {
            fn emit(&self, out: &mut Writer) {
                out.text.push_str(match self { $(Self::$variant => concat!("q::", stringify!($ty), "::", stringify!($variant))),+ });
            }
        }
    };
}
