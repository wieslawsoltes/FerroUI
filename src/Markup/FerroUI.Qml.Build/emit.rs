//! Emit typed IR constructors. Quote only literals originating in user input.
use ferroui_qml_compiler::*;
use proc_macro2::TokenStream;
use quote::quote;

pub(crate) fn module(mut document: Document) -> Result<String, String> {
    let crate::native::Functions {
        expressions,
        first_reads,
        scripts,
    } = crate::native::lower(&mut document)?;
    let ir = document.rust();
    let module = quote! {
        // ECMAScript exposes a statement completion value, including in script bindings.
        // A uniform Result and completion-value convention also represents simple leaves.
            #[allow(unused_assignments, unused_braces, clippy::needless_return, clippy::needless_question_mark)]
        pub fn compiled_qml() -> ::ferroui_qml::CompiledComponent {
            use ::ferroui_qml::ir as q;
                #[allow(unused_imports)]
                use ::std::{boxed::Box, string::String, vec, vec::Vec, result::Result::Ok, option::Option::{Some, None}};
            #[allow(unused_imports)]
            use ::ferroui_qml::{compiled as c, Value as V};
            static FUNCTIONS: &[::ferroui_qml::compiled::Evaluator] = &[#(#expressions),*];
            static SCRIPTS: &[::ferroui_qml::compiled::Script] = &[#(#scripts),*];
            static FIRST_READS: &[::ferroui_qml::compiled::FirstRead] = &[#(#first_reads),*];
            ::ferroui_qml::CompiledComponent::new(#ir, FUNCTIONS, SCRIPTS).with_first_reads(FIRST_READS)
        }
    };
    let file = syn::parse2(module).map_err(|e| format!("invalid generated Rust module: {e}"))?;
    Ok(format!(
        "// Generated by ferroui-qmlc.\n{}",
        prettyplease::unparse(&file)
    ))
}

trait Rust {
    fn rust(&self) -> TokenStream;
}

impl<T: Rust> Rust for Option<T> {
    fn rust(&self) -> TokenStream {
        match self {
            Some(v) => {
                let v = v.rust();
                quote!(Some(#v))
            }
            None => quote!(None),
        }
    }
}
impl<T: Rust> Rust for Box<T> {
    fn rust(&self) -> TokenStream {
        let v = (**self).rust();
        quote!(Box::new(#v))
    }
}
impl<T: Rust> Rust for Vec<T> {
    fn rust(&self) -> TokenStream {
        let values = self.iter().map(Rust::rust);
        quote!(vec![#(#values),*])
    }
}
impl<T: Rust> Rust for std::collections::BTreeMap<String, T> {
    fn rust(&self) -> TokenStream {
        let pairs = self.iter().map(|(key, value)| {
            let (key, value) = (key.rust(), value.rust());
            quote!((#key,#value))
        });
        quote!(::std::collections::BTreeMap::from([#(#pairs),*]))
    }
}

impl Rust for String {
    fn rust(&self) -> TokenStream {
        quote!(String::from(#self))
    }
}
impl Rust for (String, Expr) {
    fn rust(&self) -> TokenStream {
        let (key, value) = (self.0.rust(), self.1.rust());
        quote!((#key,#value))
    }
}
impl Rust for (String, i32) {
    fn rust(&self) -> TokenStream {
        let (name, value) = (self.0.rust(), self.1);
        quote!((#name, #value))
    }
}
macro_rules! primitive {
    ($($ty:ty),*) => {$(
        impl Rust for $ty { fn rust(&self) -> TokenStream { quote!(#self) } }
    )*};
}
primitive!(bool, usize, u32);

macro_rules! structure {
    ($ty:ident { $($field:ident),+ }) => {
        impl Rust for $ty {
            fn rust(&self) -> TokenStream {
                let Self { $($field),+ } = self;
                $(let $field = $field.rust();)+
                let fields = [$(quote!($field: #$field)),+];
                quote!(q::$ty { #(#fields),* })
            }
        }
    };
}
macro_rules! tag {
    ($ty:ident { $($variant:ident),+ }) => {
        impl Rust for $ty {
            fn rust(&self) -> TokenStream {
                match self { $(Self::$variant => quote!(q::$ty::$variant)),+ }
            }
        }
    };
}
