// The constructors are exhaustive. A change to the IR must also compile here.
macro_rules! record {
    ($ty:ident::$variant:ident { $($field:ident),+ }) => {{
        let fields = [$( { let value = $field.rust(); quote!($field: #value) } ),+];
        quote!(q::$ty::$variant { #(#fields),* })
    }};
}
macro_rules! tuple {
    ($ty:ident::$variant:ident ($($arg:expr),+)) => {{
        let args = [$($arg.rust()),+];
        quote!(q::$ty::$variant(#(#args),*))
    }};
}

impl Rust for MemberKind {
    fn rust(&self) -> TokenStream {
        match self {
            Self::Id(id) => tuple!(MemberKind::Id(id)),
            Self::Property {
                name,
                ty,
                modifiers,
                value,
            } => record!(MemberKind::Property {
                name,
                ty,
                modifiers,
                value
            }),
            Self::Binding { name, value } => record!(MemberKind::Binding { name, value }),
            Self::OnProperty { name, object } => record!(MemberKind::OnProperty { name, object }),
            Self::Child(child) => tuple!(MemberKind::Child(child)),
            Self::Group { name, members } => record!(MemberKind::Group { name, members }),
            Self::Signal { name, parameters } => record!(MemberKind::Signal { name, parameters }),
            Self::Function {
                name,
                parameters,
                return_type,
                body,
            } => record!(MemberKind::Function {
                name,
                parameters,
                return_type,
                body
            }),
            Self::Handler {
                name,
                parameters,
                body,
            } => record!(MemberKind::Handler {
                name,
                parameters,
                body
            }),
            Self::Component { name, object } => record!(MemberKind::Component { name, object }),
            Self::Enum { name, values } => record!(MemberKind::Enum { name, values }),
        }
    }
}
impl Rust for Binding {
    fn rust(&self) -> TokenStream {
        match self {
            Self::Expr(expr) => tuple!(Binding::Expr(expr)),
            Self::Object(object) => tuple!(Binding::Object(object)),
            Self::Objects(objects) => tuple!(Binding::Objects(objects)),
            Self::Script(script) => tuple!(Binding::Script(script)),
        }
    }
}
impl Rust for Expr {
    fn rust(&self) -> TokenStream {
        match self {
            Self::JavaScript(js) => tuple!(Expr::JavaScript(js)),
            Self::Native(index) => tuple!(Expr::Native(index)),
            Self::Null => quote!(q::Expr::Null),
            Self::Undefined => quote!(q::Expr::Undefined),
            Self::Number(n) => {
                let bits = n.to_bits();
                quote!(q::Expr::Number(f64::from_bits(#bits)))
            }
            Self::Bool(v) => tuple!(Expr::Bool(v)),
            Self::String(v) => tuple!(Expr::String(v)),
            Self::Name(v) => tuple!(Expr::Name(v)),
            Self::ScopedName { name, root } => record!(Expr::ScopedName { name, root }),
            Self::Array(v) => tuple!(Expr::Array(v)),
            Self::Record(v) => tuple!(Expr::Record(v)),
            Self::Member(base, name) => tuple!(Expr::Member(base, name)),
            Self::Index(base, index) => tuple!(Expr::Index(base, index)),
            Self::Unary(op, input) => tuple!(Expr::Unary(op, input)),
            Self::Binary(op, l, r) => tuple!(Expr::Binary(op, l, r)),
            Self::Conditional(test, yes, no) => tuple!(Expr::Conditional(test, yes, no)),
            Self::Call(callee, args) => tuple!(Expr::Call(callee, args)),
        }
    }
}
impl Rust for Stmt {
    fn rust(&self) -> TokenStream {
        match self {
            Self::JavaScript(js) => tuple!(Stmt::JavaScript(js)),
            Self::Native(index) => tuple!(Stmt::Native(index)),
            Self::While {
                test,
                body,
                post_test,
            } => record!(Stmt::While {
                test,
                body,
                post_test
            }),
            Self::For {
                init,
                test,
                update,
                body,
            } => record!(Stmt::For {
                init,
                test,
                update,
                body
            }),
            Self::Break => quote!(q::Stmt::Break),
            Self::Continue => quote!(q::Stmt::Continue),
            Self::Expr(e) => tuple!(Stmt::Expr(e)),
            Self::Return(value) => tuple!(Stmt::Return(value)),
            Self::Assign { target, op, value } => record!(Stmt::Assign { target, op, value }),
            Self::Let { name, value } => record!(Stmt::Let { name, value }),
            Self::If {
                test,
                then_body,
                else_body,
            } => record!(Stmt::If {
                test,
                then_body,
                else_body
            }),
            Self::Block(body) => tuple!(Stmt::Block(body)),
        }
    }
}
