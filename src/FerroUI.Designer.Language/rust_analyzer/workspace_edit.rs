use crate::{
    require, DocumentEdits, FileMoveRustResolution, GeneratedRustRename, LanguageError, Position,
    Range, Result, RustRenameResolution, RustSymbolRename, TextEdit,
};
use ferroui_designer_project::{canonical_file_uri, file_path};
use serde::Deserialize;
use serde_json::Value;
use std::{
    collections::{BTreeMap, BTreeSet},
    path::PathBuf,
};

#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
struct WorkspaceEdit {
    changes: Option<BTreeMap<String, Vec<TextEdit>>>,
    document_changes: Option<Vec<TextDocumentEdit>>,
}

#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
struct TextDocumentEdit {
    text_document: Document,
    edits: Vec<TextEdit>,
}

#[derive(Deserialize)]
struct Document {
    uri: String,
    version: Option<i64>,
}

pub(super) fn resolve(
    rename: &GeneratedRustRename,
    response: Value,
    generated: &BTreeSet<PathBuf>,
    versions: &BTreeMap<String, i64>,
) -> Result<FileMoveRustResolution> {
    resolve_documents(
        rename,
        response,
        versions,
        |uri| {
            Ok(file_path(uri)?
                .parent()
                .is_some_and(|path| generated.contains(path)))
        },
        true,
    )
}

pub(super) fn resolve_authored(
    rename: &RustSymbolRename,
    response: Value,
    versions: &BTreeMap<String, i64>,
) -> Result<RustRenameResolution> {
    resolve_documents(rename, response, versions, generated_xaml_source, false)
}

fn resolve_documents(
    rename: &RustSymbolRename,
    response: Value,
    versions: &BTreeMap<String, i64>,
    skip: impl Fn(&str) -> Result<bool>,
    generated_declaration: bool,
) -> Result<RustRenameResolution> {
    let edit: WorkspaceEdit = serde_json::from_value(response).map_err(|error| {
        LanguageError(format!(
            "Rust rename did not return source edits for {}. {error}",
            rename.old_name
        ))
    })?;
    require(
        edit.changes.is_none() || edit.document_changes.is_none(),
        "Rust rename returned competing edit formats",
    )?;
    let edits = edit.document_changes.unwrap_or_else(|| {
        edit.changes
            .unwrap_or_default()
            .into_iter()
            .map(|(uri, edits)| TextDocumentEdit {
                text_document: Document { uri, version: None },
                edits,
            })
            .collect()
    });
    let declaration = Range {
        start: rename.position,
        end: Position {
            character: rename.position.character + rename.old_name.encode_utf16().count() as u32,
            ..rename.position
        },
    };
    let mut verified = false;
    let mut documents = Vec::new();
    for edit in edits {
        let uri = canonical_file_uri(&edit.text_document.uri)?;
        let skipped = skip(&uri)?;
        if uri == rename.uri && skipped == generated_declaration {
            verified |= edit
                .edits
                .iter()
                .any(|edit| edit.range == declaration && edit.new_text == rename.new_name);
        }
        if skipped {
            continue;
        }
        let version = versions.get(&uri).copied();
        require(
            edit.text_document.version.is_none()
                || (edit.text_document.version == Some(1) && version.is_some()),
            "Rust rename returned a version from another source snapshot",
        )?;
        documents.push(DocumentEdits {
            uri,
            version: version.unwrap_or(-1),
            edits: edit.edits,
        });
    }
    require(
        verified,
        if generated_declaration {
            format!("Rust could not resolve {} in the generated XAML module. Check the selected Cargo build", rename.old_name)
        } else {
            format!(
                "Rust could not resolve the authored declaration of {} in the selected Cargo build",
                rename.old_name
            )
        },
    )?;
    Ok(FileMoveRustResolution {
        rename: rename.clone(),
        documents,
    })
}

fn generated_xaml_source(uri: &str) -> Result<bool> {
    use std::io::Read;
    const PREFIX: &[u8] = b"// @generated by the Rust emitter of ferroui-markup-xaml-loader ";
    let file =
        std::fs::File::open(file_path(uri)?).map_err(|error| LanguageError(error.to_string()))?;
    let mut header = Vec::new();
    file.take(PREFIX.len() as u64)
        .read_to_end(&mut header)
        .map_err(|error| LanguageError(error.to_string()))?;
    Ok(header == PREFIX)
}
