use super::*;
use crate::LanguageService;

const URI: &str = "untitled:/Layout.xaml";

fn format_text(source: &str, options: &FormattingOptions) -> String {
    let mut language = LanguageService::new(Schema::ferroui());
    language.open(URI, source, 1).unwrap();
    let formatted =
        apply_text_edits(source, &language.format(URI, options.clone()).unwrap()).unwrap();
    language.replace(URI, &formatted, 2).unwrap();
    assert!(language.format(URI, options.clone()).unwrap().is_empty());
    formatted
}

#[test]
fn markup_arguments_and_attribute_tokens_survive_wrapping() {
    let source = "<Grid>\r\n<Button Width = '12' Tag=\"{Binding Title, StringFormat=' 🧭  {0} '}\"/>\r\n\r\n</Grid>";
    let options = FormattingOptions {
        attribute_layout: AttributeLayout::Wrap,
        wrap_column: 40,
        closing_bracket_on_new_line: true,
        insert_spaces: false,
        preserve_blank_lines: true,
        ..FormattingOptions::default()
    };
    let expected = "<Grid>\r\n\t<Button\r\n\t\tWidth = '12'\r\n\t\tTag=\"{Binding Title, StringFormat=' 🧭  {0} '}\"\r\n\t/>\r\n\r\n</Grid>\r\n";
    assert_eq!(format_text(source, &options), expected);
    let options = FormattingOptions {
        attribute_layout: AttributeLayout::Inline,
        self_closing_space: SelfClosingSpace::Space,
        tab_size: 2,
        ..FormattingOptions::default()
    };
    assert_eq!(
        format_text(expected, &options),
        "<Grid>\r\n  <Button Width = '12' Tag=\"{Binding Title, StringFormat=' 🧭  {0} '}\" />\r\n</Grid>\r\n"
    );
}

#[test]
fn protects_generated_and_whitespace_sensitive_content() {
    let protected = [
        "<TextBlock><Run Text='A'/><Run Text='B'/></TextBlock>",
        "<TextBlock><TextBlock.Inlines><Span>   <Run Text='X' /></Span></TextBlock.Inlines></TextBlock>",
        "<TextBlock>  <![CDATA[  Preserve 🧪   ]]><Run Text='X'/>  </TextBlock>",
        "<Border xml:space='preserve'>  <Grid><Button /></Grid>  </Border>",
        "<x:String> <!-- translator -->     </x:String>",
        "<Border>\u{a0}<Button />\n\u{a0}</Border>",
        "<!-- @formatter:off --><StackPanel   Width='3'><Button/></StackPanel><!-- @formatter:on -->",
    ];
    let source = format!(
        "<Grid xmlns:x='http://schemas.microsoft.com/winfx/2006/xaml'>{}<Border   Width='8'><Button/></Border></Grid>",
        protected.concat()
    );
    let options = FormattingOptions {
        attribute_layout: AttributeLayout::OnePerLine,
        self_closing_space: SelfClosingSpace::Space,
        ..FormattingOptions::default()
    };
    let formatted = format_text(&source, &options);
    for text in protected {
        assert!(
            formatted.contains(text),
            "Expected unchanged content: {text:?}"
        );
    }
    assert!(
        formatted.contains("    <Border\n        Width='8'>\n        <Button />\n    </Border>")
    );
    for marker in [
        "@generated by a project tool",
        "<auto-generated>Compiler output</auto-generated>",
    ] {
        let generated =
            format!("<?xml version='1.0'?>\r\n<!-- {marker} -->\r\n<Grid><Button  /></Grid>");
        assert_eq!(format_text(&generated, &options), generated);
    }
    let unclosed_region = "<Grid>\n<Border  Width='8'/><!-- @formatter:off --><StackPanel><Button/></StackPanel></Grid>";
    let result = format_text(unclosed_region, &options);
    assert!(result.starts_with("<Grid>\n    <Border\n        Width='8' />"));
    assert!(result.ends_with("<!-- @formatter:off --><StackPanel><Button/></StackPanel></Grid>"));
}

#[test]
fn range_edits_are_local_and_trailing_comments_obey_file_options() {
    let source =
        "<Grid><Button Content='🧭' Width='80'/><Button Width='40'/></Grid><!-- tail -->\r\n \r\n";
    let mut language = LanguageService::new(Schema::ferroui());
    language.open(URI, source, 1).unwrap();
    let index = LineIndex::new(source);
    let start = source.find("<Button").unwrap();
    let end = start + source[start..].find("/>").unwrap() + 2;
    let range = index.range(SourceSpan::new(start, end)).unwrap();
    let options = FormattingOptions {
        attribute_layout: AttributeLayout::OnePerLine,
        tab_size: 2,
        ..FormattingOptions::default()
    };
    let edits = language.format_range(URI, range, options.clone()).unwrap();
    assert!(
        edits
            .iter()
            .all(|edit| range.start <= edit.range.start && edit.range.end <= range.end)
    );
    let result = apply_text_edits(source, &edits).unwrap();
    assert!(
        result.starts_with(
            "<Grid><Button\r\n    Content='🧭'\r\n    Width='80'/><Button Width='40'/>"
        )
    );
    assert!(result.ends_with("<!-- tail -->\r\n \r\n"));
    assert!(format_text(source, &options).ends_with("<!-- tail -->\r\n"));
    assert!(
        format_text(
            source,
            &FormattingOptions {
                trim_final_newlines: false,
                ..options.clone()
            }
        )
        .ends_with("<!-- tail -->\r\n\r\n")
    );
    let options = FormattingOptions {
        insert_final_newline: false,
        ..options
    };
    assert!(format_text("<Grid/><!-- tail -->", &options).ends_with("<!-- tail -->"));
}
