use super::xml_whitespace;
use crate::Schema;
use ferroui_designer_core::{Document, Node, NodeKind, SourceSpan};

pub(super) fn is_generated(document: &Document) -> bool {
    document
        .ast()
        .roots()
        .iter()
        .take_while(|&&id| id != document.ast().root())
        .filter_map(|id| document.ast().node(*id))
        .filter_map(comment)
        .any(|text| {
            text.lines().map(str::trim).any(|line| {
                line.split_whitespace().next() == Some("@generated")
                    || line.starts_with("<auto-generated>")
                    || line.starts_with("<auto-generated ")
                    || line.starts_with("<auto-generated/>")
            })
        })
}

pub(super) fn disabled_ranges(document: &Document) -> Vec<SourceSpan> {
    let mut ranges = Vec::new();
    let mut start = None;
    for node in document.ast().nodes_in_source_order() {
        match comment(node) {
            Some("@formatter:off") => {
                start.get_or_insert(node.span.start);
            }
            Some("@formatter:on") => {
                if let Some(start) = start.take() {
                    ranges.push(SourceSpan::new(start, node.span.end));
                }
            }
            _ => {}
        }
    }
    if let Some(start) = start {
        ranges.push(SourceSpan::new(start, document.source().len()));
    }
    ranges
}

fn comment(node: &Node) -> Option<&str> {
    (node.kind == NodeKind::Comment).then_some(node.text.as_deref()?.trim())
}

pub(super) fn has_significant_content(document: &Document, schema: &Schema, node: &Node) -> bool {
    if node.children.is_empty() {
        return false;
    }
    if node
        .children
        .iter()
        .filter_map(|id| document.ast().node(*id))
        .any(|child| {
            child.kind == NodeKind::CData
                || (child.kind == NodeKind::Text
                    && !xml_whitespace(&document.source()[child.span.range()]))
        })
    {
        return true;
    }
    let namespace = node.namespace_uri.as_deref();
    let local = node.local_name();
    if local == "String" && namespace == Some("http://schemas.microsoft.com/winfx/2006/xaml") {
        return true;
    }
    let property_element = local.split_once('.');
    let (owner, member) = property_element.unwrap_or((local, "Inlines"));
    schema
        .property(owner, namespace, member)
        .is_some_and(|info| {
            matches!(
                info.type_name.as_str(),
                "InlineCollection" | "Option<InlineCollection>"
            ) || (property_element.is_some()
                && matches!(info.type_name.as_str(), "String" | "Option<String>"))
        })
        || schema.type_info(local, namespace).is_some_and(|info| {
            info.name == "InlineCollection" && info.namespace == crate::schema::FRAMEWORK_NAMESPACE
        })
}
