//! Compiles the original passive inspector property views with native bindings.
fn main() {
    let views = [
        (
            "controls/RootDockDebug.xaml",
            include_str!("controls/RootDockDebug.xaml"),
        ),
        (
            "controls/DockableDebugView.xaml",
            include_str!("controls/DockableDebugView.xaml"),
        ),
        (
            "controls/DockDebugView.xaml",
            include_str!("controls/DockDebugView.xaml"),
        ),
        (
            "controls/DockWindowDebugView.xaml",
            include_str!("controls/DockWindowDebugView.xaml"),
        ),
        (
            "controls/RootDockInfoDebugView.xaml",
            include_str!("controls/RootDockInfoDebugView.xaml"),
        ),
        (
            "controls/DockDockDebugView.xaml",
            include_str!("controls/DockDockDebugView.xaml"),
        ),
        (
            "controls/GridDockDebugView.xaml",
            include_str!("controls/GridDockDebugView.xaml"),
        ),
        (
            "controls/GridDockSplitterDebugView.xaml",
            include_str!("controls/GridDockSplitterDebugView.xaml"),
        ),
        (
            "controls/ProportionalDockDebugView.xaml",
            include_str!("controls/ProportionalDockDebugView.xaml"),
        ),
        (
            "controls/ProportionalDockSplitterDebugView.xaml",
            include_str!("controls/ProportionalDockSplitterDebugView.xaml"),
        ),
        (
            "controls/StackDockDebugView.xaml",
            include_str!("controls/StackDockDebugView.xaml"),
        ),
        (
            "controls/WrapDockDebugView.xaml",
            include_str!("controls/WrapDockDebugView.xaml"),
        ),
        (
            "controls/UniformGridDockDebugView.xaml",
            include_str!("controls/UniformGridDockDebugView.xaml"),
        ),
        (
            "controls/DocumentDockDebugView.xaml",
            include_str!("controls/DocumentDockDebugView.xaml"),
        ),
        (
            "controls/ToolDockDebugView.xaml",
            include_str!("controls/ToolDockDebugView.xaml"),
        ),
        (
            "controls/DocumentContentDebugView.xaml",
            include_str!("controls/DocumentContentDebugView.xaml"),
        ),
        (
            "controls/ToolContentDebugView.xaml",
            include_str!("controls/ToolContentDebugView.xaml"),
        ),
        (
            "controls/DocumentTemplateDebugView.xaml",
            include_str!("controls/DocumentTemplateDebugView.xaml"),
        ),
        (
            "controls/DocumentDockContentDebugView.xaml",
            include_str!("controls/DocumentDockContentDebugView.xaml"),
        ),
    ];
    let mut build = ferroui_build::Build::from_env()
        .type_system(ferroui_build::TypeSystem::Model)
        .default_compile_bindings(true);
    for (module, path) in [
        ("compiled_root_dock_debug", "controls/RootDockDebug.xaml"),
        (
            "compiled_dockable_debug_view",
            "controls/DockableDebugView.xaml",
        ),
        ("compiled_dock_debug_view", "controls/DockDebugView.xaml"),
        (
            "compiled_dock_window_debug_view",
            "controls/DockWindowDebugView.xaml",
        ),
        (
            "compiled_root_dock_info_debug_view",
            "controls/RootDockInfoDebugView.xaml",
        ),
        (
            "compiled_dock_dock_debug_view",
            "controls/DockDockDebugView.xaml",
        ),
        (
            "compiled_grid_dock_debug_view",
            "controls/GridDockDebugView.xaml",
        ),
        (
            "compiled_grid_dock_splitter_debug_view",
            "controls/GridDockSplitterDebugView.xaml",
        ),
        (
            "compiled_proportional_dock_debug_view",
            "controls/ProportionalDockDebugView.xaml",
        ),
        (
            "compiled_proportional_dock_splitter_debug_view",
            "controls/ProportionalDockSplitterDebugView.xaml",
        ),
        (
            "compiled_stack_dock_debug_view",
            "controls/StackDockDebugView.xaml",
        ),
        (
            "compiled_wrap_dock_debug_view",
            "controls/WrapDockDebugView.xaml",
        ),
        (
            "compiled_uniform_grid_dock_debug_view",
            "controls/UniformGridDockDebugView.xaml",
        ),
        (
            "compiled_document_dock_debug_view",
            "controls/DocumentDockDebugView.xaml",
        ),
        (
            "compiled_tool_dock_debug_view",
            "controls/ToolDockDebugView.xaml",
        ),
        (
            "compiled_document_content_debug_view",
            "controls/DocumentContentDebugView.xaml",
        ),
        (
            "compiled_tool_content_debug_view",
            "controls/ToolContentDebugView.xaml",
        ),
        (
            "compiled_document_template_debug_view",
            "controls/DocumentTemplateDebugView.xaml",
        ),
        (
            "compiled_document_dock_content_debug_view",
            "controls/DocumentDockContentDebugView.xaml",
        ),
    ] {
        build = build.input(path).compile_group(
            ferroui_build::XamlGroup::new(module)
                .documents(&views)
                .class_document(path),
        );
    }
    build.run();
}
