use super::*;
use crate::{collections::ReadOnlyListHandle, BoxedValue};
use std::rc::Rc;
#[test]
fn model_defaults_and_setters_preserve_original_reference_objects_and_nullable_lists() {
    let header: BoxedValue = Rc::new("header".to_owned());
    let icon: BoxedValue = Rc::new(17);
    let parameter: BoxedValue = Rc::new(std::cell::Cell::new(3));
    let item = DockCommandBarItem::new(Some(header.clone()));
    assert!(Rc::ptr_eq(&item.header().unwrap(), &header));
    assert!(item.icon().is_none());
    assert!(item.command().is_none());
    assert!(item.command_parameter().is_none());
    assert!(item.items().is_none());
    assert!(item.group_id().is_none());
    assert_eq!(item.order(), 0);
    assert!(!item.is_separator());
    let command: Rc<dyn ferroui_reactiveui::ICommand> = Rc::new(crate::test_support::TestCommand);
    let child = DockCommandBarItem::new(None);
    let items = ReadOnlyListHandle::from_items(vec![child.clone()]);
    item.set_icon(Some(icon.clone()));
    item.set_command(Some(command.clone()));
    item.set_command_parameter(Some(parameter.clone()));
    item.set_items(Some(items.clone()));
    item.set_group_id(Some(" group ".into()));
    item.set_order(i32::MIN);
    item.set_is_separator(true);
    assert!(Rc::ptr_eq(&item.icon().unwrap(), &icon));
    assert!(Rc::ptr_eq(&item.command().unwrap(), &command));
    assert!(Rc::ptr_eq(&item.command_parameter().unwrap(), &parameter));
    assert!(item.items().unwrap() == items);
    assert!(Rc::ptr_eq(&item.items().unwrap().get(0), &child));
    assert_eq!(item.group_id().as_deref(), Some(" group "));
    assert_eq!(item.order(), i32::MIN);
    assert!(item.is_separator());
    let bar = DockCommandBarDefinition::new("id".into(), DockCommandBarKind::Ribbon);
    assert_eq!(bar.id(), "id");
    assert_eq!(bar.kind(), DockCommandBarKind::Ribbon);
    assert_eq!(bar.merge_mode(), DockCommandBarMergeMode::Replace);
    assert_eq!(bar.order(), 0);
    assert!(bar.group_id().is_none());
    assert!(bar.items().is_none());
    assert!(bar.content().is_none());
    bar.set_merge_mode(DockCommandBarMergeMode::MergeByGroup);
    bar.set_order(i32::MAX);
    bar.set_group_id(Some("".into()));
    bar.set_items(Some(items.clone()));
    bar.set_content(Some(parameter.clone()));
    assert_eq!(bar.merge_mode(), DockCommandBarMergeMode::MergeByGroup);
    assert_eq!(bar.order(), i32::MAX);
    assert_eq!(bar.group_id().as_deref(), Some(""));
    assert!(bar.items().unwrap() == items);
    assert!(Rc::ptr_eq(&bar.content().unwrap(), &parameter));
    assert!(*bar == *bar.clone());
    assert!(*bar != *DockCommandBarDefinition::new("id".into(), DockCommandBarKind::Ribbon));
    assert!(*child != *DockCommandBarItem::new(None));
    item.set_header(None);
    item.set_icon(None);
    item.set_command(None);
    item.set_command_parameter(None);
    item.set_items(None);
    item.set_group_id(None);
    item.set_order(0);
    item.set_is_separator(false);
    assert!(item.header().is_none());
    assert!(item.icon().is_none());
    assert!(item.command().is_none());
    assert!(item.command_parameter().is_none());
    assert!(item.items().is_none());
    assert!(item.group_id().is_none());
    assert!(!item.is_separator());
    bar.set_content(None);
    bar.set_items(None);
    bar.set_group_id(None);
    assert!(bar.content().is_none());
    assert!(bar.items().is_none());
    assert!(bar.group_id().is_none());
}
