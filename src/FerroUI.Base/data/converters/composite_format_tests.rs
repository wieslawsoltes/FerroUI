#[test]
fn composite_without_arguments() {
    assert_eq!(format("no args", &[]).as_deref(), Ok("no args"));
    assert_eq!(format("{{}}", &[]).as_deref(), Ok("{}"));
    assert_eq!(format("{0}", &[]), Err(FormatError::IndexOutOfRange));
}

#[test]
fn composite_with_one_argument() {
    assert_eq!(format("{0}", &[Null]).as_deref(), Ok(""));
    assert_eq!(format("[{0,3}]", &[Str("\u{e9}")]).as_deref(), Ok("[  \u{e9}]"));
    assert_eq!(format("{0}", &[F64(1e16)]).as_deref(), Ok("10000000000000000"));
    assert_eq!(format("{0}", &[F32(1.5)]).as_deref(), Ok("1.5"));
    assert_eq!(format("{0}", &[Bool(false)]).as_deref(), Ok("False"));
    assert_eq!(format("{0:0.00}", &[I32(5)]).as_deref(), Ok("5.00"));
    assert_eq!(format("{0,8:F2}", &[F64(7.12345)]).as_deref(), Ok("    7.12"));
    assert_eq!(format("{0}", &[I64(i64::MIN)]).as_deref(), Ok("-9223372036854775808"));
    assert_eq!(format("{0}", &[U64(u64::MAX)]).as_deref(), Ok("18446744073709551615"));
    assert_eq!(format("{0}{1}", &[I32(1)]), Err(FormatError::IndexOutOfRange));
}

#[test]
fn composite_error_kinds() {
    let args = [I32(1)];
    assert_eq!(format("{", &args), Err(FormatError::InvalidFormat));
    assert_eq!(format("}", &args), Err(FormatError::InvalidFormat));
    assert_eq!(format("{0", &args), Err(FormatError::InvalidFormat));
    assert_eq!(format("{a}", &args), Err(FormatError::InvalidFormat));
    assert_eq!(format("{0,x}", &args), Err(FormatError::InvalidFormat));
    assert_eq!(format("{0:{}", &args), Err(FormatError::InvalidFormat));
    assert_eq!(format("{1}", &args), Err(FormatError::IndexOutOfRange));
    assert_eq!(format("{99999999999999999999}", &args), Err(FormatError::InvalidFormat));
    assert_eq!(format("{0:Z}", &args), Err(FormatError::InvalidFormatSpecifier));
    assert_eq!(format("{0:R}", &[F64(1.5)]).as_deref(), Ok("1.5"));
    assert_eq!(format("{0:D}", &[F64(1.5)]), Err(FormatError::InvalidFormatSpecifier));
}

#[test]
fn alignment_counts_utf16_code_units() {
    // U+1F600 is two UTF-16 code units.
    assert_eq!(format("[{0,4}]", &[Str("\u{1f600}")]).as_deref(), Ok("[  \u{1f600}]"));
    assert_eq!(format("[{0,-4}]", &[Str("ab")]).as_deref(), Ok("[ab  ]"));
    assert_eq!(format("[{0,1000}]", &[Str("")]).map(|s| s.len()), Ok(1002));
}

