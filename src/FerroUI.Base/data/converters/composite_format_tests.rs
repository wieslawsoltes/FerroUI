#[test]
fn format_values_uses_display_form_of_other_values() {
    #[derive(PartialEq)]
    struct Unregistered;

    let values = [
        Some(FerroProperty::unset_value()),
        Some(Rc::new(BindingNotification::new(boxed(5i32))) as BoxedValue),
        boxed(Unregistered),
    ];
    let text = format_values("{0}|{1}|{2:F2}", &values).expect("valid format");
    assert!(text.starts_with("(unset)|{Value: 5}|"), "{text}");
    assert!(text.ends_with("Unregistered"), "{text}");
}

