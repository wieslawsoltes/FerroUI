//! Tests of composite formatting.
//!
//! Every expected string in the tables was produced by the managed runtime
//! (version 10, invariant culture) for the same value and format string.

use super::composite_format::FormatArg::*;
use super::composite_format::*;
use crate::data::BindingNotification;
use crate::{BoxedValue, FerroProperty};
use std::rc::Rc;

fn check(cases: &[(FormatArg<'static>, &str, &str)]) {
    for (arg, format_string, expected) in cases {
        let actual = format_arg(arg, format_string);
        assert_eq!(actual.as_deref(), Ok(*expected), "{arg:?} with {format_string:?}");
    }
}

fn check_errors(cases: &[(FormatArg<'static>, &str)]) {
    for (arg, format_string) in cases {
        let actual = format_arg(arg, format_string);
        assert_eq!(actual, Err(FormatError::InvalidFormatSpecifier), "{arg:?} with {format_string:?}");
    }
}

