#[cfg(test)]
mod tests {
    // The reference test-suite has no dedicated tests for this type.
    use super::*;

    #[test]
    fn predefined_colors_have_expected_values() {
        assert_eq!(Colors::RED, Color::new(0xff, 0xff, 0x00, 0x00));
        assert_eq!(Colors::ALICE_BLUE.to_uint32(), 0xfff0f8ff);
        assert_eq!(Colors::TRANSPARENT, Color::new(0x00, 0xff, 0xff, 0xff));
        assert_eq!(Colors::YELLOW_GREEN.to_uint32(), 0xff9acd32);
        assert_eq!(Colors::AQUA, Colors::CYAN);
    }
}
