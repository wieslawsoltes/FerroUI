//! With the feature `msl`: `shaders/scene3d.wgsl` translated by naga to the Metal Shading Language
//! at build time, for the Metal executor of the Skia backend on Graphite (step D5 of #608,
//! `docs/porting/media3d.md`, section 3.19). The output is `$OUT_DIR/scene3d.metal` and
//! `$OUT_DIR/scene3d_msl.rs` (the source, the names of the functions and the argument table
//! slots), included by the module `shader::msl`. Without the feature the script does nothing.

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=shaders/scene3d.wgsl");
    #[cfg(feature = "msl")]
    msl::write();
}

#[cfg(feature = "msl")]
mod msl {
    use naga::back::msl::sampler::{Address, Filter, InlineSampler};
    use naga::back::msl::{BindSamplerTarget, BindTarget, EntryPointResources, Options, PipelineOptions};
    use naga::ResourceBinding;
    use std::fmt::Write as _;
    use std::path::PathBuf;

    /// The version of the Metal Shading Language the source is written for: 2.1, the first with
    /// `[[invariant]]` positions (macOS 10.14, iOS 12), which the layers of a material drawn over
    /// the same triangles with `LessEqual` need.
    const LANGUAGE_VERSION: (u8, u8) = (2, 1);

    /// The argument table slots of the resources of the shader, the same in every function:
    /// `(name of the constant, group, binding, slot)`.
    const BUFFERS: [(&str, u32, u32, u8); 3] =
        [("FRAME_BUFFER_INDEX", 0, 0, 0), ("DRAW_BUFFER_INDEX", 1, 0, 1), ("BRUSH_BUFFER_INDEX", 1, 1, 2)];
    const TEXTURES: [(&str, u32, u32, u8); 2] =
        [("BRUSH_TEXTURE_INDEX", 2, 0, 0), ("RESOLVED_TEXTURE_INDEX", 0, 1, 1)];
    /// The buffer slot of the interleaved vertices: after the uniform buffers.
    const VERTEX_BUFFER_INDEX: u8 = 3;
    /// The sampler of the brush textures (group 2, binding 1), inlined into the functions:
    /// linear, the edges clamped, no mipmaps, as the wgpu executor's sampler.
    const SAMPLER: (u32, u32) = (2, 1);

    /// The constant naming the translated function of each entry point of the WGSL.
    const FUNCTIONS: [(&str, &str); 7] = [
        ("vs_main", "VERTEX_FUNCTION"),
        ("fs_main", "FRAGMENT_FUNCTION"),
        ("fs_gradient", "GRADIENT_FRAGMENT_FUNCTION"),
        ("fs_gradient_texture", "GRADIENT_TEXTURE_FRAGMENT_FUNCTION"),
        ("fs_image", "IMAGE_FRAGMENT_FUNCTION"),
        ("vs_resolve", "RESOLVE_VERTEX_FUNCTION"),
        ("fs_resolve", "RESOLVE_FRAGMENT_FUNCTION"),
    ];

    pub fn write() {
        let source = std::fs::read_to_string("shaders/scene3d.wgsl").expect("shaders/scene3d.wgsl is readable");
        let module = naga::front::wgsl::parse_str(&source)
            .unwrap_or_else(|error| panic!("scene3d.wgsl does not parse:\n{}", error.emit_to_string(&source)));
        let mut validator =
            naga::valid::Validator::new(naga::valid::ValidationFlags::all(), naga::valid::Capabilities::empty());
        let info = validator
            .validate(&module)
            .unwrap_or_else(|error| panic!("scene3d.wgsl is not valid:\n{}", error.emit_to_string(&source)));

        let mut resources = EntryPointResources::default();
        for (_, group, binding, slot) in BUFFERS {
            let target = BindTarget { buffer: Some(slot), ..BindTarget::default() };
            resources.resources.insert(ResourceBinding { group, binding }, target);
        }
        for (_, group, binding, slot) in TEXTURES {
            let target = BindTarget { texture: Some(slot), ..BindTarget::default() };
            resources.resources.insert(ResourceBinding { group, binding }, target);
        }
        resources.resources.insert(
            ResourceBinding { group: SAMPLER.0, binding: SAMPLER.1 },
            BindTarget { sampler: Some(BindSamplerTarget::Inline(0)), ..BindTarget::default() },
        );
        let mut options = Options {
            lang_version: LANGUAGE_VERSION,
            inline_samplers: vec![InlineSampler {
                address: [Address::ClampToEdge; 3],
                mag_filter: Filter::Linear,
                min_filter: Filter::Linear,
                ..InlineSampler::default()
            }],
            // A binding the table lacks is an error of the build, not invalid Metal.
            fake_missing_bindings: false,
            ..Options::default()
        };
        for entry_point in &module.entry_points {
            options.per_entry_point_map.insert(entry_point.name.clone(), resources.clone());
        }
        let (msl, translation) = naga::back::msl::write_string(&module, &info, &options, &PipelineOptions::default())
            .unwrap_or_else(|error| panic!("scene3d.wgsl cannot be written in MSL: {error}"));

        let mut rust = String::new();
        let _ = writeln!(rust, "// Generated by build.rs from shaders/scene3d.wgsl with naga.");
        let _ = writeln!(
            rust,
            "/// The Metal Shading Language source of `scene3d.wgsl` (version {}.{}).",
            LANGUAGE_VERSION.0, LANGUAGE_VERSION.1
        );
        let _ = writeln!(rust, r#"pub const SOURCE: &str = include_str!(concat!(env!("OUT_DIR"), "/scene3d.metal"));"#);
        let _ = writeln!(rust, "/// The Metal Shading Language version of [`SOURCE`], as (major, minor).");
        let (major, minor) = LANGUAGE_VERSION;
        let _ = writeln!(rust, "pub const LANGUAGE_VERSION: (u8, u8) = ({major}, {minor});");
        for (entry, constant) in FUNCTIONS {
            let index = module
                .entry_points
                .iter()
                .position(|entry_point| entry_point.name == entry)
                .unwrap_or_else(|| panic!("scene3d.wgsl has no entry point {entry}"));
            let name = translation.entry_point_names[index]
                .as_ref()
                .unwrap_or_else(|error| panic!("the entry point {entry} cannot be written in MSL: {error}"));
            let _ = writeln!(rust, "/// The function of the entry point `{entry}`.");
            let _ = writeln!(rust, "pub const {constant}: &str = {name:?};");
        }
        for (constant, group, binding, slot) in BUFFERS {
            let _ = writeln!(rust, "/// The buffer slot of `@group({group}) @binding({binding})`.");
            let _ = writeln!(rust, "pub const {constant}: usize = {slot};");
        }
        for (constant, group, binding, slot) in TEXTURES {
            let _ = writeln!(rust, "/// The texture slot of `@group({group}) @binding({binding})`.");
            let _ = writeln!(rust, "pub const {constant}: usize = {slot};");
        }
        let _ = writeln!(rust, "/// The buffer slot of the interleaved vertices (of the vertex descriptor).");
        let _ = writeln!(rust, "pub const VERTEX_BUFFER_INDEX: usize = {VERTEX_BUFFER_INDEX};");

        let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR is set by cargo"));
        std::fs::write(out.join("scene3d.metal"), msl).expect("OUT_DIR is writable");
        std::fs::write(out.join("scene3d_msl.rs"), rust).expect("OUT_DIR is writable");
    }
}
