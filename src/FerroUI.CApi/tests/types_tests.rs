//! The class entries (`api_types.rs`, docs/c-abi.md, section 16) are generated, never written by
//! hand: this test writes them from the API model (`bindings/model/ferroui-api.json`: the classes,
//! their IDs, entries, Rust paths and whether they have a default constructor) and the units of the Fluent
//! theme each class roots (the closure of the build tool, `ferroui_build::theme_roots`, over the
//! type models of the dependencies that the build script of the crate hands over), and compares
//! them with the file. With `FERROUI_CAPI_WRITE_TYPES=1` it writes the file instead.

#[cfg(feature = "desktop")]
use ferroui_build::model_set::ModelSet;
#[cfg(feature = "desktop")]
use ferroui_build::theme_roots::{kept_units, Roots, TypeGraph};
use std::collections::BTreeSet;
#[cfg(feature = "desktop")]
use std::fmt::Write as _;
use std::path::Path;
#[cfg(feature = "desktop")]
use std::path::PathBuf;

/// The module of the static units of the Fluent theme (`THEME_UNIT_<index>`).
#[cfg(feature = "desktop")]
const UNITS_MODULE: &str = "::ferroui_themes_fluent::compiled_xaml";

/// A class of the model with an entry.
#[allow(dead_code)]
struct Class {
    id: i64,
    name: String,
    entry: String,
    rust_path: String,
    creatable: bool,
}

fn classes() -> Vec<Class> {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../bindings/model/ferroui-api.json");
    let text = std::fs::read_to_string(&path).expect("the API model");
    let model: serde_json::Value = serde_json::from_str(&text).expect("the API model is JSON");
    let mut classes = Vec::new();
    for class in model["classes"].as_array().expect("the classes") {
        // The model names the entry of a class of a crate of the library (`generate_api_model.py`).
        let Some(entry) = class["entry"].as_str() else { continue };
        classes.push(Class {
            id: class["id"].as_i64().expect("id"),
            name: class["name"].as_str().expect("name").to_string(),
            entry: entry.to_string(),
            rust_path: class["rust_path"].as_str().expect("the Rust path of a class with an entry").to_string(),
            creatable: class["creatable"].as_bool().unwrap_or(false),
        });
    }
    classes
}

#[cfg(feature = "desktop")]
/// The units of the Fluent theme: the ambient ones (what the theme keeps for no root) and the
/// ones each class adds to them, by class name.
struct Units {
    ambient: Vec<u32>,
    of_class: Vec<Vec<u32>>,
}

#[cfg(feature = "desktop")]
fn units(classes: &[Class]) -> Units {
    let paths: Vec<PathBuf> = std::env::split_paths(env!("FERROUI_CAPI_XAMLMETA")).collect();
    let (models, _) = ModelSet::read(&paths).expect("the type models of the dependencies");
    let metadata: Vec<_> = models.iter().map(|model| model.metadata()).collect();
    let theme = metadata
        .iter()
        .flat_map(|metadata| metadata.theme_units.iter())
        .find(|units| units.class.ends_with(".FluentTheme"))
        .expect("the units of the Fluent theme (the desktop feature)");
    let module = theme.table_path.rsplit_once("::").map_or("", |(module, _)| module);
    assert_eq!(module, UNITS_MODULE, "the units of the Fluent theme moved");
    let graph = TypeGraph::from_models(&models);
    let ambient = kept_units(theme, &Roots::default(), &graph, false);
    let of_class = classes
        .iter()
        .map(|class| {
            let roots = Roots { types: BTreeSet::from([class.name.clone()]), ..Roots::default() };
            kept_units(theme, &roots, &graph, false).into_iter().filter(|unit| !ambient.contains(unit)).collect()
        })
        .collect();
    Units { ambient, of_class }
}

#[cfg(feature = "desktop")]
fn unit_list(units: &[u32]) -> String {
    let names: Vec<String> = units.iter().map(|unit| format!("THEME_UNIT_{unit}")).collect();
    format!("units!({})", names.join(", "))
}

#[cfg(feature = "desktop")]
fn generated() -> String {
    let classes = classes();
    let units = units(&classes);
    let mut text = String::new();
    text.push_str(
        "// @generated by tests/types_tests.rs from the API model and the units of the Fluent theme: do not edit.\n\
         //! The entries of the classes of the API model (docs/c-abi.md, section 16): `ferro_type_<class>()`\n\
         //! registers the class, its default constructor and the units of the Fluent theme it adds to the\n\
         //! ambient ones, and returns its type ID ([`crate::types`]). Write the file again with\n\
         //! `FERROUI_CAPI_WRITE_TYPES=1 cargo test -p ferroui-capi --lib types`.\n\
         \n\
         use crate::types::{entry, entry_static, Units};\n\
         \n\
         /// Static units of the Fluent theme, by name; none without the desktop platform.\n\
         #[cfg(feature = \"desktop\")]\n\
         macro_rules! units {\n\
         \x20   ($($unit:ident),*) => {{\n\
         \x20       static UNITS: Units = &[$(&::ferroui_themes_fluent::compiled_xaml::$unit),*];\n\
         \x20       UNITS\n\
         \x20   }};\n\
         }\n\
         \n\
         /// Static units of the Fluent theme, by name; none without the desktop platform.\n\
         #[cfg(not(feature = \"desktop\"))]\n\
         macro_rules! units {\n\
         \x20   ($($unit:ident),*) => {\n\
         \x20       &[]\n\
         \x20   };\n\
         }\n\
         \n\
         /// The units of the Fluent theme that no class roots: the structure of the theme and what it\n\
         /// applies to every window.\n\
         #[allow(dead_code)]\n",
    );
    let _ = writeln!(text, "pub(crate) static AMBIENT_UNITS: Units = {};", unit_list(&units.ambient));
    for (class, units) in classes.iter().zip(&units.of_class) {
        let what = if class.creatable { "with its default constructor" } else { "without a constructor" };
        let function = if class.creatable { "entry" } else { "entry_static" };
        let _ = write!(
            text,
            "\n/// Registers `{name}` ({what}) and returns its type ID, {id}.\n\
             #[no_mangle]\n\
             pub extern \"C\" fn {entry}() -> i64 {{\n\
             \x20   {function}::<::{path}>({id}, {units})\n\
             }}\n",
            name = class.name,
            id = class.id,
            entry = class.entry,
            path = class.rust_path,
            units = unit_list(units),
        );
    }
    text
}

// The units come from the Fluent theme, a dependency of the desktop platform only.
#[cfg(feature = "desktop")]
#[test]
fn the_entries_are_up_to_date() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("api_types.rs");
    let text = generated();
    if std::env::var_os("FERROUI_CAPI_WRITE_TYPES").is_some() {
        std::fs::write(&path, &text).expect("api_types.rs is written");
        return;
    }
    let current = std::fs::read_to_string(&path).unwrap_or_default().replace("\r\n", "\n");
    assert!(
        current == text,
        "api_types.rs is not the one of the API model: write it again with \
         FERROUI_CAPI_WRITE_TYPES=1 cargo test -p ferroui-capi --lib types"
    );
}

#[test]
fn the_entries_have_names_of_their_own() {
    let mut names = BTreeSet::from(["ferro_type_id".to_string(), "ferro_type_of".to_string()]);
    for class in classes() {
        assert!(names.insert(class.entry.clone()), "two functions are named {}", class.entry);
    }
}

#[test]
fn an_entry_registers_its_class() {
    super::support::ui(|| {
        let id = crate::api_types::ferro_type_button();
        assert!(id > 0, "the ID of Button");
        let name = c"Button";
        // SAFETY: a NUL-terminated name.
        assert_eq!(unsafe { crate::ferro_type_id(name.as_ptr(), -1) }, id, "the entry returns the ID of the model");
        let button = crate::ferro_create(id);
        assert!(button != 0, "a button is created from the ID of its entry");
        crate::ferro_release(button);
    });
}

#[test]
fn the_selection_fingerprint_is_the_one_of_the_build() {
    let expected = option_env!("FERROUI_CAPI_SELECTION").map_or(0, |text| text.parse::<i64>().expect("a number"));
    assert_eq!(crate::ferro_selection_fingerprint(), expected, "0 for a library of every class");
    for (text, value) in [("0", 0), ("42", 42), ("-6457349082854047077", -6457349082854047077), ("-9223372036854775808", i64::MIN)] {
        assert_eq!(crate::ids::parse_i64(text.as_bytes()), value, "{text}");
    }
}
