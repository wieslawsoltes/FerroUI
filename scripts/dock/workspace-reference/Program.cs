using System.Text;

// Capture the actual ordinal equivalence, without reflection or culture-sensitive folding.
if (args.Length != 2) throw new ArgumentException("Pass the Rust table and reference corpus paths.");
using StreamWriter writer = new(args[0]);
writer.WriteLine("// Generated by scripts/dock/workspace-reference using .NET " + Environment.Version + ".");
writer.WriteLine("// Unicode scalar simple-uppercase mappings accepted by OrdinalIgnoreCase.");
writer.WriteLine("pub(super) const ORDINAL_UPPER: &[(u32, u32)] = &[");
for (int code = 0; code <= 0x10FFFF; code++)
{
    if (!Rune.IsValid(code)) continue;
    Rune value = new(code);
    Rune upper = Rune.ToUpperInvariant(value);
    if (value != upper && StringComparer.OrdinalIgnoreCase.Equals(value.ToString(), upper.ToString()))
        writer.WriteLine($"    (0x{code:X}, 0x{upper.Value:X}),");
}
writer.WriteLine("];");

using StreamWriter corpus = new(args[1]);
corpus.WriteLine("# .NET " + Environment.Version + " OrdinalIgnoreCase independent comparison corpus; UTF-8 hex left\tright\tequal");
void Pair(string left, string right)
{
    corpus.WriteLine(Convert.ToHexString(Encoding.UTF8.GetBytes(left)) + "\t" + Convert.ToHexString(Encoding.UTF8.GetBytes(right)) + "\t" + (StringComparer.OrdinalIgnoreCase.Equals(left, right) ? "1" : "0"));
}
for (int code = 0; code <= 0x10FFFF; code++)
{
    if (!Rune.IsValid(code)) continue;
    Rune value = new(code);
    Rune upper = Rune.ToUpperInvariant(value);
    Rune lower = Rune.ToLowerInvariant(value);
    if (upper != value) Pair(value.ToString(), upper.ToString());
    if (lower != value) Pair(value.ToString(), lower.ToString());
}
