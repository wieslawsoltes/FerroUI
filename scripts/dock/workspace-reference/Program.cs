    ("I", "ı"), ("i", "İ"), ("s", "ſ"), ("k", "K"), ("ß", "SS"), ("ß", "ẞ"),
    ("ﬀ", "FF"), ("é", "e\u0301"), ("σ", "ς"), ("𐐀", "𐐨"), ("µ", "Μ"),
    ("Layout-École-𐐀", "lAYOUT-éCOLE-𐐨"), (" A ", "a"), ("A\0B", "a\0b")
}) Pair(pair.Item1, pair.Item2);
