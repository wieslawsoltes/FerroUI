#!/usr/bin/env python3
"""Converts the upstream OpenGL constant table (C#) to Rust.

Upstream (Avalonia, MIT) keeps the constants it uses in
``src/Avalonia.OpenGL/GlConsts.cs``: a transcription of the Khronos headers in
which every constant the framework does not use is commented out. This script
transliterates the active constants, in upstream order, into
``src/FerroUI.OpenGL/gl_consts.rs``.

Usage:
    scripts/convert-gl-consts.py <upstream checkout> [--check]

With ``--check`` nothing is written; the exit status tells whether the Rust
file is up to date.
"""
import re
import sys
from pathlib import Path

HEADER = """// Generated by scripts/convert-gl-consts.py from the upstream constant table;
// do not edit by hand.

//! The OpenGL constants used by the framework.
//!
//! This is not the full set of the Khronos headers: only the constants the
//! framework itself needs are present.

"""

LINE = re.compile(r"^\s*(public|internal) const int ([A-Za-z0-9_]+) = (0x[0-9A-Fa-f]+|-?[0-9]+);\s*$")


def convert(source: str) -> str:
    out = [HEADER]
    for line in source.splitlines():
        match = LINE.match(line)
        if match:
            out.append(f"pub const {match.group(2)}: i32 = {match.group(3)};\n")
    return "".join(out)


def main() -> int:
    args = [a for a in sys.argv[1:] if a != "--check"]
    check = "--check" in sys.argv[1:]
    if len(args) != 1:
        print(__doc__)
        return 2
    upstream = Path(args[0]) / "src" / "Avalonia.OpenGL" / "GlConsts.cs"
    target = Path(__file__).resolve().parent.parent / "src" / "FerroUI.OpenGL" / "gl_consts.rs"
    text = convert(upstream.read_text(encoding="utf-8-sig"))
    if check:
        return 0 if target.exists() and target.read_text(encoding="utf-8") == text else 1
    target.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
