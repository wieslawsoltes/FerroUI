#!/usr/bin/env python3
"""Generate the loader's exact, inheritance-aware WinUI event target table.

This consumes the pinned public API snapshot, works offline, and never treats a
same-named custom property as an event. Run --check in CI after scan.py --check.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MODEL = ROOT / "docs/porting/winui-gallery/data/upstream-api.json"
OUTPUT = ROOT / "src/Markup/FerroUI.Markup.Xaml.Loader/winui/event_targets.rs"
PRESENTATION = "http://schemas.microsoft.com/winfx/2006/xaml/presentation"
DEFAULT_NAMESPACES = (
    "Microsoft.UI.Xaml.Controls", "Microsoft.UI.Xaml.Controls.Primitives",
    "Microsoft.UI.Xaml", "Microsoft.UI.Xaml.Shapes", "Microsoft.UI.Xaml.Documents",
    "Microsoft.UI.Xaml.Media", "Microsoft.UI.Xaml.Media.Animation", "Microsoft.UI.Xaml.Input",
)


def rows(model: dict) -> list[tuple[str, str, tuple[str, ...]]]:
    return sorted((entry["id"], entry.get("base") or "", tuple(sorted({
        member["name"] for member in entry["members"] if member["kind"] == "event"
    }))) for entry in model["types"]
        if entry["audience"] == "public-source" and entry["id"].startswith("Microsoft.UI.Xaml."))


def is_event(table: list[tuple[str, str, tuple[str, ...]]], namespace: str, name: str, member: str) -> bool:
    index = {identity: (base, events) for identity, base, events in table}
    namespaces = DEFAULT_NAMESPACES if namespace == PRESENTATION else (namespace.removeprefix("using:"),)
    candidates = [f"{ns}.{name}" for ns in namespaces if f"{ns}.{name}" in index]
    if len(candidates) != 1:
        return False
    current = candidates[0]
    seen = set()
    while current in index and current not in seen:
        seen.add(current)
        current, events = index[current]
        if member in events:
            return True
    return False


def render(raw: bytes) -> str:
    table = rows(json.loads(raw))
    quote = lambda value: json.dumps(value, ensure_ascii=True)
    result = [
        "// Generated by scripts/winui-gallery/event_targets.py; do not edit.",
        "// Public pinned WinUI declaration data; names alone never prove behavioral parity.",
        f"// upstream-api.json SHA256: {hashlib.sha256(raw).hexdigest()}",
        "",
        "const TYPES: &[(&str, &str, &[&str])] = &[",
    ]
    result.extend(f"    ({quote(identity)}, {quote(base)}, &[{', '.join(map(quote, events))}]),"
                  for identity, base, events in table)
    result += ["];", "", "const DEFAULT_NAMESPACES: &[&str] = &["]
    result.extend(f"    {quote(namespace)}," for namespace in DEFAULT_NAMESPACES)
    result += ["];"]
    result.append(r'''
fn find(id: &str) -> Option<&'static (&'static str, &'static str, &'static [&'static str])> {
    TYPES.binary_search_by(|entry| entry.0.cmp(id)).ok().map(|index| &TYPES[index])
}

/// Recognizes only public events on a known, unambiguous WinUI owner or its bases.
pub(super) fn is_event(namespace: &str, type_name: &str, member: &str) -> bool {
    let owner = if namespace == "http://schemas.microsoft.com/winfx/2006/xaml/presentation" {
        let mut candidates = DEFAULT_NAMESPACES.iter()
            .filter_map(|namespace| find(&format!("{namespace}.{type_name}")));
        let first = candidates.next();
        if candidates.next().is_some() { return false; }
        first
    } else {
        find(&format!("{}.{}", namespace.strip_prefix("using:").unwrap_or(namespace), type_name))
    };
    let mut current = owner;
    // A finite bound also makes a malformed cyclic source hierarchy fail closed.
    for _ in 0..TYPES.len() {
        let Some((_, base, events)) = current else { return false; };
        if events.binary_search(&member).is_ok() { return true; }
        current = find(base);
    }
    false
}
'''.strip("\n"))
    return "\n".join(result) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render(MODEL.read_bytes())
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            parser.exit(1, "WinUI event target table is stale; run scripts/winui-gallery/event_targets.py\n")
    else:
        OUTPUT.write_text(expected)
    table = rows(json.loads(MODEL.read_bytes()))
    print(f"WinUI event targets: {len(table)} public types, {sum(len(row[2]) for row in table)} direct events; {'verified' if args.check else 'generated'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
