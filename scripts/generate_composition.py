class TypeInfo:
    """GeneratorTypeInfo (Generator.ConfigHelpers.cs), in Rust terms."""

    def __init__(self, gen, type_name):
        filtered = type_name.rstrip("?")
        self.schema_type = type_name
        self.filtered_type_name = filtered
        self.is_nullable = type_name.endswith("?")
        self.is_object = filtered in gen.objects
        manual = gen.manuals.get(filtered)
        self.is_passthrough = manual is not None and manual.passthrough
        self.imports = []
        self.server_imports = []
        self.cast = None
        if self.is_object and not self.is_passthrough:
            self.kind = "object"
            self.client_type = "Option<Rc<dyn ICompositionObject>>"
            self.server_type = "Option<Rc<dyn IServerObject>>"
            self.imports = ["std::rc::Rc", COMPOSITION + "::ICompositionObject"]
            self.server_imports = ["std::rc::Rc", COMPOSITION + "::server::IServerObject"]
            return
        if filtered not in TYPES:
            raise SystemExit("schema type %r is not in the TYPES table of the generator" % filtered)
        entry = TYPES[filtered]
        self.kind = entry[0]
        self.imports = list(entry[2])
        self.server_imports = list(entry[2])
        if self.kind in ("value", "boxed"):
            self.client_type = self.server_type = entry[1]
        elif self.kind == "payload":
            self.client_type = self.server_type = "Option<%s>" % entry[1]
        elif self.kind == "resource":
            self.cast = entry[3]
            self.client_type = "Option<BatchResource<%s>>" % entry[1]
            self.server_type = "Option<ServerResourceRef<%s>>" % entry[1]
            self.imports.append(COMPOSITION + "::transport::BatchResource")
            self.server_imports.append(COMPOSITION + "::server::ServerResourceRef")
        else:
            raise SystemExit("unknown kind %r" % self.kind)

    @property
    def is_copy(self):
        return self.kind in ("value", "boxed")


