class Unit:
    """One generated file: collects imports while code is emitted."""

    def __init__(self):
        self.imports = set()
        self.lines = []

    def use(self, *paths):
        for path in paths:
            self.imports.add(path)

    def emit(self, text=""):
        self.lines.extend(text.split("\n"))

    def render(self, doc):
        out = [HEADER.rstrip("\n")]
        out.append("")
        out.extend("//! " + line if line else "//!" for line in doc)
        out.append("")
        for path in sorted(self.imports):
            out.append("use %s;" % path)
        if self.imports:
            out.append("")
        body = self.lines
        while body and body[-1] == "":
            body = body[:-1]
        out.extend(body)
        return "\n".join(line.rstrip() for line in out) + "\n"


