def snake(name):
    s = re.sub(r"([a-z])([A-Z])", r"\1_\2", name)
    s = re.sub(r"([A-Z0-9]+)([A-Z][a-z])", r"\1_\2", s)
    return s.lower()


def screaming(name):
    return snake(name).upper()


def server_name(c):
    return ("Server" + c) if c is not None else "ServerObject"


def changed_fields_type_name(cl):
    return cl.name + "ChangedFields"


def changed_fields_field_name(cl):
    return "changed_fields_of_" + snake(cl.name)


