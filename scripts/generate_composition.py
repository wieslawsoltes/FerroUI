#!/usr/bin/env python3
"""Generates the composition object model of FerroUI from the composition schema.

This is the port of the upstream generator
(src/tools/DevGenerators/CompositionGenerator/*.cs in Avalonia: Generator.cs,
Config.cs, Generator.ListProxy.cs, Generator.KeyFrameAnimation.cs,
Generator.Utils.cs, Generator.ConfigHelpers.cs, Extensions.cs). It reads
scripts/composition-schema.xml (a verbatim copy of upstream
src/Avalonia.Base/composition-schema.xml) and writes one Rust file per schema
class, plus composition_animations.rs and mod.rs, under
src/FerroUI.Base/rendering/composition/generated/.

How to rerun (from the repository root; Python 3, standard library only):

    python3 scripts/generate_composition.py

Options:
    --check     do not write; exit with status 1 if a generated file is stale
    --schema P  read the schema from P instead of scripts/composition-schema.xml
    --out D     write to directory D instead of the default

The output is deterministic: it depends only on the schema and this script.
Files in the output directory that the generator no longer produces are
removed.

Where upstream emits C# partial classes, this generator emits, per schema
class X, "property blocks" that a hand-written class embeds:

    XChangedFields        the changed-fields bit mask (upstream XChangedFields)
    XHooks / XProps       the UI-thread half (not for ServerOnly classes)
    ServerXHooks / ServerXProps
                          the server half

See the documentation at the top of the generated mod.rs for the contract.

Tables in this script that carry what upstream takes from the C# type system:

    TYPES            how each schema type maps to Rust and crosses a batch
    UNPORTED_TYPES   schema types that have no Rust counterpart yet; their
                     properties are skipped (the changed-fields bit stays
                     reserved) and listed in the generated file
    DEFAULTS         the DefaultValue expressions of the schema, in Rust
    SERVER_BASES     hand-written server base classes named by ServerBase /
                     Inherits, and whether they derive from ServerObject
"""

