def _bool(element, name):
    return element.get(name, "false").strip().lower() == "true"


class GManualClass:
    def __init__(self, element):
        self.name = element.get("Name")
        self.passthrough = _bool(element, "Passthrough")
        self.server_name = element.get("ServerName")


class GImplements:
    def __init__(self, element):
        self.name = element.get("Name")
        self.server_name = element.get("ServerName")


class GProperty:
    def __init__(self, element):
        self.name = element.get("Name")
        self.client_name = element.get("ClientName")
        self.type = element.get("Type")
        self.default_value = element.get("DefaultValue")
        self.animated = _bool(element, "Animated")
        self.internal_set = _bool(element, "InternalSet")
        self.internal = _bool(element, "Internal")
        self.private = _bool(element, "Private")


class GClass:
    def __init__(self, element):
        self.name = element.get("Name")
        self.inherits = element.get("Inherits")
        self.changes_base = element.get("ChangesBase")
        self.server_base = element.get("ServerBase")
        self.custom_ctor = _bool(element, "CustomCtor")
        self.custom_server_ctor = _bool(element, "CustomServerCtor")
        self.internal = _bool(element, "Internal")
        self.server_only = _bool(element, "ServerOnly")
        self.abstract = _bool(element, "Abstract")
        self.implements = [GImplements(e) for e in element.findall("Implements")]
        self.properties = [GProperty(e) for e in element.findall("Property")]
        self.is_list = element.tag == "List"
        self.item_type = element.get("ItemType")
        if element.tag == "Brush":
            # GBrush
            self.custom_update = _bool(element, "CustomUpdate")
            self.inherits = "CompositionBrush"


class GAnimationType:
    def __init__(self, element):
        self.name = element.get("Name")
        self.type = element.get("Type")


class GConfig:
    def __init__(self, path):
        root = ET.parse(path).getroot()
        if root.tag != "NComposition":
            raise SystemExit("the schema root element must be NComposition")
        self.usings = [e.text for e in root.findall("Using")]
        self.manual_classes = [GManualClass(e) for e in root.findall("Manual")]
        # Document order across the three element kinds, like the XML
        # serializer of the reference.
        self.classes = [GClass(e) for e in root if e.tag in ("Object", "Brush", "List")]
        self.key_frame_animations = [GAnimationType(e) for e in root.findall("KeyFrameAnimation")]


