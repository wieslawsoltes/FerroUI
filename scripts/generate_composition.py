        unit.use(COMPOSITION + "::server::ServerPropertyValue")

        unit.emit()
        unit.emit("    /// " + doc)
        unit.emit("    pub fn %s(&self) -> %s {" % (accessor, info.client_type))
        unit.emit("        " + self.field_get(info, field))
        unit.emit("    }")
        unit.emit()
        unit.emit("    /// Sets " + doc)
        unit.emit("    pub fn set_%s(&self, host: &dyn %s, value: %s) {" % (accessor, hooks, info.client_type))
        unit.emit("        let mut changed = false;")
        unit.emit("        let old_value = %s;" % self.field_get(info, field))
        unit.emit("        if old_value.differs(&value) {")
        if info.is_copy:
            unit.emit("            %s::validate_%s_change(host, old_value, value);" % (hooks, field))
        else:
            unit.emit("            %s::validate_%s_change(host, &old_value, &value);" % (hooks, field))
        unit.emit("            %s::on_%s_changing(host);" % (hooks, field))
        unit.emit("            changed = true;")
        unit.emit("            // Update the backing value")
        unit.emit("            " + self.field_set(info, field, "value" if info.is_copy else "value.clone()"))
        unit.emit("            // Register object for serialization in the next batch")
        unit.emit("            self.%s.set(self.%s.get() | %s::%s);" % (changed_field, changed_field, changed_type, flag))
        unit.emit("            host.register_for_serialization();")
        if prop.animated:
            unit.use(COMPOSITION + "::expressions::ExpressionVariant")
