class Generator:
    def __init__(self, config):
        self.config = config
        self.manuals = {m.name: m for m in config.manual_classes}
        self.objects = set(m.name for m in config.manual_classes) | set(c.name for c in config.classes)
        self.brushes = set(c.name for c in config.classes if hasattr(c, "custom_update")) | {"CompositionBrush"}
        self.classes = {c.name: c for c in config.classes}
        self.type_info_cache = {}
        self.files = {}
        self.skipped = []

    def get_type_info(self, type_name):
        if type_name not in self.type_info_cache:
            self.type_info_cache[type_name] = TypeInfo(self, type_name)
        return self.type_info_cache[type_name]

    # ---- class graph ----------------------------------------------------

    def props_of(self, cl):
        """The properties of a class that are generated."""
        return [p for p in cl.properties if p.type.rstrip("?") not in UNPORTED_TYPES]

    def client_base(self, cl):
        """(kind, name): 'none', 'generated' (embedded) or 'manual'."""
        if cl.inherits is None:
            return ("none", None)
        base = self.classes.get(cl.inherits)
        if base is not None and not base.server_only:
            return ("generated", base)
        return ("manual", cl.inherits)

    def server_base(self, cl):
        """(kind, value): 'root', 'list', 'generated' (embedded) or 'manual'."""
        if cl.is_list:
            return ("list", server_name(cl.item_type))
        name = cl.server_base or server_name(cl.inherits)
        if name in SERVER_ROOTS:
            return ("root", name)
        if name.startswith("Server") and name[len("Server"):] in self.classes:
            return ("generated", self.classes[name[len("Server"):]])
        if name not in SERVER_BASES:
            raise SystemExit("server base %r of %s is not in the SERVER_BASES table" % (name, cl.name))
        return ("manual", name)

    def server_is_animated(self, cl):
        """Whether the server class derives from ServerObject."""
        kind, value = self.server_base(cl)
        if kind == "list":
            return True
        if kind == "generated":
            return self.server_is_animated(value)
        return SERVER_BASES[value]

    def has_start_animation(self, cl):
        if any(p.animated for p in self.props_of(cl)):
            return True
        kind, base = self.client_base(cl)
        return kind == "generated" and self.has_start_animation(base)

    def variant_props(self, cl):
        return [p for p in self.props_of(cl) if p.type in VARIANT_PROPERTY_TYPES]

    def has_get_composition_property(self, cl):
        if cl.server_only:
            return False
        if self.variant_props(cl):
            return True
        kind, base = self.server_base(cl)
        return kind == "generated" and self.has_get_composition_property(base)

    # ---- entry point ----------------------------------------------------

    def generate(self):
        for cl in self.config.classes:
            self.generate_class(cl)
        self.generate_animations()
        self.generate_mod()
        return self.files

    # ---- changed fields enum --------------------------------------------

    def generate_changed_fields_enum(self, unit, cl):
        name = changed_fields_type_name(cl)
        values = []
        for prop in cl.properties:
            values.append(prop.name)
            if prop.animated:
                values.append(prop.name + "Animated")
        count = len(values)
        base_type = "u8" if count <= 8 else "u16" if count <= 16 else "u32" if count <= 32 else "u64"
        unit.use("bitflags::bitflags", COMPOSITION + "::transport::BatchValue", COMPOSITION + "::transport::BatchValueReader")
        unit.emit("bitflags! {")
        unit.emit("    /// The fields of `%s` that changed since its last serialization." % cl.name)
        unit.emit("    #[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]")
        unit.emit("    pub struct %s: %s {" % (name, base_type))
        for index, value in enumerate(values):
            unit.emit("        const %s = %d;" % (screaming(value), 1 << index))
        unit.emit("    }")
        unit.emit("}")
        unit.emit()
        unit.emit("impl BatchValue for %s {" % name)
        unit.emit("    #[inline]")
        unit.emit("    fn write_to(&self, out: &mut Vec<u8>) {")
        unit.emit("        self.bits().write_to(out);")
        unit.emit("    }")
        unit.emit()
        unit.emit("    #[inline]")
        unit.emit("    fn read_from(input: &mut BatchValueReader<'_>) -> Self {")
        unit.emit("        %s::from_bits_retain(%s::read_from(input))" % (name, base_type))
        unit.emit("    }")
        unit.emit("}")
        unit.emit()

    # ---- field access snippets ------------------------------------------

    @staticmethod
    def field_decl(info, type_name):
        return ("Cell<%s>" if info.is_copy else "RefCell<%s>") % type_name

    @staticmethod
    def field_get(info, field):
        return ("self.%s.get()" if info.is_copy else "self.%s.borrow().clone()") % field

    @staticmethod
    def field_set(info, field, value):
        if info.is_copy:
            return "self.%s.set(%s);" % (field, value)
        return "*self.%s.borrow_mut() = %s;" % (field, value)

    @staticmethod
    def field_init(info):
        return "Cell::new(Default::default())" if info.is_copy else "RefCell::new(None)"

    def default_value(self, prop):
        key = (prop.type.rstrip("?"), prop.default_value)
        if key not in DEFAULTS:
            raise SystemExit("default value %r of type %r is not in the DEFAULTS table" % (prop.default_value, prop.type))
        return DEFAULTS[key]

    # ---- class ----------------------------------------------------------

    def generate_class(self, cl):
        unit = Unit()
        props = self.props_of(cl)
        skipped = [p for p in cl.properties if p.type.rstrip("?") in UNPORTED_TYPES]
        for prop in skipped:
            self.skipped.append((cl.name, prop.name, prop.type, UNPORTED_TYPES[prop.type.rstrip("?")]))

        if cl.properties:
            self.generate_changed_fields_enum(unit, cl)
        if not cl.server_only:
            if cl.is_list:
                self.generate_client_list(unit, cl)
            else:
                self.generate_client(unit, cl, props)
        self.generate_server(unit, cl, props)

        doc = ["`%s`%s." % (cl.name, " (server only)" if cl.server_only else "")]
        notes = []
        if cl.abstract:
            notes.append("abstract")
        if cl.internal:
            notes.append("internal")
        if cl.custom_ctor:
            notes.append("custom constructor on the UI thread")
        if cl.custom_server_ctor:
            notes.append("custom constructor on the server")
        if cl.changes_base:
            notes.append("changes base `%s`" % cl.changes_base)
        if notes:
            doc += ["", "Schema attributes: " + ", ".join(notes) + "."]
        for impl in cl.implements:
            doc += ["", "Implements `%s`%s." % (impl.name, (" (server: `%s`)" % impl.server_name) if impl.server_name else "")]
        for prop in skipped:
            doc += ["", "Skipped property `%s`: %s." % (prop.name, UNPORTED_TYPES[prop.type.rstrip("?")])]
        self.files[snake(cl.name) + ".rs"] = unit.render(doc)

    # ---- client ---------------------------------------------------------

    def client_property_ref(self, unit, cl, prop):
        """ClientProperty(cl, p): the composition property of the server class."""
        return "%sProps::id_of_%s_property().base()" % (server_name(cl.name), snake(prop.name))

    def generate_client(self, unit, cl, props):
        name = cl.name
        hooks = name + "Hooks"
        struct = name + "Props"
        changed_type = changed_fields_type_name(cl)
        changed_field = changed_fields_field_name(cl)
        base_kind, base = self.client_base(cl)
        has_changed = bool(cl.properties)
        animated = [p for p in props if p.animated]

        unit.use(COMPOSITION + "::transport::BatchStreamWriter")

        # --- hooks trait
        if base_kind == "generated":
            supertrait = base.name + "Hooks"
            unit.use("super::%sHooks" % base.name, "super::%sProps" % base.name)
        else:
            supertrait = "ICompositionObjectHost"
            unit.use(COMPOSITION + "::ICompositionObjectHost")
        unit.emit("/// The partial methods of `%s`: implemented by the class that embeds" % name)
        unit.emit("/// [`%s`]. Every hook defaults to doing nothing." % struct)
        unit.emit("pub trait %s: %s {" % (hooks, supertrait))
        if base_kind == "manual":
            unit.emit("    /// `base.SerializeChangesCore(writer)`: serializes the changes of the")
            unit.emit("    /// hand-written base class `%s`." % base)
            unit.emit("    fn base_serialize_changes_core(&self, writer: &mut BatchStreamWriter<'_>);")
            unit.emit()
        unit.emit("    fn initialize_defaults_extra(&self) {}")
        for prop in props:
            info = self.get_type_info(prop.type)
            unit.use(*info.imports)
            pname = snake(prop.name)
            arg = info.client_type if info.is_copy else "&" + info.client_type
            unit.emit()
            unit.emit("    fn validate_%s_change(&self, _old_value: %s, _new_value: %s) {}" % (pname, arg, arg))
            unit.emit("    fn on_%s_changed(&self) {}" % pname)
            unit.emit("    fn on_%s_changing(&self) {}" % pname)
        unit.emit("}")
        unit.emit()

        # --- struct
        unit.emit("/// The UI-thread properties of `%s`." % name)
        unit.emit("pub struct %s {" % struct)
        if base_kind == "generated":
            unit.emit("    base: %sProps," % base.name)
        if has_changed:
            unit.use("std::cell::Cell")
            unit.emit("    %s: Cell<%s>," % (changed_field, changed_type))
        for prop in props:
            info = self.get_type_info(prop.type)
