#!/usr/bin/env python3
"""Generate inking string tables from the pinned WinUI Resources.resw files.

Usage: generate-strings.py <microsoft-ui-xaml checkout> [--check]
The source commit is recorded in docs/porting/data/winui-inking/source-map.json.
"""
import argparse
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("source", type=Path)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
root = Path(__file__).resolve().parents[2]
manifest = json.loads((root / "docs/porting/data/winui-inking/source-map.json").read_text())
commit = "7e4b0c2096be402f51cc8f7d203ebf67cff183d0"
if manifest.get("commit") != commit:
    raise SystemExit("The source ledger revision differs from this generator's pinned commit")
expected = {entry["path"]: entry for entry in manifest["files"] if entry["category"] == "localization"}
source = args.source / "controls/dev/InkToolbar/Strings"
files = sorted(source.glob("*/Resources.resw"), key=lambda path: path.parent.name.lower())
if len(files) != 86 or len(expected) != 86:
    raise SystemExit(f"Expected 86 pinned localization files, found {len(files)}")
actual = {path.relative_to(args.source).as_posix() for path in files}
if actual != expected.keys():
    raise SystemExit(f"Localization paths differ from the source ledger: {sorted(actual ^ expected.keys())}")
for path in files:
    name = path.relative_to(args.source).as_posix()
    contents = path.read_bytes()
    blob_sha = hashlib.sha1(b"blob " + str(len(contents)).encode("ascii") + b"\0" + contents).hexdigest()
    entry = expected[name]
    if len(contents) != entry["size"] or blob_sha != entry["sha"]:
        raise SystemExit(f"Pinned source mismatch: {name}\nExpected {entry['sha']} ({entry['size']} bytes), got {blob_sha} ({len(contents)} bytes)")
lines = [
    "// Generated by scripts/winui-inking/generate-strings.py; do not edit.",
    "// Source: microsoft-ui-xaml 7e4b0c2096be402f51cc8f7d203ebf67cff183d0, InkToolbar/Strings.",
    "// Copyright (c) Microsoft Corporation. MIT license; see NOTICE.md.",
    "#[rustfmt::skip]",
    "pub(super) const CULTURES: &[(&str, &[(&str, &str)])] = &[",
]
entry_count = 0
for path in files:
    entries = sorted((entry.attrib["name"], entry.findtext("value") or "") for entry in ET.parse(path).findall("data"))
    lines.append(f'    ({json.dumps(path.parent.name.lower())}, &[')
    for key, value in entries:
        lines.append(f"        ({json.dumps(key)}, {json.dumps(value, ensure_ascii=False)}),")
    lines.append("    ]),")
    entry_count += len(entries)
lines.append("];")
output = "\n".join(lines) + "\n"
target = root / "src/FerroUI.Controls.Inking/ink_toolbar_strings_data.rs"
if args.check:
    if not target.exists() or target.read_text() != output:
        raise SystemExit("InkToolbar string tables differ; rerun generator")
else:
    target.write_text(output)
print(f"{len(files)} pinned source blobs, {entry_count} localized entries: {'verified' if args.check else 'generated'}")
