#!/usr/bin/env python3
"""Generates the mechanical part of the markup metadata of FerroUI.Base and
FerroUI.Controls (the `markup_types/` module of each crate).

The managed original answers markup's questions with reflection; the port
states the answers as declarations (see "Markup metadata" in
docs/porting/PORTING-GUIDE.md). Most of them follow mechanically from the
upstream C# sources and the Rust sources, so this script derives them by
comparing the two:

    target        generated file (per crate)             from
    ------        --------------------------             ----
    enums         markup_types/enums.rs                  every public enum / bitflags type of the crate that
                                                         upstream declares public, with upstream member names
    classes       markup_types/classes.rs                the `markup:` part of every class listed in the
                                                         crate's register_types.rs: [Content], plain
                                                         properties, routed events as static values, plain
                                                         events, type attributes, attributes of registered
                                                         properties
    named-values  markup_types/named_values.rs (Base)    the static values of `Colors` and `Brushes`
    rust-paths    rust_paths.rs (Base, Controls,         the shortest public Rust path of every registered class
                  Markup.Xaml, Dialogs)                  and markup type, for the emitter of Rust source
                                                         (scripts/rust_paths.py)

Everything else in `markup_types/` (mod.rs, values.rs, contracts.rs,
plain.rs, the tests) is written by hand and never touched by this script.

What cannot be derived (constructors with arguments, members whose Rust
signature needs an adapter closure, notes) is hand-maintained in
scripts/markup_types_overrides.py and merged into the generated class
declarations; edit that file, never the generated ones.

How to rerun (from the repository root; Python 3, standard library only):

    python3 scripts/generate_markup_types.py --upstream ../Avalonia

Options:
    --upstream P   the reference checkout of the upstream project (its `src`
                   directory is read); default: $FERROUI_UPSTREAM, else the
                   sibling directory `Avalonia` of the repository
    --check        do not write; exit with status 1 and name the stale files
                   (with a line-count summary of the difference) if a
                   generated file differs from what would be generated
    --target T     only `enums`, `classes`, `named-values` or `rust-paths` (repeatable)
    --report       also print what was left out and why (members that are not
                   ported, events whose arguments cannot be held in an untyped
                   value, plain properties that need a hand-written override)

The output is deterministic: it depends only on the upstream checkout, the
Rust sources of the two crates, the override file and this script. Because
the Rust sources are an input, rerun it (or `--check` it) after porting a
class or changing the public interface of one.

Tables in this script:

    XMLNS_NAMESPACES   the dotted namespaces mapped to the framework XML
                       namespace (mirrors the ASSEMBLY statics of the two
                       register_types.rs)
    ENUM_EXTRA         enumerations outside those namespaces that are declared
                       anyway
    ENUM_NAMESPACE     namespaces the scanner cannot read from upstream
    ENUM_RENAMED       upstream member -> Rust variant, where they differ
    FLAG_CONSTANTS     upstream flags member -> Rust constant, where the
                       SCREAMING_SNAKE_CASE rule does not give it
    EVENT_ARGS_NOT_COPIED
                       event argument types whose instances must reach the
                       handler itself (cancellable), so the events cannot be
                       adapted by cloning the arguments
"""

