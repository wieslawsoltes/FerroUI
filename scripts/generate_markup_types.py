def top_level(body):
    """`body` with the contents of nested blocks removed."""
    out, depth = [], 0
    for c in body:
        if c == "{":
            depth += 1
            out.append("{" if depth == 1 else "")
        elif c == "}":
            depth -= 1
            out.append("}" if depth == 0 else "")
        else:
            out.append(c if depth == 0 else "")
    return "".join(out)


def upstream_class(sources, name):
    """What the upstream declaration(s) of class `name` state."""
    result = dict(files=[], attributes=[], properties=[], events=[], event_types={}, routed=[], registered=[], attached=[], raw="")
    for path in sorted(sources.cs_by_type.get(name, [])):
        text = sources.cs[path]
        m = re.search(
            r"((?:\[[^\n]*\]\s*)*)(?:public|internal)\s+(?:abstract\s+|sealed\s+|static\s+|unsafe\s+|partial\s+)*"
            r"(?:class|struct|interface)\s+" + name + r"\b(?!<)([^{]*)\{",
            text,
        )
        if not m:
            continue
        body = text[m.end() : block_end(text, m.end()) - 1]
        result["files"].append(path)
        result["raw"] += text
        result["attributes"] += [a.strip() for a in re.findall(r"\[([^\]]+)\]", m.group(1))]
        flat = top_level(body)
        for f in re.finditer(r"public\s+static\s+readonly\s+([\w<>?,. \[\]]+?)\s+(\w+)\s*(?:=|;)", flat):
            type_, field = f.groups()
            if "RoutedEvent" in type_:
                result["routed"].append(field)
            elif field.endswith("Property"):
                result["registered"].append(field[:-8])
        for p in re.finditer(
            r"((?:\[[^\]\n]+\]\s*)*)public\s+((?:new\s+|virtual\s+|override\s+|abstract\s+|static\s+|required\s+)*)"
            r"([\w<>?,. \[\]]+?)\s+(\w+)\s*(\{[^}]*\}|=>)",
            flat,
        ):
            attributes, modifiers, type_, property_, _ = p.groups()
            if type_.strip() in ("class", "struct", "interface", "enum") or "event" in type_.split():
                continue
            result["properties"].append(
                dict(
                    name=property_,
                    type=type_.strip(),
                    attributes=[x.strip() for x in re.findall(r"\[([^\]]+)\]", attributes)],
                    static="static" in modifiers,
                )
            )
        # The accessors of attached properties carry the attributes of the property.
        for a in re.finditer(r"((?:\[[^\]\n]+\]\s*)+)public\s+static\s+[\w<>?,. \[\]]+?\s+Get(\w+)\s*\(", flat):
            attributes = [x.strip() for x in re.findall(r"\[([^\]]+)\]", a.group(1))]
            result["attached"].append((a.group(2), attributes))
        for e in re.finditer(r"public\s+(?:static\s+)?event\s+([\w<>?,. ]+?)\s+(\w+)\s*[;{]", flat):
            result["events"].append(e.group(2))
            result["event_types"][e.group(2)] = e.group(1).strip().rstrip("?")
    return result


def has_public_setter(raw, property_):
    m = re.search(r"public\s+(?:new\s+|virtual\s+|override\s+)*[\w<>?,. \[\]]+\s+" + property_ + r"\s*\{", raw)
    if not m:
        return False
    body = raw[m.end() : block_end(raw, m.end())]
    for accessor in re.finditer(r"(\w+\s+)?\b(set|init)\b\s*(;|\{|=>)", body):
        return (accessor.group(1) or "").strip() not in ("private", "internal", "protected")
    return False


def constant_string(raw, name):
    m = re.search(r"const\s+string\s+" + name + r'\s*=\s*"([^"]*)"', raw)
    return m.group(1) if m else None


def registered_classes(crate):
    """[(class name, dotted namespace)] in the order of the crate's register_types.rs.

    The namespace of an entry is the one of the `// FerroUI..` comment that heads its
    section; under any other section comment it is the namespace of the module of the
    entry in the `NAMESPACES` table of the file (the longest module path that is a prefix
    of the path of the entry), which is how the runtime type gets its namespace.
    """
    whole = read(os.path.join(SRC, crate, "register_types.rs"))
    table = whole[whole.index("const NAMESPACES") : whole.index("];", whole.index("const NAMESPACES"))]
    modules = sorted(re.findall(r'\("(?:\w+)((?:::\w+)*)",\s*"([\w.]+)"\)', table), key=lambda entry: -len(entry[0]))
    text = whole[whole.index("const TYPES") :]
    result, namespace = [], None
    for line in text.split("\n"):
        m = re.match(r"\s*// (FerroUI[\w.]*)\s*$", line)
        if m:
            namespace = m.group(1)
        elif re.match(r"\s*//", line):
            namespace = None
        m = re.match(r"\s*crate::([\w:]+),", line)
        if m:
            path = "::" + m.group(1)
            of_module = next((n for prefix, n in modules if path == prefix or path.startswith(prefix + "::")), None)
            result.append((m.group(1).split("::")[-1], namespace or of_module))
    return result


def class_kinds(sources, crate):
    """class name -> True for a class of the object model, False for a static type."""
    kinds = {}
    for path in sources.rust[crate]:
        text = sources.rust_text[path]
        for m in re.finditer(r"^(?:\w+::)?ferro_static_type!\((\w+)\)", text, re.M):
            kinds[m.group(1)] = False
        for m in re.finditer(r"^impl (?:\w+::)?StaticType for (\w+)", text, re.M):
            kinds.setdefault(m.group(1), False)
        for m in re.finditer(r"^(?:\w+::)?ferro_class!\s*[({]\s*(\w+)\s*:", text, re.M):
            kinds[m.group(1)] = True
        for m in re.finditer(r"^(?:\w+::)?ferro_transition_class!\(\s*(?:///[^\n]*\s*)*(\w+)\s*:", text, re.M):
            kinds[m.group(1)] = True
    # The root class is declared by hand, without the class macro.
    kinds["FerroObject"] = True
    return kinds


def translate_attribute(attribute, ported):
    """An upstream property attribute in the declaration form, or None if it names something not ported."""
    attribute = attribute.replace("Metadata.", "")
    attribute = re.sub(r"nameof\((?:\w+\.)*(\w+)\)", r'"\1"', attribute)
    for type_ in re.findall(r"typeof\((\w+)\)", attribute):
        if type_ not in ported:
            return None
    return re.sub(r"typeof\((\w+)\)", r"type(Ref<\1>)", attribute)


def generate_classes(sources, crate, overrides, report, known_event_arguments, known_event_classes):
    ported = set()
    for c in CRATES:
        ported.update(name for name, _ in registered_classes(c))
    kinds = class_kinds(sources, crate)
    # A class may have one `markup:` part: one that is declared with the class is not generated.
    declared_elsewhere = set()
    for path in sources.rust[crate]:
        for m in re.finditer(r"ferro_class_info!\(\s*(\w+)\s*\{(.*?)\n\}\);", sources.rust_text[path], re.S):
            if re.search(r"\bmarkup:", m.group(2)):
                declared_elsewhere.add(m.group(1))
    by_namespace, statics = {}, []
    for name, namespace in registered_classes(crate):
        if name not in kinds:
            report.append("%s: %s: declaration form not recognised" % (crate, name))
            continue
        if name in declared_elsewhere:
            report.append("%s: %s: declares its `markup:` part in its own file; not generated" % (crate, name))
            continue
        up = upstream_class(sources, name)
        raw = up["raw"]
        extra = overrides.get(name, {})
        members = {}
        for function, signature, visibility in sources.members[crate].get(name, []):
            members.setdefault(function, (signature, visibility))
        registered = set(up["registered"])
        rust_properties = {f[:-9] for f in members if f.endswith("_property")}

        # Plain properties, and the attributes of registered ones.
        properties = list(extra.get("properties", []))
        declared = {re.match(r"\s*(\w+)", p).group(1) for p in properties}
        property_attributes = []
        for p in up["properties"]:
            property_ = p["name"]
            if property_ in registered:
                # An attached property that the class registers and also exposes as a property of
                # its own instances (`Visual.FlowDirection`): the run-time type system projects the
                # static accessors of an attached property only, so the instance property is
                # declared, over the registered property.
                definition = members.get(snake(property_) + "_property")
                attached_type = (
                    re.search(r"->\s*AttachedProperty<(.+)>$", definition[0]) if definition and definition[1] == "pub" else None
                )
                registers = re.search(r"\b%sProperty\s*=\s*(?:AvaloniaProperty\s*\.\s*)?RegisterAttached<" % property_, raw)
                if attached_type and registers and not p["static"] and property_ not in declared and property_ not in extra.get("skip", []):
                    value_type = attached_type.group(1).strip()
                    accessors = "get: |this: &Ref<%s>| this.get_value(%s::%s_property())" % (name, name, snake(property_))
                    if has_public_setter(raw, property_):
                        accessors += ",\n                set: |this: &Ref<%s>, value: %s| this.set_value(%s::%s_property(), value)" % (
                            name, value_type, name, snake(property_))
                    properties.append("%s: %s {\n                %s\n            }" % (property_, value_type, accessors))
                    declared.add(property_)
                attributes = [a for a in p["attributes"] if re.match(PROPERTY_ATTRIBUTES + r"|AssignBinding\b", a.replace("Metadata.", ""))]
                if not attributes:
                    continue
                if snake(property_) not in rust_properties:
                    report.append("%s: %s.%s: registered property not ported (attributes %s)" % (crate, name, property_, attributes))
                    continue
                translated = [translate_attribute(a, ported) for a in attributes]
                if None in translated:
                    report.append("%s: %s.%s: attribute names a type that is not ported: %s" % (crate, name, property_, attributes))
                    translated = [a for a in translated if a]
                if translated:
                    property_attributes.append("%s: [%s]" % (property_, ", ".join(translated)))
                continue
            if p["static"] or property_ in declared or property_ in extra.get("skip", []):
                continue
            getter, setter = members.get(snake(property_)), members.get("set_" + snake(property_))
            settable = has_public_setter(raw, property_)
            if p["type"].rstrip("?") == "IResourceDictionary" and getter and setter:
                # The property is typed with the contract, as in the managed original; the
                # port holds the dictionary object.
                properties.append(
                    "%s: Rc<dyn IResourceDictionary> {\n"
                    "                get: |this: &Ref<%s>| -> Rc<dyn IResourceDictionary> { this.%s().into() },\n"
                    "                try_set: |this: &Ref<%s>, value: Rc<dyn IResourceDictionary>| {\n"
                    "                    match value.as_object().and_then(|object| object.to_ref().cast::<ResourceDictionary>()) {\n"
                    "                        Some(dictionary) => Ok(this.set_%s(dictionary)),\n"
                    "                        None => Err(\"The resource dictionary is not a ResourceDictionary.\"),\n"
                    "                    }\n"
                    "                }\n"
                    "            }" % (property_, name, snake(property_), name, snake(property_))
                )
                declared.add(property_)
                continue
            if getter and setter and getter[1] == "pub" and setter[1] == "pub" and settable:
                get_type = re.search(r"->\s*(.+)$", getter[0])
                set_type = re.search(r"\(&self,\s*\w+:\s*(.+)\)$", setter[0])
                if get_type and set_type and get_type.group(1).strip() == set_type.group(1).strip() and not re.search(r"&|impl ", get_type.group(1)):
                    attributes = [
                        translate_attribute(a, ported)
                        for a in p["attributes"]
                        if re.match(PROPERTY_ATTRIBUTES + r"|AssignBinding\b|Obsolete\b", a)
                    ]
                    suffix = " [%s]" % ", ".join(a for a in attributes if a) if attributes else ""
                    properties.append(
                        "%s: %s { get: %s::%s, set: %s::set_%s }%s"
                        % (property_, get_type.group(1).strip(), name, snake(property_), name, snake(property_), suffix)
                    )
                    declared.add(property_)
                    continue
            collection = re.search(r"List|Collection|Dictionar|Definitions|Classes|Styles|Controls|Templates|Inlines|KeyFrames", p["type"])
            get_type = re.search(r"->\s*(.+)$", getter[0]) if getter and getter[1] == "pub" else None
            if collection and not settable and get_type and not re.search(r"&|impl |\bVec<", get_type.group(1)):
                # A collection is a read-only property whose value (a shared handle) is added to.
                properties.append("%s: %s { get: %s::%s }" % (property_, get_type.group(1).strip(), name, snake(property_)))
                declared.add(property_)
                continue
            if settable or collection:
                report.append(
                    "%s: %s.%s (%s): not declared; %s"
                    % (crate, name, property_, p["type"], "its getter is `%s`" % getter[0] if getter else "it has no getter in the port")
                )
        for property_, attributes in up["attached"]:
            attributes = [a for a in attributes if re.match(PROPERTY_ATTRIBUTES, a)]
            if attributes and snake(property_) in rust_properties:
                translated = [a for a in (translate_attribute(a, ported) for a in attributes) if a]
                property_attributes.append("%s: [%s]" % (property_, ", ".join(translated)))

        # The accessors of attached properties. The run-time type system projects the pair
        # of every attached property with the host type of its registration as the type of
        # the element; where the managed original declares an accessor for another type of
        # element (`TextElement.GetFontSize(Control)` of a property registered for
        # `TextElement`), the accessor is declared as it is there.
        accessors = []
        declared_methods = " ".join(extra.get("methods", []))
        for a in re.finditer(
            r"\b(\w+)Property\s*=\s*(?:AvaloniaProperty\s*\.\s*)?RegisterAttached<\s*\w+\s*,\s*(\w+)\s*,", raw
        ):
            property_, host = a.groups()
            definition = members.get(snake(property_) + "_property")
            value_type = re.search(r"->\s*AttachedProperty<(.+)>$", definition[0]) if definition and definition[1] == "pub" else None
            if not value_type:
                continue
            value_type = value_type.group(1).strip()
            get = re.search(r"public\s+static\s+[\w<>?,. \[\]]+?\s+Get%s\s*\(\s*(\w+)\s+\w+\s*\)" % property_, raw)
            set_ = re.search(r"public\s+static\s+void\s+Set%s\s*\(\s*(\w+)\s+\w+\s*," % property_, raw)
            for kind, accessor in (("Get", get), ("Set", set_)):
                if not accessor or accessor.group(1) == host or ("fn %s%s(" % (kind, property_)) in declared_methods:
                    continue
                element = "FerroObject" if accessor.group(1) == "AvaloniaObject" else accessor.group(1)
                if element not in ported:
                    report.append("%s: %s.%s%s(%s): the type of the element is not ported" % (crate, name, kind, property_, element))
                    continue
                if kind == "Get":
                    accessors.append(
                        "static fn Get%s(Ref<%s>) -> %s =>\n                |element: Ref<%s>| element.get_value(%s::%s_property())"
                        % (property_, element, value_type, element, name, snake(property_))
                    )
                else:
                    accessors.append(
                        "static fn Set%s(Ref<%s>, %s) =>\n                |element: Ref<%s>, value: %s| element.set_value(%s::%s_property(), value)"
                        % (property_, element, value_type, element, value_type, name, snake(property_))
                    )
        methods = list(extra.get("methods", [])) + accessors

        # The content property.
        content = extra.get("content")
        if content is None:
            for p in up["properties"]:
                if any(a.replace("Metadata.", "") == "Content" for a in p["attributes"]):
                    if snake(p["name"]) in rust_properties or p["name"] in declared:
                        content = p["name"]
                    else:
                        report.append("%s: %s: [Content] %s: the property cannot be declared" % (crate, name, p["name"]))

        # Routed events as static values.
        fields = list(extra.get("fields", []))
        for field in up["routed"]:
            accessor = members.get(snake(field))
            type_ = re.search(r"->\s*(.+)$", accessor[0]) if accessor and accessor[1] == "pub" else None
            if type_:
                fields.append("%s: %s => || *%s::%s()" % (field, re.sub(r"^&'static ", "", type_.group(1).strip()), name, snake(field)))
            else:
                report.append("%s: %s.%s: routed event not ported" % (crate, name, field))

        # Plain events.
        events = list(extra.get("events", []))
        routed = {field[:-5] for field in up["routed"]}
        for event in up["events"]:
            if event in routed or any(e.startswith(event + "(") for e in events):
                continue
            subscribe = members.get(snake(event))
            if not subscribe or subscribe[1] != "pub":
                report.append("%s: %s.%s: event not ported" % (crate, name, event))
                continue
            # `EventHandler` and `EventHandler<EventArgs>` are the same handler: the sender and `EventArgs`.
            plain_handler = up["event_types"].get(event) in ("EventHandler", "EventHandler<EventArgs>")
            if re.search(r"handler: impl Fn\(\) \+ 'static", subscribe[0]) and plain_handler:
                # A plain `EventHandler`: the sender and empty arguments.
                events.append(
                    "%s(Option<BoxedValue>, EventArgs) => |this: &Ref<%s>, handler: MarkupDelegate| {\n"
                    "                let sender = this.downgrade();\n"
                    "                this.%s(move || {\n"
                    "                    handler.invoke(&[into_markup_value(sender.upgrade()), into_markup_value(EventArgs::EMPTY)]);\n"
                    "                })\n            }" % (event, name, snake(event))
                )
                continue
            if re.search(r"handler: impl Fn\(\) \+ 'static", subscribe[0]):
                events.append(
                    "%s() => |this: &Ref<%s>, handler: MarkupDelegate| this.%s(move || {\n"
                    "                handler.invoke(&[]);\n            })" % (event, name, snake(event))
                )
                continue
            m = re.search(r"handler: impl Fn\(&(\w+)\) \+ 'static", subscribe[0])
            if not m:
                report.append("%s: %s.%s: event not declared; handler form `%s`" % (crate, name, event, subscribe[0]))
            elif m.group(1) in EVENT_ARGS_NOT_COPIED:
                report.append("%s: %s.%s: event not declared; its arguments (%s) are cancellable and cannot be copied" % (crate, name, event, m.group(1)))
            elif not sources.rust_type_is_boxable(m.group(1)):
                report.append("%s: %s.%s: event not declared; its arguments (%s) are not `Clone + PartialEq`" % (crate, name, event, m.group(1)))
            else:
                # The Rust event passes no sender: the adapter passes the instance.
                # The parameters are the ones of the handler of the managed original: an event
                # declared with the plain handler raises `EventArgs` (whatever arguments derived
                # from them the instance passes).
                events.append(
                    "%s(Option<BoxedValue>, %s) => |this: &Ref<%s>, handler: MarkupDelegate| {\n"
                    "                let sender = this.downgrade();\n"
                    "                this.%s(move |e: &%s| {\n"
                    "                    handler.invoke(&[into_markup_value(sender.upgrade()), into_markup_value(e.clone())]);\n"
                    "                })\n            }"
                    % (event, "EventArgs" if plain_handler else m.group(1), name, snake(event), m.group(1))
                )

        # Type attributes.
        attributes = list(extra.get("attributes", []))
        for attribute in up["attributes"]:
            m = re.match(r"(\w+)(?:\((.*)\))?$", attribute.strip(), re.S)
            if not m:
                continue
            kind, arguments = m.groups()
            if kind in ("UsableDuringInitialization", "TrimSurroundingWhitespace", "WhitespaceSignificantCollection", "ControlTemplateScope"):
                attributes.append(kind)
            elif kind == "PseudoClasses":
                values = []
                for argument in (a.strip() for a in arguments.split(",")):
                    value = argument if argument.startswith('"') else constant_string(raw, argument)
                    if value is None:
                        values = None
                        break
                    values.append(value if value.startswith('"') else '"%s"' % value)
                if values is None:
                    if not any(a.startswith("PseudoClasses(") for a in extra.get("attributes", [])):
                        report.append("%s: %s: [%s]: constant not resolved; needs an override" % (crate, name, attribute))
                else:
                    attributes.append("PseudoClasses(%s)" % ", ".join(values))
            elif kind == "TemplatePart":
                m2 = re.match(r'\s*("?\w+"?)\s*,\s*typeof\((\w+)\)\s*(?:,\s*IsRequired\s*=\s*(true|false))?\s*$', arguments)
                part = m2 and (m2.group(1) if m2.group(1).startswith('"') else constant_string(raw, m2.group(1)))
                if not part:
                    report.append("%s: %s: [%s]: form not recognised" % (crate, name, attribute))
                elif m2.group(2) not in ported:
                    report.append("%s: %s: [%s]: the part type is not a ported class" % (crate, name, attribute))
                else:
                    part = part if part.startswith('"') else '"%s"' % part
                    required = ", IsRequired = " + m2.group(3) if m2.group(3) else ""
                    attributes.append("TemplatePart(%s, type(Ref<%s>)%s)" % (part, m2.group(2), required))

        def part(label, items, indent):
            return "%s%s: [\n%s%s],\n" % (indent, label, "".join("%s    %s,\n" % (indent, i) for i in items), indent)

        if not kinds[name]:
            # A static type: its metadata is linked to the runtime type and registered.
            if not (fields or property_attributes or methods or extra.get("static_properties")):
                continue
            body = '    namespace: "%s",\n    type_info: %s,\n' % (namespace, name)
            if property_attributes:
                body += part("property_attributes", property_attributes, "    ")
            if methods:
                body += part("methods", methods, "    ")
            if fields:
                body += part("fields", fields, "    ")
            if extra.get("static_properties"):
                body += part("static_properties", extra["static_properties"], "    ")
            by_namespace.setdefault(namespace, []).append((name, "ferro_markup_type!(static %s {\n%s});\n" % (name, body)))
            statics.append(name)
            continue

        body = ""
        if content:
            body += "        content: %s,\n" % content
        if extra.get("parse"):
            body += "        parse: %s,\n" % extra["parse"]
        for label, items in (
            ("constructors", extra.get("constructors", [])),
            ("properties", properties),
            ("property_attributes", property_attributes),
            ("methods", methods),
            ("fields", fields),
            ("static_properties", extra.get("static_properties", [])),
            ("events", events),
        ):
            if items:
                body += part(label, items, "        ")
        if attributes:
            joined = ", ".join(attributes)
            body += "        attributes: [%s],\n" % joined if len(joined) < 90 else part("attributes", attributes, "        ")
        if not body:
            continue
        note = extra.get("note", "")
        by_namespace.setdefault(namespace, []).append(
            (
                name,
                "%sferro_class_info!(%s {\n    markup: {\n        namespace: \"%s\",\n%s    },\n});\n"
                % (note + "\n" if note else "", name, namespace, body),
            )
        )

    for name in overrides:
        if name not in kinds and not name.startswith("_"):
            report.append("%s: override for %s, which is not a class of the crate" % (crate, name))

    out = [HEADER]
    out.append(
        "//! The `markup` part of the classes of the object model of this crate:\n"
        "//! what markup needs to know about each class beyond its registered\n"
        "//! properties (content property, plain properties, constructors with\n"
        "//! arguments, methods, routed events as static values, plain events,\n"
        "//! attributes of the type and of its registered properties), as the managed\n"
        "//! original declares it. The hand-written members come from\n"
        "//! `scripts/markup_types_overrides.py`.\n"
        "//!\n"
        "//! A plain event lists the parameters of the handler of the managed\n"
        "//! original: nothing for an event without arguments, the sender and the\n"
        "//! arguments otherwise (the adapter passes the instance as the sender).\n\n"
        "// Obsolete members of the managed original are declared too (with `[Obsolete]`).\n"
        "#![allow(deprecated)]\n\n"
    )
    out.append(CLASS_USES[crate])
    for namespace in sorted(by_namespace):
        out.append("\n// %s\n" % namespace)
        for name, declaration in sorted(by_namespace[namespace]):
            out.append("\n" + declaration)
    # The typed routed events: an instantiation of `RoutedEvent<TEventArgs>` per type of
    # arguments of the events declared above. The base crate declares them on the type
    # itself; another crate cannot (the type is not its own) and uses a marker.
    arguments = sorted(set(re.findall(r": RoutedEvent<(\w+)> =>", "".join(out))) - set(known_event_arguments))
    known_event_arguments.extend(arguments)
    events = []
    if arguments:
        out.append("\n// FerroUI.Interactivity\n")
        if crate != "FerroUI.Base":
            out.append(
                "\n/// Carries the metadata of `RoutedEvent<TEventArgs>` for the arguments of this crate.\n"
                "pub(crate) struct RoutedEventOf<TEventArgs>(std::marker::PhantomData<TEventArgs>);\n"
            )
        for argument in arguments:
            type_ = ("RoutedEvent<%s>" if crate == "FerroUI.Base" else "RoutedEventOf<%s>") % argument
            events.append(type_)
            out.append(
                "\nferro_markup_type!(class %s as \"RoutedEvent`1\" {\n"
                "    namespace: \"FerroUI.Interactivity\",\n"
                "    handles: [RoutedEvent<%s>, Option<RoutedEvent<%s>>],\n"
                "    base: RoutedEvent,\n"
                "    generic: \"RoutedEvent`1\" [%s],\n"
                "});\n" % (type_, argument, argument, argument)
            )
    # The typed arguments of routed events: live handles like the base arguments
    # (`Rc<dyn IRoutedEventArgs>`), with the public properties of the managed original
    # whose Rust accessors return a type that can be held in an untyped value.
    argument_bases = {}
    for path in sources.rust[crate]:
        for m in re.finditer(r"^\s*(?:\w+::)*ferro_routed_event_args!\((\w+)\s*:\s*(\w+)\)", sources.rust_text[path], re.M):
            argument_bases[m.group(1)] = m.group(2)
    typed = [a for a in arguments if a in argument_bases]
    for argument in list(typed):
        base = argument_bases[argument]
        while base in argument_bases and base not in typed and base not in known_event_classes:
            typed.append(base)
            base = argument_bases[base]
    typed = sorted(set(typed) - set(known_event_classes))
    known_event_classes.extend(typed)
    argument_classes = []
    if typed:
        out.append(
            "\n// The typed arguments of routed events.\n\n"
            "/// The arguments of a routed event as the typed arguments `T`.\n"
            "fn typed_event_args<T: 'static, R>(e: &Rc<dyn IRoutedEventArgs>, f: impl FnOnce(&T) -> R) -> Result<R, String> {\n"
            "    match e.query_args(std::any::TypeId::of::<T>()).and_then(|args| args.downcast_ref::<T>()) {\n"
            "        Some(args) => Ok(f(args)),\n"
            "        None => Err(format!(\"The arguments are not {}.\", std::any::type_name::<T>())),\n"
            "    }\n"
            "}\n"
        )
    for argument in typed:
        up = upstream_class(sources, argument)
        namespace = re.search(r"namespace\s+([\w.]+)", up["raw"])
        if not namespace:
            report.append("%s: %s: event arguments not found upstream; not declared" % (crate, argument))
            continue
        members = {}
        for function, signature, visibility in sources.members[crate].get(argument, []):
            members.setdefault(function, (signature, visibility))
        properties = []
        for p in up["properties"]:
            if p["static"]:
                continue
            getter = members.get(snake(p["name"]))
            get_type = re.search(r"\(&self\)\s*->\s*(.+)$", getter[0]) if getter and getter[1] == "pub" else None
            if not get_type or not re.match(EVENT_PROPERTY_TYPES, get_type.group(1).strip()):
                report.append(
                    "%s: %s.%s: not declared (%s)"
                    % (crate, argument, p["name"], "accessor `%s`" % getter[0] if getter else "no accessor in the port")
                )
                continue
            type_ = get_type.group(1).strip()
            accessors = "try_get: |e: &Rc<dyn IRoutedEventArgs>| typed_event_args::<%s, _>(e, |e| e.%s())" % (argument, snake(p["name"]))
            setter = members.get("set_" + snake(p["name"]))
            if setter and setter[1] == "pub" and re.search(r"\(&self,\s*\w+:\s*%s\)$" % re.escape(type_), setter[0]) and has_public_setter(up["raw"], p["name"]):
                accessors += ",\n            try_set: |e: &Rc<dyn IRoutedEventArgs>, value: %s| typed_event_args::<%s, _>(e, |e| e.set_%s(value))" % (
                    type_, argument, snake(p["name"]))
            properties.append("        %s: %s {\n            %s\n        },\n" % (p["name"], type_, accessors))
        base = argument_bases[argument]
        base = base if base in known_event_classes else "Rc<dyn IRoutedEventArgs>"
        out.append(
            "\nferro_markup_type!(class %s {\n    namespace: \"%s\",\n    handles: [%s],\n"
            "    this: Rc<dyn IRoutedEventArgs>,\n    base: %s,\n%s});\n"
            % (
                argument,
                namespace.group(1).replace("Avalonia", "FerroUI"),
                argument,
                base,
                "    properties: [\n%s    ],\n" % "".join(properties) if properties else "",
            )
        )
        argument_classes.append(argument)
    events = events + argument_classes
    registrations = [
        "    ValueTypes::register_cast::<RoutedEvent<%s>, RoutedEvent>(|event| event.as_routed_event());\n" % a for a in arguments
    ]
    out.append(
        "\n/// Registers the casts of the typed routed events declared in this file to the\n"
        "/// untyped routed event, with the untyped value conversions of the current thread.\n"
        "pub(super) fn register_value_types() {\n%s}\n" % "".join(registrations)
    )
    out.append(
        "\n/// The types declared in this file that are not classes: the types that own static\n"
        "/// members only and the typed routed events. (The metadata of a class is reached\n"
        "/// from its runtime type and needs no registration.)\n"
        "pub(super) const TYPES: &[&MarkupType] = &[\n"
    )
    out.extend("    <%s as MarkupTyped>::MARKUP,\n" % name for name in sorted(statics) + events)
    out.append("];\n")
    text = "".join(out)
    if statics or events:
        # Only these declarations need the two imports.
        prefix = "crate" if crate == "FerroUI.Base" else "ferroui_base"
        text = text.replace(
            CLASS_USES[crate], CLASS_USES[crate] + "use %s::ferro_markup_type;\nuse %s::metadata::MarkupTyped;\n" % (prefix, prefix)
        )
    return text


