def load_overrides():
    spec = importlib.util.spec_from_file_location("markup_types_overrides", OVERRIDES)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return {"FerroUI.Base": module.BASE, "FerroUI.Controls": module.CONTROLS}


def main():
    parser = argparse.ArgumentParser(description="Generates the mechanical part of the markup metadata.")
    default_upstream = os.environ.get("FERROUI_UPSTREAM") or os.path.join(os.path.dirname(ROOT), "Avalonia")
    parser.add_argument("--upstream", default=default_upstream)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--report", action="store_true")
    parser.add_argument("--target", action="append", choices=["enums", "classes", "named-values", "rust-paths"])
    args = parser.parse_args()

    upstream = os.path.join(args.upstream, "src")
    if not os.path.isdir(os.path.join(upstream, "Avalonia.Base")):
        print("no upstream checkout at %s (pass --upstream or set FERROUI_UPSTREAM)" % args.upstream)
        return 2
    targets = args.target or ["enums", "classes", "named-values", "rust-paths"]
    sources = Sources(upstream)
    overrides = load_overrides()
    report, files = [], {}
    # The base crate declares its typed routed events first; the crates built on it add theirs.
    known_event_arguments = []
    known_event_classes = []
    for crate in CRATES:
        directory = os.path.join(SRC, crate, "markup_types")
        if "enums" in targets:
            files[os.path.join(directory, "enums.rs")] = generate_enums(sources, crate, report)
        if "classes" in targets:
            files[os.path.join(directory, "classes.rs")] = generate_classes(sources, crate, overrides[crate], report, known_event_arguments, known_event_classes)
    if "named-values" in targets:
        files[os.path.join(SRC, "FerroUI.Base", "markup_types", "named_values.rs")] = generate_named_values(sources, report)
    if "rust-paths" in targets:
        for crate in RUST_PATH_CRATES:
            macro = "crate::ferro_rust_paths" if crate == "FerroUI.Base" else "ferroui_base::ferro_rust_paths"
            text, missing = rust_paths.rust_paths_file(os.path.join(SRC, crate), HEADER, macro)
            files[os.path.join(SRC, crate, "rust_paths.rs")] = text
            report.extend("%s: %s" % (crate, line) for line in missing)

    stale = []
    for path in sorted(files):
        old = read(path) if os.path.exists(path) else ""
        if old == files[path]:
            continue
        diff = list(difflib.unified_diff(old.split("\n"), files[path].split("\n"), lineterm="", n=0))
        added = sum(1 for line in diff if line.startswith("+") and not line.startswith("+++"))
        removed = sum(1 for line in diff if line.startswith("-") and not line.startswith("---"))
        stale.append("%s (+%d -%d lines)" % (os.path.relpath(path, ROOT), added, removed))
        if not args.check:
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(files[path])
    if args.report:
        for line in report:
            print("  " + line)
    if args.check:
        if stale:
            print("stale generated files:\n  " + "\n  ".join(stale))
            return 1
        print("generated files are up to date")
        return 0
    print("generated %d files (%d changed)" % (len(files), len(stale)))
    for line in stale:
        print("  " + line)
    return 0


if __name__ == "__main__":
    sys.exit(main())
