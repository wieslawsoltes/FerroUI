def upstream_enums(sources):
    """name -> [(namespace, is public, members in declaration order)]"""
    result = {}
    for path in sorted(sources.cs):
        text = sources.cs[path]
        namespace = re.search(r"namespace\s+([\w.]+)", text)
        namespace = namespace.group(1) if namespace else ""
        # The key enumerations are shared with the remote protocol, where they
        # are compiled into another namespace.
        if namespace.startswith("Avalonia.Remote.Protocol"):
            namespace = "Avalonia.Input"
        for m in re.finditer(r"\b(public|internal)\s+enum\s+(\w+)[^{]*\{(.*?)\}", text, re.S):
            visibility, name, body = m.groups()
            body = re.sub(r"\[[^\]]*\]", "", body)
            members = [x.strip().split("=")[0].strip() for x in body.split(",") if x.strip()]
            result.setdefault(name, []).append((namespace.replace("Avalonia", "FerroUI"), visibility == "public", members))
    return result


def rust_enums(sources, crate):
    """[(name, kind, members, declared constants, file)] of the public field-less enums and flags types."""
    result = []
    for path in sources.rust[crate]:
        text = sources.rust_text[path]
        for m in re.finditer(r"^pub enum (\w+)\s*\{(.*?)^\}", text, re.S | re.M):
            name, body = m.groups()
            body = re.sub(r"//[^\n]*", "", body)
            body = re.sub(r"#\[[^\]]*\]", "", body)
            if re.search(r"[({]", body):
                continue
            members = [x.strip().split("=")[0].strip() for x in body.split(",") if x.strip()]
            result.append((name, "enum", members, path))
        for m in re.finditer(r"bitflags(?:::bitflags)?!\s*\{(.*?)^\}", text, re.S | re.M):
            for m2 in re.finditer(r"pub struct (\w+)\s*:\s*\w+\s*\{(.*?)\n    \}", m.group(1), re.S):
                result.append((m2.group(1), "flags", re.findall(r"const (\w+)\s*=", m2.group(2)), path))
    return result


def wrap_members(members):
    lines, current = [], "       "
    for member in members:
        if len(current) + len(member) + 2 > 116:
            lines.append(current)
            current = "       "
        current += " " + member + ","
    lines.append(current)
    return "\n".join(lines)


def generate_enums(sources, crate, report):
    upstream = upstream_enums(sources)
    by_namespace = {}
    # An enumeration that declares its metadata next to the type is not generated.
    declared_elsewhere = set()
    for text in sources.rust_text.values():
        declared_elsewhere.update(re.findall(r"^(?:\w+::)?ferro_markup_enum!\(\s*(?:flags\s+)?(\w+)", text, re.M))
    for name, kind, members, path in rust_enums(sources, crate):
        if name in declared_elsewhere:
            report.append("%s: enum %s: declares its metadata in its own file; not generated" % (crate, name))
            continue
        declarations = [u for u in upstream.get(name, []) if u[1]]
        if name in ENUM_NAMESPACE:
            namespace = ENUM_NAMESPACE[name]
            upstream_members = declarations[0][2] if declarations else members
            if not declarations and kind == "flags":
                # The member names of the mirrored type: the constants in PascalCase.
                upstream_members = ["".join(part.capitalize() for part in member.split("_")) for member in members]
        elif not declarations:
            continue
        else:
            namespace, _, upstream_members = declarations[0]
        is_property_type = bool(re.search(r"\b" + name + r"\b", sources.property_signatures))
        if namespace.startswith("FerroUI.Rendering.Composition"):
            continue
        if namespace not in XMLNS_NAMESPACES and namespace != "System" and not is_property_type and name not in ENUM_EXTRA:
            continue
        text = sources.rust_text[path]
        constants = re.findall(r"pub const (\w+): " + name + r"\b", text)
        renamed = ENUM_RENAMED.get(name, {})
        entries, missing = [], []
        if kind == "flags":
            known = set(members) | set(constants)
            for member in upstream_members:
                constant = FLAG_CONSTANTS.get(member, re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", "_", member).upper())
                if constant in known:
                    entries.append("    %s = %s::%s,\n" % (member, name, constant))
                elif member in known:
                    entries.append("    %s = %s::%s,\n" % (member, name, member))
                else:
                    missing.append(member)
            declaration = 'ferro_markup_enum!(flags %s {\n%s}, { namespace: "%s" });\n' % (name, "".join(entries), namespace)
        else:
            known = set(members) | set(constants)
            for member in upstream_members:
                if member in renamed:
                    entries.append("%s = %s" % (member, renamed[member]))
                elif member in known:
                    entries.append(member)
                else:
                    missing.append(member)
            declaration = 'ferro_markup_enum!(%s { %s }, { namespace: "%s" });\n' % (name, ", ".join(entries), namespace)
            if len(declaration) > 119:
                declaration = 'ferro_markup_enum!(\n    %s {\n%s\n    },\n    { namespace: "%s" }\n);\n' % (
                    name,
                    wrap_members(entries),
                    namespace,
                )
        if missing:
            report.append("%s: enum %s: members not in the port: %s" % (crate, name, ", ".join(missing)))
            declaration = "// Members of the managed original that the port does not have: %s.\n%s" % (
                ", ".join(missing),
                declaration,
            )
        by_namespace.setdefault(namespace, []).append((name, declaration))

    out = [HEADER]
    out.append(
        "//! Markup metadata of the enumerations of this crate: every public\n"
        "//! enumeration (and set of flags) that markup can name or that is the type of\n"
        "//! a property, with the member names of the managed original.\n\n"
    )
    out.append(ENUM_USES[crate])
    names = []
    for namespace in sorted(by_namespace):
        out.append("\n// %s\n" % namespace)
        for name, declaration in sorted(by_namespace[namespace]):
            out.append(declaration)
            names.append(name)
    out.append("\n/// The enumerations declared in this file.\npub(super) const TYPES: &[&MarkupType] = &[\n")
    out.extend("    <%s as MarkupTyped>::MARKUP,\n" % name for name in names)
    out.append("];\n")
    out.append(
        "\n/// Registers the nullable form of each enumeration with the untyped value\n"
        "/// conversions of the current thread.\npub(super) fn register_value_types() {\n"
    )
    out.extend("    ValueTypes::register_nullable::<%s>();\n" % name for name in names)
    out.append("}\n")
    return "".join(out)


