def generate_named_values(sources, report):
    media = os.path.join(sources.upstream, "Avalonia.Base", "Media")
    colors = re.findall(r"public static Color (\w+)\s*=>", read(os.path.join(media, "Colors.cs")))
    brushes = re.findall(r"public static IImmutableSolidColorBrush (\w+)\s*=>", read(os.path.join(media, "Brushes.cs")))
    rust_colors = read(os.path.join(SRC, "FerroUI.Base", "media", "colors.rs"))
    rust_brushes = read(os.path.join(SRC, "FerroUI.Base", "media", "brushes.rs"))
    screaming = lambda n: re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", n).upper()
    out = [HEADER]
    out.append(
        "//! Markup metadata of the named colors and brushes: the static values of\n"
        "//! `Colors` and `Brushes`, with the names of the managed original.\n\n"
        "use crate::ferro_markup_type;\n"
        "use crate::media::{Brushes, Color, Colors, IImmutableSolidColorBrush};\n"
        "use crate::metadata::{MarkupType, MarkupTyped};\n"
        "use std::rc::Rc;\n\n"
    )
    out.append("// The named values are static properties in the managed original.\n")
    out.append('ferro_markup_type!(static Colors {\n    namespace: "FerroUI.Media",\n    static_properties: [\n')
    for name in colors:
        if re.search(r"pub const " + screaming(name) + r": Color", rust_colors):
            out.append("        %s: Color { get: || Colors::%s },\n" % (name, screaming(name)))
        else:
            report.append("FerroUI.Base: Colors.%s is not ported" % name)
    out.append("    ],\n});\n\n")
    out.append("// A named brush is declared with the type the managed original declares (the contract of\n")
    out.append("// an immutable solid color brush, which has `Color`); it is assignable to the properties\n")
    out.append("// that take a brush through the registered casts of the brush contracts.\n")
    out.append('ferro_markup_type!(static Brushes {\n    namespace: "FerroUI.Media",\n    static_properties: [\n')
    for name in brushes:
        function = screaming(name).lower()
        if re.search(r"pub fn " + function + r"\(\)", rust_brushes):
            out.append(
                "        %s: Rc<dyn IImmutableSolidColorBrush> {\n            get: || -> Rc<dyn IImmutableSolidColorBrush> { Brushes::%s() }\n        },\n"
                % (name, function)
            )
        else:
            report.append("FerroUI.Base: Brushes.%s is not ported" % name)
    out.append("    ],\n});\n\n")
    out.append(
        "/// The types declared in this file.\n"
        "pub(super) const TYPES: &[&MarkupType] = &[<Colors as MarkupTyped>::MARKUP, <Brushes as MarkupTyped>::MARKUP];\n"
    )
    return "".join(out)


