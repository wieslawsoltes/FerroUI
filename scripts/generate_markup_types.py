def snake(name):
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", "_", name).lower()


def read(path):
    with open(path, encoding="utf-8-sig", errors="replace") as f:
        return f.read()


def walk(directory, extension):
    """The files under `directory` with `extension`, in a stable order."""
    result = []
    for current, directories, files in os.walk(directory):
        directories.sort()
        for name in sorted(files):
            if name.endswith(extension):
                result.append(os.path.join(current, name))
    return result


def is_product_source(path):
    name = os.path.basename(path)
    return not (
        name.endswith("_tests.rs")
        or "/tests/" in path
        or "/testing/" in path
        or "/markup_types/" in path
        or "test_support" in name
        or "mocks" in name
    )


_MODULES = {}


def declared_modules(path):
    """The names of the modules the Rust file `path` declares (`mod x;`, with any visibility)."""
    if path not in _MODULES:
        text = read(path) if os.path.exists(path) else ""
        _MODULES[path] = set(re.findall(r"^\s*(?:pub(?:\([a-z]+\))?\s+)?mod\s+(\w+)\s*;", text, re.M))
    return _MODULES[path]


def is_compiled(crate_root, path):
    """Whether the file is part of the crate: every module on its path is declared by its
    parent (a file that is in the directory but not yet wired into the crate is not read)."""
    parts = os.path.relpath(path, crate_root).split(os.sep)
    parts[-1] = parts[-1][:-3]
    if parts[-1] == "mod":
        parts.pop()
    if parts in ([], ["lib"]):
        return True
    parent = os.path.join(crate_root, "lib.rs")
    directory = crate_root
    for part in parts:
        if part not in declared_modules(parent):
            return False
        directory = os.path.join(directory, part)
        parent = os.path.join(directory, "mod.rs") if os.path.isdir(directory) else directory + ".rs"
    return True


def strip_cs_comments(text):
    text = re.sub(r"//[^\n]*", "", text)
    return re.sub(r"/\*.*?\*/", "", text, flags=re.S)


def block_end(text, start):
    """The index after the brace that closes the block opened before `start`."""
    depth, i = 1, start
    while depth and i < len(text):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
        i += 1
    return i


class Sources:
    """The Rust sources of the two crates and the upstream C# sources."""

    def __init__(self, upstream):
        self.upstream = upstream
        self.rust = {
            crate: [
                p
                for p in walk(os.path.join(SRC, crate), ".rs")
                if is_product_source(p) and is_compiled(os.path.join(SRC, crate), p)
            ]
            for crate in CRATES
        }
        self.rust_text = {p: read(p) for crate in CRATES for p in self.rust[crate]}
        self.cs = {}
        for project in UPSTREAM_PROJECTS.values():
            for path in walk(os.path.join(upstream, project), ".cs"):
                self.cs[path] = strip_cs_comments(read(path))
        self.cs_by_type = {}
        for path, text in self.cs.items():
            for m in re.finditer(r"\b(?:class|struct|interface)\s+(\w+)", text):
                self.cs_by_type.setdefault(m.group(1), set()).add(path)
        self.members = {crate: self._rust_members(crate) for crate in CRATES}
        self.property_signatures = " ".join(
            signature
            for crate in CRATES
            for owner in self.members[crate].values()
            for (name, signature, _) in owner
            if name.endswith("_property")
        )

    def _rust_members(self, crate):
        """owner type -> [(function name, signature, visibility)] of its inherent functions."""
        members = {}
        for path in self.rust[crate]:
            owner = None
            lines = self.rust_text[path].split("\n")
            for i, line in enumerate(lines):
                m = re.match(r"\s*(?:(?:\w+::)?ferro_properties!\s*\{\s*)?impl(?:<[^>]*>)?\s+(\w+)\s*(?:,.*)?(?:\{.*)?$", line)
                if m and " for " not in line:
                    owner = m.group(1)
                elif re.match(r"impl\b.* for ", line):
                    owner = None
                m = re.search(
                    r"^\s*(?:(?:\w+::)?ferro_property!\()?\s*(?:#\[[^\]]*\]\s*)*(pub(?:\([a-z]+\))?\s+)?(?:const\s+)?fn (\w+)\s*(?:<[^>]*>)?\(",
                    line,
                )
                if m and owner:
                    signature, j = line.strip(), i
                    while "{" not in signature and ";" not in signature and j < i + 12 and j + 1 < len(lines):
                        j += 1
                        signature += " " + lines[j].strip()
                    signature = signature.split("{")[0].strip()
                    members.setdefault(owner, []).append((m.group(2), signature, (m.group(1) or "").strip()))
        return members

    def rust_type_is_boxable(self, name):
        """Whether the Rust type `name` is `Clone + PartialEq` (can be held in an untyped value)."""
        for text in self.rust_text.values():
            m = re.search(r"((?:#\[[^\n]*\]\s*\n)*)pub struct " + name + r"\b", text)
            if not m:
                continue
            derives = " ".join(re.findall(r"derive\(([^)]*)\)", m.group(1)))
            has = lambda trait: bool(
                re.search(r"\b" + trait + r"\b", derives) or re.search(r"impl\s+" + trait + r" for " + name + r"\b", text)
            )
            return has("Clone") and has("PartialEq")
        return False


