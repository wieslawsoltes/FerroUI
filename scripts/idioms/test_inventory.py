#!/usr/bin/env python3
"""Tests of scripts/idioms/inventory.py: the blanking of comments and literals, the generated-file
headers and the patterns. Run with `python3 -m unittest discover -s scripts/idioms -p 'test_*.py'`."""

import os
import sys
import unittest

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import inventory  # noqa: E402


def code(text):
    return inventory.MARKUP_TYPE.sub(lambda m: m.group(1) + " " * len(m.group(2)),
                                     inventory.blank_comments_and_literals(text))


def count(key, text):
    pattern = next(p for k, _, p, _, _ in inventory.PATTERNS if k == key)
    return len(pattern.findall(code(text)))


class BlankingTests(unittest.TestCase):
    def test_comments_are_blanked_and_newlines_kept(self):
        text = "a // TimeSpan\nb /* Uri /* nested */ Uri */ c\n/// TimeSpan\n//! Uri\nd"
        blanked = inventory.blank_comments_and_literals(text)
        self.assertEqual(len(blanked), len(text))
        self.assertEqual(blanked.count("\n"), text.count("\n"))
        self.assertNotIn("TimeSpan", blanked)
        self.assertNotIn("Uri", blanked)
        self.assertIn("c", blanked)
        self.assertIn("d", blanked)

    def test_strings_are_blanked(self):
        text = r'''let a = "TimeSpan \" Uri"; let b = r#"Uri " TimeSpan"#; let c = b"Uri"; x'''
        blanked = inventory.blank_comments_and_literals(text)
        self.assertNotIn("TimeSpan", blanked)
        self.assertNotIn("Uri", blanked)
        self.assertTrue(blanked.rstrip().endswith("x"))

    def test_chars_and_lifetimes(self):
        text = "fn f<'a>(x: &'a Uri) -> char { '\"' } fn g() -> char { '\\'' } struct TimeSpan;"
        blanked = inventory.blank_comments_and_literals(text)
        self.assertIn("&'a Uri", blanked)
        self.assertIn("struct TimeSpan", blanked)

    def test_comment_markers_inside_strings_are_text(self):
        blanked = inventory.blank_comments_and_literals('let s = "//"; let t: TimeSpan;')
        self.assertIn("TimeSpan", blanked)

    def test_raw_identifiers_are_code(self):
        blanked = inventory.blank_comments_and_literals("let r#type = Uri::new();")
        self.assertIn("Uri", blanked)


class GeneratedTests(unittest.TestCase):
    def test_headers(self):
        self.assertTrue(inventory.is_generated("// @generated by scripts/x.py — do not edit\nfn f() {}"))
        self.assertTrue(inventory.is_generated("\n// Generated by scripts/convert-unicode-enums.py\n"))
        self.assertFalse(inventory.is_generated("//! The table is generated by the build script.\n"))
        self.assertFalse(inventory.is_generated("fn f() {}\n" * 20 + "// @generated\n"))


class PatternTests(unittest.TestCase):
    def test_disposable_impls_over_lines(self):
        self.assertEqual(count("idisposable_impls", "impl<T: Clone>\n    IDisposable for X<T> {}"), 1)
        self.assertEqual(count("idisposable_impls", "impl X { fn f(&self) -> Rc<dyn IDisposable> {} }"), 0)

    def test_getters(self):
        self.assertEqual(count("get_accessors", "pub fn get_text(&self) -> String"), 1)
        self.assertEqual(count("get_accessors", "pub fn get_value(&self, key: &str)"), 0)
        self.assertEqual(count("get_accessors", "fn get_text(&self)"), 0)

    def test_error_shapes(self):
        self.assertEqual(count("exception_types", "pub struct XamlLoadException { }"), 1)
        self.assertEqual(count("error_types", "pub enum ParseError { }"), 1)
        self.assertEqual(count("std_error_impls", "impl std::error::Error for ParseError {}"), 1)
        self.assertEqual(count("std_error_impls", "impl Error for ParseError {}"), 1)

    def test_markup_type_descriptions_declare_nothing(self):
        text = "ferro_markup_type!(struct TimeSpan { namespace: \"System\" });"
        self.assertEqual(len(inventory.DECLARATION.findall(code(text))), 0)
        self.assertEqual(count("time_span", text), 1)

    def test_names_are_whole_words(self):
        self.assertEqual(count("dictionary", "let d: ResourceDictionary = Dictionary::new();"), 1)
        self.assertEqual(count("task", "Task<u32> TaskCompletionSource<u32>"), 1)
        self.assertEqual(count("cancellation_token", "CancellationTokenSource CancellationToken"), 2)


if __name__ == "__main__":
    unittest.main()
