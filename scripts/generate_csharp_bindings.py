#!/usr/bin/env python3
"""The C# backend of the bindings of FerroUI (#636, step 6): reads the API model
(`bindings/model/ferroui-api.json`) and writes one file, `FerroUI.cs`, over the C ABI:

    readonly structs   a wrapper per class that holds the handle and nothing else
    interfaces         `IButton : IContentControl`: the hierarchy, for the constraints below
    extension methods  generic over the wrapper and constrained by its interface, so that a call
                       does not box and writes chain on the wrapper's own type:
                       `text.FontSize(12).Opacity(0.5)` writes, `text.FontSize()` reads
    static methods     attached properties, `Grid.SetRow(child, 1)`
    enums              over `long`, with the values of the framework
    Ferro.RunApp       checks the library, registers the classes of the selection, runs the loop

A failed write throws `FerroException`; a read returns a plain value, or the fallback of its kind.
Text is written as UTF-16 (`ferro_set_str16`), with no transcoding. Reads are
`SuppressGCTransition` calls. **Writes are not**: writing a property can raise an event, whose
handler is managed code, and a call without a GC transition cannot call back. What a handler
throws stops at the boundary.

Two kinds of output, as for the other backends (bindings/README.md):

    the full bindings   bindings/csharp/full/FerroUI.cs
    a selection         <application>/ferroui/FerroUI.cs, from <application>/ferroui.json

No .NET SDK is assumed by this script: it writes text. `.github/workflows/capi.yml` compiles and
runs what it writes.

    python3 scripts/generate_csharp_bindings.py            # the full bindings and the samples
    python3 scripts/generate_csharp_bindings.py --check    # exit 1 if one is stale
    python3 scripts/generate_csharp_bindings.py --select path/to/ferroui.json
"""

