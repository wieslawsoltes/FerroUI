def pascal(words):
    return "".join(word[:1].upper() + word[1:] for word in words)


def safe(name):
    return name + "Value" if name in RESERVED else name


def xml(text):
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def summary(text, indent):
    if not text:
        return []
    return [f"{indent}/// <summary>{xml(' '.join(text.split()))}</summary>"]


def cs_type(kind):
    if kind.startswith("enum:"):
        return "global::FerroUI.Bindings." + kind[5:]
    return {"bool": "bool", "int": "long", "float": "double", "string": "string"}[kind]


def read(kind, id_):
    if kind == "bool":
        return f"Native.ferro_get_bool_or(self.Handle, {id_}, 0) != 0"
    if kind == "int":
        return f"Native.ferro_get_i64_or(self.Handle, {id_}, 0)"
    if kind == "float":
        return f"Native.ferro_get_f64_or(self.Handle, {id_}, 0)"
    if kind == "string":
        return f"Native.GetString(self.Handle, {id_})"
    return f"({cs_type(kind)})Native.ferro_get_i64_or(self.Handle, {id_}, 0)"


def write(kind, handle, id_):
    if kind == "bool":
        return f"Native.Check(Native.ferro_set_bool({handle}, {id_}, value ? (byte)1 : (byte)0));"
    if kind == "int":
        return f"Native.Check(Native.ferro_set_i64({handle}, {id_}, value));"
    if kind == "float":
        return f"Native.Check(Native.ferro_set_f64({handle}, {id_}, value));"
    if kind == "string":
        return f"Native.SetString({handle}, {id_}, value);"
    return f"Native.Check(Native.ferro_set_i64({handle}, {id_}, (long)value));"


def instance_lines(cls, prop, declaration, inherited, own):
    """The extension methods of a property. A getter or a setter an ancestor already has for this
    property is left out: both would apply to the wrapper, and the call would be ambiguous."""
    kinds = kinds_of(declaration)
    if not kinds:
        return []
    name = safe(pascal(prop["words"]))
    constraint = f"where T : struct, I{cls['name']}"
    id_ = prop["id"]
    lines = []

    def fresh(signature):
        if signature in inherited or signature in own:
            return False
        own.add(signature)
        return True

    scalar = [kind for kind in kinds if kind != "object"]
    if scalar and fresh((name, "get")):
        lines += summary(f"Reads {prop['name']}. {declaration['doc']}", "        ")
        lines.append(f"        public static {cs_type(scalar[0])} {name}<T>(this T self) {constraint} => {read(scalar[0], id_)};")
    if "object" in kinds:
        getter = name + "Object" if scalar else name
        if fresh((getter, "get")):
            lines.append(f"        public static FerroObject {getter}<T>(this T self) {constraint} => Native.GetObject(self.Handle, {id_});")
    if not declaration["read_only"]:
        for kind in scalar:
            if fresh((name, cs_type(kind))):
                lines.append(f"        public static T {name}<T>(this T self, {cs_type(kind)} value) {constraint} {{ {write(kind, 'self.Handle', id_)} return self; }}")
        if "object" in kinds and fresh((name, "object")):
            lines.append(f"        public static T {name}<T>(this T self, IFerroObject value) {constraint} {{ Native.Check(Native.ferro_set_handle(self.Handle, {id_}, value?.Handle ?? 0)); return self; }}")
    return lines


def attached_lines(prop, declaration, taken):
    kinds = kinds_of(declaration)
    if not kinds:
        return []
    short = prop["name"].rsplit(".", 1)[-1]
    getter, setter = f"Get{short}", f"Set{short}"
    if getter in taken:
        return []
    taken.update((getter, setter))
    id_ = prop["id"]
    lines = summary(f"The attached property {prop['name']}. {declaration['doc']}", "        ")
    scalar = [kind for kind in kinds if kind != "object"]
    if scalar:
        kind = scalar[0]
        lines.append(f"        public static {cs_type(kind)} {getter}(IFerroObject self) => {read(kind, id_)};")
        if not declaration["read_only"]:
            lines.append(f"        public static void {setter}(IFerroObject target, {cs_type(kind)} value) {{ {write(kind, 'target.Handle', id_)} }}")
    else:
        lines.append(f"        public static FerroObject {getter}(IFerroObject self) => Native.GetObject(self.Handle, {id_});")
        if not declaration["read_only"]:
            lines.append(f"        public static void {setter}(IFerroObject target, IFerroObject value) {{ Native.Check(Native.ferro_set_handle(target.Handle, {id_}, value?.Handle ?? 0)); }}")
    return lines


def generate(model, manifest=None):
    selection = Selection(model, manifest)
    properties = {prop["name"]: prop for prop in model["properties"]}
    events = {event["name"]: event for event in model["events"]}
    classes = ordered(model, selection)
    statuses = {status["name"]: status["value"] for status in model["abi"]["statuses"]}
    entries = [] if selection.full else [cls["entry"] for cls in model["classes"] if cls.get("entry") and selection.cls(cls)]
    lines = [HEADER]
    lines += RUNTIME.rstrip("\n").split("\n")
    lines += ["", "    internal static unsafe partial class Native", "    {",
              f"        internal const int AbiVersion = {model['abi_version']};",
              f"        internal const int BufferTooSmall = {statuses['FERRO_BUFFER_TOO_SMALL']};",
              f"        internal const long ApiFingerprint = {_long(model['fingerprint'])};",
              f"        internal const long SelectionFingerprint = {_long(selection.fingerprint)};", ""]
    for entry in entries:
        lines.append(f"        [global::System.Runtime.InteropServices.LibraryImport(Library)] private static partial long {entry}();")
    lines.append("        internal static void RegisterTypes()")
    lines.append("        {")
    lines += [f"            {entry}();" for entry in entries]
    lines += ["        }", "    }", ""]
    used = set()
    for cls in classes:
        for prop_name in cls["properties"]:
            if not selection.prop(properties[prop_name]):
                continue
            for declaration in properties[prop_name]["declarations"]:
                if declaration["owner"] == cls["name"]:
                    used.update(kind[5:] for kind in kinds_of(declaration) if kind.startswith("enum:"))
    for enum in model["enums"]:
        if enum["name"] not in used:
            continue
        lines += summary(enum["doc"], "    ")
        lines.append(f"    public enum {enum['name']} : long")
        lines.append("    {")
        for member in enum["members"]:
            lines.append(f"        {safe(member['name'])} = {member['value']},")
        lines += ["    }", ""]
    signatures = {}
    for cls in classes:
        name = cls["name"]
        base = f"I{cls['base']}" if cls["base"] else "IFerroObject"
        inherited = set(signatures[cls["base"]]) if cls["base"] else set()
        own = set()
        taken = set()
        static_lines, extension_lines = [], []
        for prop_name in cls["properties"]:
            prop = properties[prop_name]
            if not selection.prop(prop):
                continue
            declaration = next((d for d in prop["declarations"] if d["owner"] == name), None)
            if declaration is None:
                continue
            if declaration["kind"] == "attached":
                static_lines += attached_lines(prop, declaration, taken)
            else:
                extension_lines += instance_lines(cls, prop, declaration, inherited, own)
        for event_name in cls["events"]:
            event = events[event_name]
            if not selection.event(event):
                continue
            method = f"On{pascal(event['words'])}"
            if (method, "event") in inherited or (method, "event") in own:
                continue
            own.add((method, "event"))
            declaration = next(d for d in event["declarations"] if d["owner"] == name)
            extension_lines += summary(f"{event_name}: the sender is valid for the call. {declaration['doc']}", "        ")
            extension_lines.append(f"        public static Subscription {method}<T>(this T self, global::System.Action<T> handler) where T : struct, I{name} =>")
            extension_lines.append(f"            Native.Subscribe(self.Handle, {event['id']}, sender => handler(Native.Wrap<T>(sender)));")
        signatures[name] = inherited | own
        lines += summary(cls["doc"], "    ")
        lines.append(f"    public interface I{name} : {base} {{ }}")
        lines.append("")
        lines += summary(cls["doc"], "    ")
        lines.append(f"    public readonly struct {name} : I{name}")
        lines.append("    {")
        lines.append(f"        public const long TypeId = {cls['id']};")
        lines.append(f"        public {name}(ulong handle) {{ Handle = handle; }}")
        lines.append("        public ulong Handle { get; }")
        if cls["creatable"]:
            lines.append(f"        public static {name} Create() => new {name}(Native.Create(TypeId));")
        lines += static_lines
        lines.append("    }")
        lines.append("")
        if extension_lines:
            lines.append(f"    public static class {name}Extensions")
            lines.append("    {")
            lines += extension_lines
            lines.append("    }")
            lines.append("")
    lines.append("}")
    return "\n".join(lines) + "\n"


def _long(value):
    return "long.MinValue" if value == -(1 << 63) else f"{value}L"


def targets(selected=None):
    if selected:
        return [(os.path.join(os.path.dirname(os.path.abspath(selected)), "ferroui"), selected)]
    return [(OUT, None)] + [(os.path.join(os.path.dirname(path), "ferroui"), path)
                            for path in sorted(glob.glob(SAMPLE_MANIFESTS))]


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n", maxsplit=1)[0])
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--select", help="a manifest (ferroui.json): write its selection beside it, in ferroui/")
    options = parser.parse_args()
    with open(MODEL, encoding="utf-8") as file:
        model = json.load(file)
    stale = False
    for directory, manifest_path in targets(options.select):
        manifest = None
        if manifest_path:
            with open(manifest_path, encoding="utf-8") as file:
                manifest = json.load(file)
        text = generate(model, manifest)
        path = os.path.join(directory, FILE)
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if current == text:
            continue
        if options.check:
            print(f"stale: {os.path.relpath(path, ROOT)}")
            stale = True
            continue
        os.makedirs(directory, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as file:
            file.write(text)
        print(f"wrote {os.path.relpath(path, ROOT)} ({len(text.encode('utf-8'))} bytes)")
    if stale:
        sys.exit(1)


if __name__ == "__main__":
    main()
