#!/usr/bin/env python3
"""A library of the C ABI for one application (docs/c-abi.md, section 17; #977).

    python3 scripts/capi/app_library.py <ferroui.json> [--out <dir>] [--build] [--profile release]

Reads the manifest of an application (the `ferroui.json` of its bindings: the `classes` it uses
and, optionally, the groups of calls `abi`; scripts/ferroui_selection.py) and writes, in `--out`
(default: `ferroui-library/` beside the manifest):

- `exports.txt`: the exported symbols list of macOS (`-Wl,-exported_symbols_list,exports.txt`);
- `exports.map`: the version script of ELF (`-Wl,--version-script=exports.map`);
- `ferroui_capi.def`: the module definition of Windows (`/DEF:ferroui_capi.def`);
- `ferroui_app.h`: for C and C++, `ferro_app_register_types()` (the entries of the classes, before
  `ferro_app_run`), `FERRO_APP_SELECTION_FINGERPRINT` and `ferro_app_check()`;
- `selection.json`: the classes, their entries, the theme units they keep, the exports, the
  fingerprint, the Cargo features and the commands that build the library.

The library is the crate built by use (`--no-default-features --features desktop`: no tables of
types, docs/c-abi.md, section 16) with `FERROUI_CAPI_SELECTION` set to the fingerprint of the
selection, so that `ferro_selection_fingerprint()` returns it, as a static library; a shared
library is linked from it with the exports of the selection only, so that the linker keeps the
classes of the selection, their theme units and the calls, and drops the rest. `--build` does
both on macOS (`libferroui_capi.dylib` and `libferroui_capi.a` in `--out`); on Linux and Windows
`selection.json` has the commands.

Cargo is `cargo`, or `$CARGO`; `--cargo-config` adds `--config` values; the target directory is
`$CARGO_TARGET_DIR`, else `target` of the workspace.
"""

import argparse
import json
import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.dirname(HERE))
from ferroui_selection import AppSelection  # noqa: E402

MODEL = os.path.join(ROOT, "bindings", "model", "ferroui-api.json")
ENTRIES = os.path.join(ROOT, "src", "FerroUI.CApi", "api_types.rs")
FEATURES = ["--no-default-features", "--features", "desktop"]


def theme_units(entries):
    """The units of the Fluent theme the entries keep with the ambient ones, from the generated
    entries (`api_types.rs`): (ambient, units of the selection beyond them)."""
    with open(ENTRIES, encoding="utf-8") as file:
        text = file.read()
    ambient = re.search(r"AMBIENT_UNITS: Units = units!\(([^)]*)\)", text)
    ambient = sorted(int(n) for n in re.findall(r"THEME_UNIT_(\d+)", ambient.group(1))) if ambient else []
    kept = set()
    for entry in entries:
        found = re.search(r"fn " + re.escape(entry) + r"\(\) -> i64 \{\s*\w+::<[^>]*>\(\d+, units!\(([^)]*)\)\)", text)
        if not found:
            raise SystemExit(f"{entry} is not an entry of api_types.rs")
        kept.update(int(n) for n in re.findall(r"THEME_UNIT_(\d+)", found.group(1)))
    return ambient, sorted(kept - set(ambient))


def c_header(selection):
    lines = [
        "/* Generated by scripts/capi/app_library.py from the manifest of the application: do not edit.",
        " * The classes of the application, registered with their entries before ferro_app_run",
        " * (docs/c-abi.md, sections 16 and 17), and the fingerprint of its selection. */",
        "",
        "#ifndef FERROUI_APP_H",
        "#define FERROUI_APP_H",
        "",
        '#include "ferroui.h"',
        "",
        "/* What a library built for this selection returns from ferro_selection_fingerprint(). */",
        f"#define FERRO_APP_SELECTION_FINGERPRINT ((int64_t){selection.fingerprint}LL)",
        "",
        "/* 1 when the library serves this selection: one built for it, or one of every class (0). */",
        "static inline int ferro_app_check(void) {",
        "    int64_t library = ferro_selection_fingerprint();",
        "    return library == 0 || library == FERRO_APP_SELECTION_FINGERPRINT;",
        "}",
        "",
        "/* Registers the classes of the selection; 0, or the number of entries that failed. */",
        "static inline int ferro_app_register_types(void) {",
        "    int failed = 0;",
    ]
    for entry in selection.entries:
        lines.append(f"    failed += {entry}() <= 0;")
    lines += ["    return failed;", "}", "", "#endif", ""]
    return "\n".join(lines)


def write(path, text):
    with open(path, "w", encoding="utf-8") as file:
        file.write(text)


def cargo_command(profile, options):
    command = [os.environ.get("CARGO", "cargo"), "rustc", "--locked", "--profile", profile, "-p", "ferroui-capi",
               "--lib", "--crate-type", "staticlib", *FEATURES]
    for value in options.cargo_config:
        command += ["--config", value]
    return command + ["--", "--print", "native-static-libs"]


def build(selection, out, options):
    """Builds the static library of the selection and links the shared library (macOS)."""
    if sys.platform != "darwin":
        raise SystemExit("--build links the shared library on macOS; selection.json has the commands of the others")
    env = dict(os.environ, FERROUI_CAPI_SELECTION=str(selection.fingerprint))
    command = cargo_command(options.profile, options)
    print("+ FERROUI_CAPI_SELECTION=%d %s" % (selection.fingerprint, " ".join(command)), flush=True)
    result = subprocess.run(command, cwd=ROOT, env=env, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    if result.returncode != 0:
        print(result.stdout[-6000:])
        raise SystemExit("the build of the library failed")
    found = re.findall(r"native-static-libs: (.*)", result.stdout)
    if not found:
        raise SystemExit("rustc printed no native-static-libs line")
    native = found[-1].split()
    target = os.environ.get("CARGO_TARGET_DIR") or os.path.join(ROOT, "target")
    archive = os.path.join(out, "libferroui_capi.a")
    shutil.copy(os.path.join(target, options.profile, "libferroui_capi.a"), archive)
    dylib = os.path.join(out, "libferroui_capi.dylib")
    # Each export is also an undefined symbol of the link, so that the members of the archive that
    # define it are loaded; the list then keeps only those exported.
    undefined = [f"-Wl,-u,_{name}" for name in selection.exports]
    link = ["cc", "-dynamiclib", "-o", dylib, "-install_name", "@rpath/libferroui_capi.dylib",
            f"-Wl,-exported_symbols_list,{os.path.join(out, 'exports.txt')}", "-Wl,-dead_strip", *undefined,
            archive, *native]
    print("+ " + " ".join(link[:8]) + " ...", flush=True)
    subprocess.run(link, check=True)
    stripped = dylib + ".stripped"
    subprocess.run(["strip", "-x", "-o", stripped, dylib], check=True)
    os.replace(stripped, dylib)
    return {"native_libs": " ".join(native), "dylib": os.path.getsize(dylib), "archive": os.path.getsize(archive)}


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("manifest")
    parser.add_argument("--out", help="the directory of the outputs (default: ferroui-library/ beside the manifest)")
    parser.add_argument("--build", action="store_true", help="build the static and the shared library (macOS)")
    parser.add_argument("--profile", default="release")
    parser.add_argument("--cargo-config", action="append", default=[], help="a --config value for cargo")
    options = parser.parse_args()
    with open(options.manifest, encoding="utf-8") as file:
        manifest = json.load(file)
    with open(MODEL, encoding="utf-8") as file:
        model = json.load(file)
    selection = AppSelection(model, manifest)
    out = os.path.abspath(options.out or os.path.join(os.path.dirname(os.path.abspath(options.manifest)), "ferroui-library"))
    os.makedirs(out, exist_ok=True)
    write(os.path.join(out, "exports.txt"), "".join(f"_{name}\n" for name in selection.exports))
    write(os.path.join(out, "exports.map"),
          "{\n  global:\n" + "".join(f"    {name};\n" for name in selection.exports) + "  local: *;\n};\n")
    write(os.path.join(out, "ferroui_capi.def"),
          "LIBRARY ferroui_capi\nEXPORTS\n" + "".join(f"    {name}\n" for name in selection.exports))
    write(os.path.join(out, "ferroui_app.h"), c_header(selection))
    ambient, units = theme_units(selection.entries)
    summary = {
        "manifest": os.path.relpath(os.path.abspath(options.manifest), ROOT),
        "fingerprint": selection.fingerprint,
        "classes": selection.classes,
        "entries": selection.entries,
        "groups": selection.groups,
        "theme_units": {"ambient": ambient, "selection": units},
        "exports": len(selection.exports),
        "cargo_features": FEATURES,
        "environment": {"FERROUI_CAPI_SELECTION": str(selection.fingerprint)},
        "commands": {
            "static library": " ".join(cargo_command(options.profile, options)),
            "macOS": "cc -dynamiclib -install_name @rpath/libferroui_capi.dylib -Wl,-exported_symbols_list,exports.txt "
                     "-Wl,-dead_strip -Wl,-u,_<each export> libferroui_capi.a <native libraries>",
            "Linux": "cc -shared -o libferroui_capi.so -Wl,--version-script=exports.map -Wl,--gc-sections "
                     "-Wl,--undefined=<each export> libferroui_capi.a <native libraries>",
            "Windows": "link /DLL /DEF:ferroui_capi.def /OPT:REF /OPT:ICF ferroui_capi.lib <native libraries> "
                       "/OUT:ferroui_capi.dll",
        },
    }
    if options.build:
        summary["built"] = build(selection, out, options)
    write(os.path.join(out, "selection.json"), json.dumps(summary, indent=1) + "\n")
    print(f"{len(selection.classes)} classes, {len(selection.entries)} entries, {len(selection.exports)} exports, "
          f"{len(units)} theme units beyond the {len(ambient)} ambient ones, fingerprint {selection.fingerprint}: {out}")
    if options.build:
        print(f"libferroui_capi.dylib {summary['built']['dylib'] / 1e6:.2f} MB (stripped)")


if __name__ == "__main__":
    main()
