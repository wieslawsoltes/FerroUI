#!/usr/bin/env python3
"""The table of WinUI's `Symbol` values and the glyphs `SymbolIcon` draws for them
(docs/porting/winui-controls.md, the icons).

WinUI's `Symbol` enumeration keeps the code points of the old Segoe UI Symbol font as its values,
and `CSymbolIcon::ConvertSymbolValueToGlyph` (dxaml/xcp/core/core/elements/icon.cpp) maps most of
them to the code point of the same picture in Segoe Fluent Icons. This script reads both from the
pinned checkout of microsoft-ui-xaml and writes them, in declaration order, into
`docs/porting/data/winui-controls/symbol-glyphs.tsv`; the test `symbol_icon_tests` of
`ferroui-controls` compares `Symbol` with that table, and `--check` compares the Rust source
(`Symbol`, `Symbol::ALL`, `Symbol::glyph` and the markup enumeration) with it, without the checkout.

    symbol_map.py --write [--reference <microsoft-ui-xaml>]   regenerate the table from WinUI
    symbol_map.py --check                                     compare the Rust source with the table

Standard library only.
"""

import argparse
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "winui-theme"))
import winui_sources as w  # noqa: E402

REPOSITORY = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TABLE = os.path.join(REPOSITORY, "docs/porting/data/winui-controls/symbol-glyphs.tsv")
RUST = os.path.join(REPOSITORY, "src/FerroUI.Controls/symbol_icon.rs")
MODEL = "dxaml/xcp/tools/XCPTypesAutoGen/XamlOM/Model/Microsoft.UI.Xaml.Controls.cs"
RENDERER = "dxaml/xcp/core/core/elements/icon.cpp"


def fail(message):
    print(f"error: {message}", file=sys.stderr)
    sys.exit(1)


def extract(model, renderer):
    """(name, value, glyph) of every member of `Symbol`, in declaration order."""
    match = re.search(r"public enum Symbol\s*\{(.*?)\n\s*\}", model, re.S)
    if not match:
        fail(f"no `enum Symbol` in {MODEL}")
    values = [(name, int(value, 16)) for name, value in re.findall(r"\b(\w+)\s*=\s*(0x[0-9A-Fa-f]+)\s*,", match[1])]
    if not values or len({n for n, _ in values}) != len(values) or len({v for _, v in values}) != len(values):
        fail("the members of Symbol are empty or not unique")
    match = re.search(r"CSymbolIcon::ConvertSymbolValueToGlyph\([^)]*\)\s*\{(.*?)\n\}", renderer, re.S)
    if not match:
        fail(f"no CSymbolIcon::ConvertSymbolValueToGlyph in {RENDERER}")
    pairs = re.findall(r"case\s+(0x[0-9A-Fa-f]+):\s*return static_cast<WCHAR>\((0x[0-9A-Fa-f]+)\);", match[1])
    mapping = {int(value, 16): int(glyph, 16) for value, glyph in pairs}
    if len(mapping) != len(pairs):
        fail("ConvertSymbolValueToGlyph maps a value twice")
    if not re.search(r"(?:default:|\};)\s*return static_cast<WCHAR>\(symbolValue\);", match[1]):
        fail("ConvertSymbolValueToGlyph no longer returns the value itself by default: review it")
    return [(name, value, mapping.get(value, value)) for name, value in values]


def render(entries, commit):
    return (
        f"# The members of WinUI's Symbol, their values and the glyph SymbolIcon draws (microsoft-ui-xaml {commit}).\n"
        "# Generated by scripts/winui-controls/symbol_map.py --write; do not edit.\n"
        "# name\tvalue\tglyph\n"
        + "".join(f"{name}\t0x{value:04X}\t0x{glyph:04X}\n" for name, value, glyph in entries)
    )


def read_table():
    entries = []
    with open(TABLE, encoding="utf-8") as file:
        for line in file:
            if line.startswith("#") or not line.strip():
                continue
            name, value, glyph = line.rstrip("\n").split("\t")
            entries.append((name, int(value, 16), int(glyph, 16)))
    return entries


def check(entries):
    with open(RUST, encoding="utf-8") as file:
        source = file.read()
    problems = []
    match = re.search(r"pub enum Symbol\s*\{(.*?)\n\}", source, re.S)
    values = re.findall(r"\b(\w+)\s*=\s*(0x[0-9A-Fa-f]+)\s*,", match[1] if match else "")
    if [(n, int(v, 16)) for n, v in values] != [(n, v) for n, v, _ in entries]:
        problems.append("the members of `enum Symbol` or their values or order differ from the table")
    glyphs = {n: int(g, 16) for n, g in re.findall(r"Self::(\w+)\s*=>\s*'\\u\{([0-9A-Fa-f]+)\}'", source)}
    if glyphs != {n: g for n, _, g in entries}:
        problems.append("`Symbol::glyph` differs from the table")
    every = re.search(r"pub const ALL:.*?=\s*&\[(.*?)\];", source, re.S)
    if not every or re.findall(r"Self::(\w+)", every[1]) != [n for n, _, _ in entries]:
        problems.append("`Symbol::ALL` differs from the table or its order")
    markup = re.search(r"ferro_markup_enum!\(\s*Symbol\s*\{(.*?)\}", source, re.S)
    if not markup or re.findall(r"\b\w+\b", markup[1]) != [n for n, _, _ in entries]:
        problems.append("the markup enumeration of Symbol differs from the table or its order")
    for problem in problems:
        print(f"error: {problem}", file=sys.stderr)
    return not problems


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true", help="regenerate the table from the WinUI checkout")
    group.add_argument("--check", action="store_true", help="compare the Rust source with the table")
    parser.add_argument("--reference", help="the checkout of microsoft-ui-xaml")
    arguments = parser.parse_args()
    if arguments.write:
        root = w.reference_root(arguments.reference)
        commit = subprocess.run(["git", "-C", root, "rev-parse", "HEAD"], check=True, stdout=subprocess.PIPE, text=True).stdout.strip()
        if commit != w.REFERENCE_COMMIT:
            fail(f"the checkout is at {commit}, not at the pin {w.REFERENCE_COMMIT}")
        with open(os.path.join(root, MODEL), encoding="utf-8-sig") as file:
            model = file.read()
        with open(os.path.join(root, RENDERER), encoding="utf-8-sig") as file:
            renderer = file.read()
        os.makedirs(os.path.dirname(TABLE), exist_ok=True)
        with open(TABLE, "w", encoding="utf-8") as file:
            file.write(render(extract(model, renderer), commit))
        print(f"wrote {os.path.relpath(TABLE, REPOSITORY)}")
        return 0
    entries = read_table()
    if not check(entries):
        return 1
    print(f"Symbol: {len(entries)} members, their values, glyphs and markup names match the table")
    return 0


if __name__ == "__main__":
    sys.exit(main())
