#!/usr/bin/env python3
"""The C++ backend of the bindings of FerroUI (#636, step 3): reads the API model
(`bindings/model/ferroui-api.json`) and writes one header-only library, `ferroui.hpp`, over the
C ABI:

    Object          a counted handle (RAII): copying retains, destroying releases
    enum class      one per enumeration of a property, with the values of the framework
    Button, ...     a class per class of the model, with its bases: typed accessors of the
                    properties (`text()` reads, `text("Hi")` writes and returns the object, so
                    that writes chain), static accessors of attached properties
                    (`Grid::set_row(child, 1)`), and two functions per event (`on_click`
                    for the life of the object, `subscribe_click` for an RAII subscription)
    run_app         checks the library, registers the classes of the selection, runs the loop

A failed call throws `ferroui::Error`. Nothing unwinds across the C ABI: the trampolines of the
handlers and of the start function catch what the code of the application throws.

Two kinds of output, as for the other backends (bindings/README.md):

    the full bindings   bindings/cpp/full/ferroui.hpp
    a selection         <application>/ferroui/ferroui.hpp, from <application>/ferroui.json:
                        the classes it names, their bases, and what those declare (only the
                        `properties` and `events` it lists, when it lists them)

Every call uses the stable IDs of the model as constants, so no name is looked up at run time.

How to run (from the repository root; Python 3, standard library only):

    python3 scripts/generate_cpp_bindings.py            # the full bindings and the samples
    python3 scripts/generate_cpp_bindings.py --check    # exit 1 if one is stale
    python3 scripts/generate_cpp_bindings.py --select path/to/ferroui.json
"""

