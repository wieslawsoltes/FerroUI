RUN = r"""
/// Checks that the library is the one of these bindings: its ABI, the model its IDs come from, and
/// the selection it was built for (0 is a library of every class).
inline void check_library() {
    if (ferro_abi_version() != FERRO_ABI_VERSION) {
        throw Error(FERRO_INVALID_ARGUMENT, "the library implements another version of the ABI");
    }
    if (ferro_api_fingerprint() != api_fingerprint) {
        throw Error(FERRO_INVALID_ARGUMENT, "the library was built from another API model");
    }
    std::int64_t selection = ferro_selection_fingerprint();
    if (selection != 0 && selection != selection_fingerprint) {
        throw Error(FERRO_INVALID_ARGUMENT, "the library was built for another selection");
    }
}

/// Runs the application: `start` is called on the UI thread once it is set up, then the main loop
/// runs until the application ends.
template <class Start>
void run_app(Start&& start) {
    check_library();
    register_types();
    using Stored = std::decay_t<Start>;
    Stored stored(std::forward<Start>(start));
    auto call = [](std::int64_t token) -> std::int64_t {
        try {
            (*reinterpret_cast<Stored*>(static_cast<std::intptr_t>(token)))();
            return 0;
        } catch (...) {
            detail::report_exception();
            return 1;
        }
    };
    detail::check(ferro_app_run(nullptr, call, static_cast<std::int64_t>(reinterpret_cast<std::intptr_t>(&stored))));
}

}  // namespace ferroui
"""


def snake(words):
    return "_".join(words)


def safe(name):
    return name + "_" if name in RESERVED else name


def comment(text, indent):
    """One documentation comment of about 100 columns."""
    if not text:
        return []
    lines, line = [], ""
    for word in text.split():
        if len(line) + len(word) + 1 > 96 - len(indent):
            lines.append(f"{indent}/// {line}")
            line = word
        else:
            line = f"{line} {word}" if line else word
    if line:
        lines.append(f"{indent}/// {line}")
    return lines


def kinds_of(declaration):
    """What a declaration can be written and read as."""
    value = declaration["value"]
    kind = value["kind"]
    if kind == "unsupported":
        return []
    if kind == "object":
        return ["object"]
    if kind == "content":
        return ["string", "object"]
    if kind == "enum" and value.get("enum"):
        return ["enum:" + value["enum"]]
    return [{"bool": "bool", "integer": "int", "number": "float"}.get(kind, "string")]


def value_type(kind):
    if kind.startswith("enum:"):
        return kind[5:]
    return {"bool": "bool", "int": "std::int64_t", "float": "double", "string": "std::string",
            "object": "Object"}[kind]


def read_expression(kind, handle, prop):
    if kind == "bool":
        return f"detail::get_bool({handle}, {prop})"
    if kind == "int":
        return f"detail::get_i64({handle}, {prop})"
    if kind == "float":
        return f"detail::get_f64({handle}, {prop})"
    if kind == "string":
        return f"detail::get_string({handle}, {prop})"
    if kind.startswith("enum:"):
        return f"static_cast<{kind[5:]}>(detail::get_i64({handle}, {prop}))"
    return None


def write_statement(kind, handle, prop):
    if kind == "bool":
        return f"detail::check(ferro_set_bool({handle}, {prop}, value_));"
    if kind == "int":
        return f"detail::check(ferro_set_i64({handle}, {prop}, value_));"
    if kind == "float":
        return f"detail::check(ferro_set_f64({handle}, {prop}, value_));"
    if kind == "string":
        return f"detail::set_string({handle}, {prop}, value_);"
    if kind == "object":
        return f"detail::check(ferro_set_handle({handle}, {prop}, value_.handle()));"
    return f"detail::check(ferro_set_i64({handle}, {prop}, static_cast<std::int64_t>(value_)));"


def parameter(kind):
    if kind == "string":
        return "std::string_view value_"
    if kind == "object":
        return "const Object& value_"
    return f"{value_type(kind)} value_"


def object_getter(handle, prop):
    return ("FerroHandle result = 0; "
            f"detail::check(ferro_get_handle({handle}, {prop}, &result)); "
            "return Object(detail::Adopt{}, result);")


def instance_accessors(prop, declaration, name):
    """The members of a property of the instance: (member names, lines)."""
    kinds = kinds_of(declaration)
    if not kinds:
        return [], []
    indent = "    "
    lines = comment(f"{prop['name']}. {declaration['doc']}", indent)
    id_ = prop["id"]
    names = [name]
    first = kinds[0]
    if first == "object":
        lines.append(f"{indent}Object {name}() const {{ {object_getter('this->handle()', id_)} }}")
    else:
        lines.append(f"{indent}{value_type(first)} {name}() const {{ return {read_expression(first, 'this->handle()', id_)}; }}")
        if "object" in kinds:
            names.append(name + "_object")
            lines.append(f"{indent}Object {name}_object() const {{ {object_getter('this->handle()', id_)} }}")
    if not declaration["read_only"]:
        for kind in kinds:
            lines.append(f"{indent}Self& {name}({parameter(kind)}) {{ {write_statement(kind, 'this->handle()', id_)} return this->self(); }}")
            if kind == "string":
                lines.append(f"{indent}Self& {name}(const char* value_) {{ return {name}(std::string_view(value_)); }}")
    return names, lines


def attached_accessors(prop, declaration, base):
    """The static members of an attached property: (member names, lines)."""
    kinds = kinds_of(declaration)
    if not kinds:
        return [], []
    indent = "    "
    lines = comment(f"{prop['name']} (attached). {declaration['doc']}", indent)
    id_ = prop["id"]
    getter, setter = f"get_{base}", f"set_{base}"
    first = kinds[0]
    if first == "object":
        lines.append(f"{indent}static Object {getter}(const Object& target) {{ {object_getter('target.handle()', id_)} }}")
    else:
        lines.append(f"{indent}static {value_type(first)} {getter}(const Object& target) {{ return {read_expression(first, 'target.handle()', id_)}; }}")
    names = [getter]
    if not declaration["read_only"]:
        names.append(setter)
        for kind in kinds:
            lines.append(f"{indent}static void {setter}(const Object& target, {parameter(kind)}) {{ {write_statement(kind, 'target.handle()', id_)} }}")
            if kind == "string":
                lines.append(f"{indent}static void {setter}(const Object& target, const char* value_) {{ {setter}(target, std::string_view(value_)); }}")
    return names, lines


def ordered(model, selection):
    """The classes of the selection, each after its base."""
    by_name = {cls["name"]: cls for cls in model["classes"]}
    done, result = set(), []

    def visit(name):
        if name in done:
            return
        done.add(name)
        base = by_name[name]["base"]
        if base:
            visit(base)
        result.append(by_name[name])

    for cls in model["classes"]:
        if cls["name"] in selection.classes:
            visit(cls["name"])
    return result


def class_lines(cls, properties, events, inherited, selection):
    """The API template and the wrapper of a class, and the member names it has."""
    name = cls["name"]
    base = f"{cls['base']}Api<Self>" if cls["base"] else "ObjectApi<Self>"
    members, body = [], []
    for prop_name in cls["properties"]:
        prop = properties[prop_name]
        if not selection.prop(prop):
            continue
        for declaration in prop["declarations"]:
            if declaration["owner"] != name:
                continue
            if declaration["kind"] == "attached":
                short = prop_name.rsplit(".", 1)[-1]
                words = prop["words"][len(prop["words"]) - _word_count(short, prop["words"]):]
                added, lines = attached_accessors(prop, declaration, safe(snake(words)))
            else:
                added, lines = instance_accessors(prop, declaration, safe(snake(prop["words"])))
            if set(added) & set(members):
                continue
            members += added
            body += lines
            break
    for event_name in cls["events"]:
        event = events[event_name]
        if not selection.event(event):
            continue
        declaration = next(d for d in event["declarations"] if d["owner"] == name)
        words = snake(event["words"])
        on, subscribe = f"on_{words}", f"subscribe_{words}"
        if on in members or subscribe in members:
            continue
        members += [on, subscribe]
        body += comment(f"{event_name}: the handler takes the object, and may return `true` for handled. {declaration['doc']}", "    ")
        body.append("    template <class Handler>")
        body.append(f"    Self& {on}(Handler&& handler) {{ detail::subscribe<Self>(this->handle(), {event['id']}, std::forward<Handler>(handler)); return this->self(); }}")
        body.append("    template <class Handler>")
        body.append(f"    Subscription {subscribe}(Handler&& handler) {{ return Subscription(detail::subscribe<Self>(this->handle(), {event['id']}, std::forward<Handler>(handler))); }}")
    # A member of the same name hides the overloads of the bases.
    usings = [f"    using {base}::{member};" for member in members if member in inherited]
    lines = comment(cls["doc"], "")
    lines.append("template <class Self>")
    lines.append(f"class {name}Api : public {base} {{")
    lines.append("public:")
    lines.append(f"    using {base}::{base.split('<')[0]};")
    lines += usings
    lines += body
    lines.append("};")
    lines.append("")
    lines.append(f"class {name} final : public {name}Api<{name}> {{")
    lines.append("public:")
    lines.append(f"    using {name}Api<{name}>::{name}Api;")
    lines.append(f"    static constexpr std::int64_t type_id = {cls['id']};")
    if cls["creatable"]:
        lines.append(f"    static {name} create() {{ return {name}(detail::Adopt{{}}, detail::create(type_id)); }}")
    lines.append("};")
    lines.append("")
    return lines, members


def _word_count(short, words):
    """How many of the last `words` spell `short` (`Row` of `Grid.Row`)."""
    target = short.lower()
    for count in range(1, len(words) + 1):
        if "".join(words[-count:]) == target:
            return count
    return len(words)


def generate(model, manifest=None):
    selection = Selection(model, manifest)
    properties = {prop["name"]: prop for prop in model["properties"]}
    events = {event["name"]: event for event in model["events"]}
    lines = [HEADER, "//", "// The C++ bindings of FerroUI (bindings/README.md, docs/c-abi.md): header-only, over the C ABI.",
             "", "#pragma once", "", "#include <cstddef>", "#include <cstdint>", "#include <cstdio>",
             "#include <exception>", "#include <stdexcept>", "#include <string>", "#include <string_view>",
             "#include <type_traits>", "#include <utility>", "", '#include "ferroui.h"']
    lines += RUNTIME.rstrip("\n").split("\n")
    lines += ["", f"inline constexpr std::int64_t api_fingerprint = {_int64(model['fingerprint'])};",
              f"inline constexpr std::int64_t selection_fingerprint = {_int64(selection.fingerprint)};", ""]
    # The enumerations the classes of the selection use.
    used = set()
    classes = ordered(model, selection)
    for cls in classes:
        for prop_name in cls["properties"]:
            if not selection.prop(properties[prop_name]):
                continue
            for declaration in properties[prop_name]["declarations"]:
                if declaration["owner"] == cls["name"]:
                    used.update(kind[5:] for kind in kinds_of(declaration) if kind.startswith("enum:"))
    known = {enum["name"] for enum in model["enums"]}
    for enum in model["enums"]:
        if enum["name"] not in used:
            continue
        lines += comment(enum["doc"], "")
        lines.append(f"enum class {enum['name']} : std::int64_t {{")
        for member in enum["members"]:
            lines.append(f"    {safe(member['name'])} = {member['value']},")
        lines.append("};")
        lines.append("")
    missing = used - known
    if missing:
        raise SystemExit(f"enumerations the model does not list: {sorted(missing)}")
    members = {}
    for cls in classes:
        inherited = set()
        current = cls["base"]
        while current:
            inherited |= members[current]
            current = next(c["base"] for c in classes if c["name"] == current)
        class_text, own = class_lines(cls, properties, events, inherited, selection)
        lines += class_text
        members[cls["name"]] = set(own)
    lines.append("/// Registers the classes of the selection, with the units of the theme they need: what a")
    lines.append("/// library built for the selection knows. The full bindings register nothing.")
    lines.append("inline void register_types() {")
    if not selection.full:
        for cls in model["classes"]:
            if cls.get("entry") and selection.cls(cls):
                lines.append(f"    {cls['entry']}();")
    lines.append("}")
    lines += RUN.rstrip("\n").split("\n")
    return "\n".join(lines) + "\n"


def _int64(value):
    # The most negative value has no literal of its own.
    return "(-9223372036854775807 - 1)" if value == -(1 << 63) else str(value)


def targets(selected=None):
    if selected:
        return [(os.path.join(os.path.dirname(os.path.abspath(selected)), "ferroui"), selected)]
    return [(OUT, None)] + [(os.path.join(os.path.dirname(path), "ferroui"), path)
                            for path in sorted(glob.glob(SAMPLE_MANIFESTS))]


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n", maxsplit=1)[0])
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--select", help="a manifest (ferroui.json): write its selection beside it, in ferroui/")
    options = parser.parse_args()
    with open(MODEL, encoding="utf-8") as file:
        model = json.load(file)
    stale = False
    for directory, manifest_path in targets(options.select):
        manifest = None
        if manifest_path:
            with open(manifest_path, encoding="utf-8") as file:
                manifest = json.load(file)
        text = generate(model, manifest)
        path = os.path.join(directory, FILE)
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if current == text:
            continue
        if options.check:
            print(f"stale: {os.path.relpath(path, ROOT)}")
            stale = True
            continue
        os.makedirs(directory, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as file:
            file.write(text)
        print(f"wrote {os.path.relpath(path, ROOT)} ({len(text.encode('utf-8'))} bytes)")
    if stale:
        sys.exit(1)


if __name__ == "__main__":
    main()
