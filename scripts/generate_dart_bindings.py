def camel(words):
    return words[0] + "".join(word[:1].upper() + word[1:] for word in words[1:]) if words else ""


def pascal(words):
    return "".join(word[:1].upper() + word[1:] for word in words)


def safe(name):
    return name + "Value" if name in RESERVED else name


def comment(text, indent="  "):
    if not text:
        return []
    lines, line = [], ""
    for word in text.split():
        if len(line) + len(word) + 1 > 92 - len(indent):
            lines.append(f"{indent}/// {line}")
            line = word
        else:
            line = f"{line} {word}" if line else word
    if line:
        lines.append(f"{indent}/// {line}")
    return lines


def dart_type(kind):
    if kind.startswith("enum:"):
        return kind[5:]
    return {"bool": "bool", "int": "int", "float": "double", "string": "String"}[kind]


def read(kind, handle, id_):
    if kind.startswith("enum:"):
        return f"{kind[5:]}(_getI64({handle}, {id_}))"
    getter = {"bool": "_getBool", "int": "_getI64", "float": "_getF64", "string": "_getString"}[kind]
    return f"{getter}({handle}, {id_})"


def write(kind, handle, id_):
    if kind.startswith("enum:"):
        return f"_setI64({handle}, {id_}, value.value)"
    setter = {"bool": "_setBool", "int": "_setI64", "float": "_setF64", "string": "_setString"}[kind]
    return f"{setter}({handle}, {id_}, value)"


def instance_lines(prop, declaration, taken):
    kinds = kinds_of(declaration)
    if not kinds:
        return []
    name = safe(camel(prop["words"]))
    if name in taken:
        return []
    id_ = prop["id"]
    lines = comment(f"{prop['name']}. {declaration['doc']}")
    scalar = [kind for kind in kinds if kind != "object"]
    taken.add(name)
    if scalar:
        kind = scalar[0]
        lines.append(f"  {dart_type(kind)} get {name} => {read(kind, 'handle', id_)};")
        if not declaration["read_only"]:
            lines.append(f"  set {name}({dart_type(kind)} value) => {write(kind, 'handle', id_)};")
    if "object" in kinds:
        getter = name + "Object" if scalar else name
        taken.add(getter)
        lines.append(f"  FerroObject get {getter} => FerroObject(_getObject(handle, {id_}));")
        if not declaration["read_only"]:
            lines.append(f"  set {getter}(FerroObject value) => _setObject(handle, {id_}, value.handle);")
    return lines


def attached_lines(prop, declaration, taken):
    kinds = kinds_of(declaration)
    if not kinds:
        return []
    short = pascal(prop["words"][-_word_count(prop):])
    getter, setter = f"get{short}", f"set{short}"
    if getter in taken:
        return []
    taken.update((getter, setter))
    id_ = prop["id"]
    lines = comment(f"{prop['name']} (attached). {declaration['doc']}")
    scalar = [kind for kind in kinds if kind != "object"]
    if scalar:
        kind = scalar[0]
        lines.append(f"  static {dart_type(kind)} {getter}(FerroObject target) => {read(kind, 'target.handle', id_)};")
        if not declaration["read_only"]:
            lines.append(f"  static void {setter}(FerroObject target, {dart_type(kind)} value) => {write(kind, 'target.handle', id_)};")
    else:
        lines.append(f"  static FerroObject {getter}(FerroObject target) => FerroObject(_getObject(target.handle, {id_}));")
        if not declaration["read_only"]:
            lines.append(f"  static void {setter}(FerroObject target, FerroObject value) => _setObject(target.handle, {id_}, value.handle);")
    return lines


def _word_count(prop):
    """How many of the last words of an attached property are its short name."""
    target = prop["name"].rsplit(".", 1)[-1].lower()
    for count in range(1, len(prop["words"]) + 1):
        if "".join(prop["words"][-count:]) == target:
            return count
    return len(prop["words"])


def generate(model, manifest=None):
    selection = Selection(model, manifest)
    properties = {prop["name"]: prop for prop in model["properties"]}
    events = {event["name"]: event for event in model["events"]}
    classes = ordered(model, selection)
    statuses = {status["name"]: status["value"] for status in model["abi"]["statuses"]}
    lines = [HEADER]
    lines += RUNTIME.rstrip("\n").split("\n")
    lines += ["", f"const int _abiVersion = {model['abi_version']};",
              f"const int _bufferTooSmall = {statuses['FERRO_BUFFER_TOO_SMALL']};",
              f"const int _apiFingerprint = {model['fingerprint']};",
              f"const int _selectionFingerprint = {selection.fingerprint};", ""]
    entries = [] if selection.full else [cls["entry"] for cls in model["classes"] if cls.get("entry") and selection.cls(cls)]
    lines.append("void _registerTypes() {")
    if entries:
        lines.append("  for (final entry in const [" + ", ".join(f"'{entry}'" for entry in entries) + "]) {")
        lines.append("    _lib.lookupFunction<ffi.Int64 Function(), int Function()>(entry)();")
        lines.append("  }")
    lines.append("}")
    lines.append("")
    used = set()
    for cls in classes:
        for prop_name in cls["properties"]:
            if not selection.prop(properties[prop_name]):
                continue
            for declaration in properties[prop_name]["declarations"]:
                if declaration["owner"] == cls["name"]:
                    used.update(kind[5:] for kind in kinds_of(declaration) if kind.startswith("enum:"))
    for enum in model["enums"]:
        if enum["name"] not in used:
            continue
        lines += comment(enum["doc"], "")
        lines.append(f"extension type const {enum['name']}(int value) {{")
        seen = set()
        for member in enum["members"]:
            name = safe(camel(member["words"]))
            while name in seen:
                name += "Value"
            seen.add(name)
            lines.append(f"  static const {enum['name']} {name} = {enum['name']}({member['value']});")
        lines.append("}")
        lines.append("")
    for cls in classes:
        name = cls["name"]
        base = cls["base"] or "FerroObject"
        lines += comment(cls["doc"], "")
        lines.append(f"extension type {name}._(int handle) implements {base} {{")
        lines.append(f"  static const int typeId = {cls['id']};")
        if cls["creatable"]:
            lines.append(f"  factory {name}() => {name}._(_create(typeId));")
        lines.append(f"  {name}.of(FerroObject object) : this._(object.handle);")
        taken = set()
        for prop_name in cls["properties"]:
            prop = properties[prop_name]
            if not selection.prop(prop):
                continue
            declaration = next((d for d in prop["declarations"] if d["owner"] == name), None)
            if declaration is None:
                continue
            if declaration["kind"] == "attached":
                lines += attached_lines(prop, declaration, taken)
            else:
                lines += instance_lines(prop, declaration, taken)
        for event_name in cls["events"]:
            event = events[event_name]
            if not selection.event(event):
                continue
            method = f"on{pascal(event['words'])}"
            if method in taken:
                continue
            taken.add(method)
            declaration = next(d for d in event["declarations"] if d["owner"] == name)
            lines += comment(f"{event_name}: the sender is valid for the call. {declaration['doc']}")
            lines.append(f"  Subscription {method}(void Function({name} sender) handler) =>")
            lines.append(f"      _subscribe(handle, {event['id']}, (sender) => handler({name}._(sender)));")
        lines.append("}")
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def targets(selected=None):
    if selected:
        return [(os.path.join(os.path.dirname(os.path.abspath(selected)), "ferroui"), selected)]
    return [(OUT, None)] + [(os.path.join(os.path.dirname(path), "ferroui"), path)
                            for path in sorted(glob.glob(SAMPLE_MANIFESTS))]


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n", maxsplit=1)[0])
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--select", help="a manifest (ferroui.json): write its selection beside it, in ferroui/")
    options = parser.parse_args()
    with open(MODEL, encoding="utf-8") as file:
        model = json.load(file)
    stale = False
    for directory, manifest_path in targets(options.select):
        manifest = None
        if manifest_path:
            with open(manifest_path, encoding="utf-8") as file:
                manifest = json.load(file)
        text = generate(model, manifest)
        path = os.path.join(directory, FILE)
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if current == text:
            continue
        if options.check:
            print(f"stale: {os.path.relpath(path, ROOT)}")
            stale = True
            continue
        os.makedirs(directory, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as file:
            file.write(text)
        print(f"wrote {os.path.relpath(path, ROOT)} ({len(text.encode('utf-8'))} bytes)")
    if stale:
        sys.exit(1)


if __name__ == "__main__":
    main()
