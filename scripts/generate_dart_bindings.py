#!/usr/bin/env python3
"""The Dart backend of the bindings of FerroUI (#636, step 5): reads the API model
(`bindings/model/ferroui-api.json`) and writes one library, `ferroui.dart`, over the C ABI with
`dart:ffi`:

    FerroObject     the handle, as an extension type: a wrapper is an `int`, with no allocation
    Button, ...     an extension type per class, implementing its base: properties are getters
                    and setters (`text.fontSize = 12`), attached properties are static
                    (`Grid.setRow(child, 1)`), events are `onClick(handler)`
    enumerations    extension types over `int`, with a constant per member
    runApp          checks the library, registers the classes of the selection, runs the loop

A failed setter throws `FerroError`; a getter returns a plain value, or the fallback of its kind.
Getters are leaf calls. **Setters are not**: writing a property can raise an event, whose handler
is Dart code, and a leaf call cannot call back. What a handler throws stops at the boundary.

The library is opened from `FERROUI_LIBRARY`, else by its usual name. A standalone Dart program
runs its main isolate on a thread that is not the main thread of the process, which X11 allows
and AppKit does not: the desktop application runs on Linux and Windows, not on macOS.

Two kinds of output, as for the other backends (bindings/README.md):

    the full bindings   bindings/dart/full/ferroui.dart
    a selection         <application>/ferroui/ferroui.dart, from <application>/ferroui.json

No Dart SDK is assumed by this script: it writes text. `.github/workflows/capi.yml` analyzes and
runs what it writes.

    python3 scripts/generate_dart_bindings.py            # the full bindings and the samples
    python3 scripts/generate_dart_bindings.py --check    # exit 1 if one is stale
    python3 scripts/generate_dart_bindings.py --select path/to/ferroui.json
"""

