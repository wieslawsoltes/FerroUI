#!/usr/bin/env python3
"""The Go backend of the bindings of FerroUI (#636, step 4): reads the API model
(`bindings/model/ferroui-api.json`) and writes a package `ferroui` over the C ABI with cgo:

    runtime.go   the only file with C calls of values: handles, errors, values, events, the start
    api.go       a struct per class, embedding its base; `Text()` reads and `SetText(v)` writes,
                 `OnClick(handler)` subscribes; a constant per enumeration member; attached
                 properties as functions (`GridSetRow(child, 1)`)
    entries.go   the classes of a selection, registered before the application starts

A wrapper is the handle and nothing else, and it is passed by value. Go has no destructors that
run on the UI thread, so a handle is released with `Release()`. A setter returns an `error`; a
getter returns a plain value, or the fallback of its kind with the failure in `LastError()`. A
panic in a handler stops at the boundary of the C ABI.

The UI thread: `init` locks the main goroutine to the main thread, and `RunApp` is called from it.

Two kinds of output, as for the other backends (bindings/README.md):

    the full bindings   bindings/go/full/
    a selection         <application>/ferroui/, from <application>/ferroui.json

No Go toolchain is assumed by this script: it writes text. The job `go` of
`.github/workflows/capi.yml` compiles and runs what it writes.

    python3 scripts/generate_go_bindings.py            # the full bindings and the samples
    python3 scripts/generate_go_bindings.py --check    # exit 1 if one is stale
    python3 scripts/generate_go_bindings.py --select path/to/ferroui.json
"""

import argparse
import glob
import json
import os
import sys

