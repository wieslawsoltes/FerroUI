def pascal(words):
    return "".join(word[:1].upper() + word[1:] for word in words)


def comment(text):
    if not text:
        return []
    lines, line = [], ""
    for word in text.split():
        if len(line) + len(word) + 1 > 92:
            lines.append(f"// {line}")
            line = word
        else:
            line = f"{line} {word}" if line else word
    if line:
        lines.append(f"// {line}")
    return lines


def go_type(kind):
    if kind.startswith("enum:"):
        return kind[5:]
    return {"bool": "bool", "int": "int64", "float": "float64", "string": "string"}[kind]


def read(kind, handle, id_):
    if kind.startswith("enum:"):
        return f"{kind[5:]}(getI64({handle}, {id_}))"
    getter = {"bool": "getBool", "int": "getI64", "float": "getF64", "string": "getString"}[kind]
    return f"{getter}({handle}, {id_})"


def write(kind, handle, id_):
    if kind.startswith("enum:"):
        return f"setI64({handle}, {id_}, int64(value))"
    setter = {"bool": "setBool", "int": "setI64", "float": "setF64", "string": "setString"}[kind]
    return f"{setter}({handle}, {id_}, value)"


def member_name(name, base):
    """A method may not have the name of the field of the embedded base, nor of the base's members."""
    return name + "Value" if name in RESERVED_MEMBERS or name == base else name


def instance_lines(cls, prop, declaration, taken):
    kinds = kinds_of(declaration)
    if not kinds:
        return []
    base = cls["base"] or "Object"
    name = member_name(pascal(prop["words"]), base)
    receiver = f"func (o {cls['name']})"
    lines = comment(f"{name} reads {prop['name']}. {declaration['doc']}")
    id_ = prop["id"]
    scalar = [kind for kind in kinds if kind != "object"]
    if scalar:
        lines.append(f"{receiver} {name}() {go_type(scalar[0])} {{ return {read(scalar[0], 'o.h', id_)} }}")
        taken.add(name)
    if "object" in kinds:
        getter = name + "Object" if scalar else name
        lines.append(f"{comment_line(getter)}")
        lines.append(f"{receiver} {getter}() Object {{ return getObject(o.h, {id_}) }}")
        taken.add(getter)
    if not declaration["read_only"]:
        for kind in scalar:
            setter = f"Set{name}"
            lines.append(f"// {setter} writes {prop['name']}.")
            lines.append(f"{receiver} {setter}(value {go_type(kind)}) error {{ return {write(kind, 'o.h', id_)} }}")
            taken.add(setter)
        if "object" in kinds:
            setter = f"Set{name}Object" if scalar else f"Set{name}"
            lines.append(f"// {setter} writes {prop['name']} to an object; nil is null.")
            lines.append(f"{receiver} {setter}(value Wrapper) error {{ return setObject(o.h, {id_}, value) }}")
            taken.add(setter)
    return lines


def comment_line(name):
    return f"// {name} is the object the property holds, with one reference counted: release it."


def attached_lines(cls, prop, declaration, used):
    kinds = kinds_of(declaration)
    if not kinds:
        return []
    short = prop["name"].rsplit(".", 1)[-1]
    getter = unique(f"{cls['name']}{short}", used)
    setter = unique(f"{cls['name']}Set{short}", used)
    id_ = prop["id"]
    lines = comment(f"{getter} reads the attached property {prop['name']}. {declaration['doc']}")
    scalar = [kind for kind in kinds if kind != "object"]
    if scalar:
        lines.append(f"func {getter}(target Wrapper) {go_type(scalar[0])} {{ return {read(scalar[0], 'target.Handle()', id_)} }}")
    else:
        lines.append(f"func {getter}(target Wrapper) Object {{ return getObject(target.Handle(), {id_}) }}")
    if not declaration["read_only"]:
        if scalar:
            lines.append(f"// {setter} writes the attached property {prop['name']}.")
            lines.append(f"func {setter}(target Wrapper, value {go_type(scalar[0])}) error {{ return {write(scalar[0], 'target.Handle()', id_)} }}")
        else:
            lines.append(f"// {setter} writes the attached property {prop['name']} to an object.")
            lines.append(f"func {setter}(target Wrapper, value Wrapper) error {{ return setObject(target.Handle(), {id_}, value) }}")
    return lines


def unique(name, used):
    while name in used:
        name += "Value"
    used.add(name)
    return name


def generate_api(model, selection):
    properties = {prop["name"]: prop for prop in model["properties"]}
    events = {event["name"]: event for event in model["events"]}
    classes = ordered(model, selection)
    used = set(RUNTIME_NAMES) | {cls["name"] for cls in classes}
    lines = [HEADER, "", "package ferroui", "",
             f"const apiFingerprint int64 = {model['fingerprint']}",
             f"const selectionFingerprint int64 = {selection.fingerprint}", ""]
    enums = set()
    for cls in classes:
        for prop_name in cls["properties"]:
            if not selection.prop(properties[prop_name]):
                continue
            for declaration in properties[prop_name]["declarations"]:
                if declaration["owner"] == cls["name"]:
                    enums.update(kind[5:] for kind in kinds_of(declaration) if kind.startswith("enum:"))
    for enum in model["enums"]:
        if enum["name"] not in enums:
            continue
        used.add(enum["name"])
        lines += comment(f"{enum['name']}: {enum['doc']}")
        lines.append(f"type {enum['name']} int64")
        lines.append("")
        lines.append("const (")
        for member in enum["members"]:
            name = unique(f"{enum['name']}{member['name']}", used)
            lines.append(f"\t{name} {enum['name']} = {member['value']}")
        lines.append(")")
        lines.append("")
    for cls in classes:
        name = cls["name"]
        base = cls["base"] or "Object"
        lines += comment(f"{name}: {cls['doc']}")
        lines.append(f"type {name} struct{{ {base} }}")
        lines.append("")
        if cls["creatable"]:
            constructor = unique(f"New{name}", used)
            lines.append(f"// {constructor} creates a {name}, with one reference counted.")
            lines.append(f"func {constructor}() ({name}, error) {{")
            lines.append(f"\tobject, err := create({cls['id']})")
            lines.append(f"\treturn As[{name}](object), err")
            lines.append("}")
            lines.append("")
        taken = set()
        for prop_name in cls["properties"]:
            prop = properties[prop_name]
            if not selection.prop(prop):
                continue
            declaration = next((d for d in prop["declarations"] if d["owner"] == name), None)
            if declaration is None:
                continue
            if declaration["kind"] == "attached":
                text = attached_lines(cls, prop, declaration, used)
            else:
                if member_name(pascal(prop["words"]), base) in taken:
                    continue
                text = instance_lines(cls, prop, declaration, taken)
            if text:
                lines += text
                lines.append("")
        for event_name in cls["events"]:
            event = events[event_name]
            if not selection.event(event):
                continue
            method = f"On{pascal(event['words'])}"
            if method in taken:
                continue
            taken.add(method)
            declaration = next(d for d in event["declarations"] if d["owner"] == name)
            lines += comment(f"{method} subscribes to {event_name}; the sender is valid for the call. {declaration['doc']}")
            lines.append(f"func (o {name}) {method}(handler func({name})) (Subscription, error) {{")
            lines.append(f"\treturn subscribe(o.h, {event['id']}, func(sender Object) {{ handler(As[{name}](sender)) }})")
            lines.append("}")
            lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def generate_entries(model, selection):
    entries = [] if selection.full else [cls["entry"] for cls in model["classes"] if cls.get("entry") and selection.cls(cls)]
    lines = [HEADER, "", "package ferroui", ""]
    if entries:
        lines += ['// #include "ferroui.h"', 'import "C"', ""]
    lines.append("// The classes of the selection, with the units of the theme they need: what a library built for")
    lines.append("// the selection knows. The full bindings register nothing.")
    lines.append("func registerTypes() {")
    lines += [f"\tC.{entry}()" for entry in entries]
    lines.append("}")
    return "\n".join(lines) + "\n"


def generate(model, manifest=None):
    selection = Selection(model, manifest)
    return [("runtime.go", RUNTIME), ("api.go", generate_api(model, selection)),
            ("entries.go", generate_entries(model, selection))]


def targets(selected=None):
    if selected:
        return [(os.path.join(os.path.dirname(os.path.abspath(selected)), "ferroui"), selected)]
    return [(OUT, None)] + [(os.path.join(os.path.dirname(path), "ferroui"), path)
                            for path in sorted(glob.glob(SAMPLE_MANIFESTS))]


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n", maxsplit=1)[0])
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--select", help="a manifest (ferroui.json): write its selection beside it, in ferroui/")
    options = parser.parse_args()
    with open(MODEL, encoding="utf-8") as file:
        model = json.load(file)
    stale = False
    for directory, manifest_path in targets(options.select):
        manifest = None
        if manifest_path:
            with open(manifest_path, encoding="utf-8") as file:
                manifest = json.load(file)
        for name, text in generate(model, manifest):
            path = os.path.join(directory, name)
            current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
            if current == text:
                continue
            if options.check:
                print(f"stale: {os.path.relpath(path, ROOT)}")
                stale = True
                continue
            os.makedirs(directory, exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as file:
                file.write(text)
            print(f"wrote {os.path.relpath(path, ROOT)} ({len(text.encode('utf-8'))} bytes)")
    if stale:
        sys.exit(1)


if __name__ == "__main__":
    main()
