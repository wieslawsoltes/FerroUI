#!/usr/bin/env python3
"""Measures the WinUI theme port (`src/FerroUI.Themes.WinUI`) against the theme of
microsoft-ui-xaml (docs/porting/winui-theme.md, section 8).

The reference is the merged theme of a WinUI 3 application (`winui_sources.merge`): every
resource key and every style (keyed, or implicit as `{TargetType}`) of every source document,
in each theme dictionary, with the definitions that a later document replaces set apart as
superseded. Each effective item is

* ported: the port defines the key in the same theme dictionary (`Default`, `Light`,
  `HighContrast`) or, for a key outside the theme dictionaries, in a dictionary of the port; a
  keyed style is ported when the port has a control theme (or style) with its key; an implicit
  style `{T}` when the port has the default control theme of the FerroUI control that
  `controls.json` maps `T` to; any item when a comment of a port document claims it
  (`<!-- WinUI: <key>[, <key>...] -->`, the key as this script prints it);
* waived: `waivers.json` names it, with the reason;
* pending: neither, with the batch of `controls.json` that ports it.

The port is also checked on its own: every resource key a port document names
(`{DynamicResource}`, `{StaticResource}`, `ResourceKey`) is defined by the port or by the accent
colour provider of the theme; a key is not defined twice in the same scope; every control of
the Fluent theme has its default control themes in the port or is pending in a batch.

It also counts the deviations of docs/porting/winui-theme/DEVIATIONS.md (the table rows of each
`## <control>` section) and the items each waiver covers. Additive native controls are
documented separately from the key inventory, using `native_additions` in controls.json;
their implementation notes do not promote missing source resource declarations to ported.

Writes docs/porting/winui-theme/TRACKING.md, docs/porting/winui-theme/tracking.json and
docs/porting/winui-theme/PROGRESS.md, the mapping tables of docs/porting/winui-theme.md (between
its `mapping:begin`/`mapping:end` markers) and the list of the controls without a WinUI
counterpart in DEVIATIONS.md (between its `counterparts:begin`/`counterparts:end` markers). The
date of a control in PROGRESS.md is the date of the last commit of its document (`git log`).
Only the standard library and git.

usage: status.py [--reference <microsoft-ui-xaml>] [--check]

`--check` writes nothing and fails when the written files would change or when the port has
unresolved references or duplicate keys.
"""

import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import winui_sources as w  # noqa: E402

REPOSITORY = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DOCS = os.path.join(REPOSITORY, "docs/porting/winui-theme")
DESIGN = os.path.join(REPOSITORY, "docs/porting/winui-theme.md")
CONTROLS = os.path.join(w.HERE, "controls.json")
FLUENT_CONTROLS = os.path.join(REPOSITORY, "src/FerroUI.Themes.Fluent/Controls")

# Keys the port defines in code, not in a document: the accent colour and its shades
# (`Accents/system_accent_colors.rs`, which WinUI gets from the system as well).
PROVIDED_KEYS = {
    "SystemAccentColor",
    "SystemAccentColorDark1",
    "SystemAccentColorDark2",
    "SystemAccentColorDark3",
    "SystemAccentColorLight1",
    "SystemAccentColorLight2",
    "SystemAccentColorLight3",
}

DEVIATIONS = os.path.join(DOCS, "DEVIATIONS.md")
PROGRESS = os.path.join(DOCS, "PROGRESS.md")
COUNTERPARTS_BEGIN = "<!-- counterparts:begin (generated by scripts/winui-theme/status.py from scripts/winui-theme/controls.json; do not edit) -->"
COUNTERPARTS_END = "<!-- counterparts:end -->"
DEVIATION_ROW = re.compile(r"^\| ([A-Z]+-\d+) \|", re.M)


def read_deviations():
    """{section title: [deviation ids]} of DEVIATIONS.md."""
    if not os.path.exists(DEVIATIONS):
        return {}
    text = open(DEVIATIONS, encoding="utf-8").read()
    sections = {}
    for match in re.finditer(r"^## (.+?)\n(.*?)(?=^## |\Z)", text, re.M | re.S):
        ids = DEVIATION_ROW.findall(match.group(2))
        if ids:
            sections[match.group(1).strip()] = ids
    return sections


def anchor(title):
    """The anchor GitHub gives a heading."""
    return re.sub(r"[^a-z0-9 -]", "", title.lower()).replace(" ", "-")


def commit_date(path):
    try:
        output = subprocess.run(
            ["git", "log", "-1", "--format=%cs", "--", path],
            cwd=REPOSITORY,
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            check=False,
        ).stdout.decode().strip()
    except OSError:
        output = ""
    return output or "not committed"


MAPPING_BEGIN = "<!-- mapping:begin (generated by scripts/winui-theme/status.py from scripts/winui-theme/controls.json; do not edit) -->"
MAPPING_END = "<!-- mapping:end -->"


def load_controls():
    with open(CONTROLS, encoding="utf-8") as file:
        return json.load(file)


def evaluate(root):
    theme = w.merge(root)
    waivers = w.load_waivers()
    controls = load_controls()
    port = w.port_documents(REPOSITORY)

    port_keys = defaultdict(list)  # (variant, key) -> [documents]
    for document in port:
        for scope_key in document.keys:
            port_keys[scope_key].append(document.path)
    claims = set()
    for document in port:
        claims |= document.claims
    all_port_keys = {key for (_, key) in port_keys}

    def implicit_targets(target):
        entry = controls["winui"].get(target)
        if entry is None:
            return {target}
        return {entry["ferroui"]} if entry.get("ferroui") else set()

    document_batches = {prefix: batch for prefix, batch in controls.get("document_batches", {}).items() if prefix != "comment"}

    def batch_of(item):
        exact = document_batches.get(f"{item.document}#{item.key}")
        if exact:
            return exact
        for prefix, batch in sorted(document_batches.items(), key=lambda pair: -len(pair[0])):
            if "#" not in prefix and item.document.startswith(prefix):
                return batch
        entry = controls["winui"].get(item.target_type or "")
        if entry:
            return entry["batch"]
        return "resources"

    def is_ported(item):
        if item.ident in claims or item.key in claims:
            return True
        if item.kind == "Style":
            if item.key.startswith("{"):
                return any("{" + target + "}" in all_port_keys for target in implicit_targets(item.key[1:-1]))
            return item.key in all_port_keys
        if item.variant:
            return (item.variant, item.key) in port_keys
        return ("", item.key) in port_keys or any(key == item.key for (_, key) in port_keys)

    items = []
    for (variant, key), item in theme.effective.items():
        reason = w.waiver_for(waivers, item)
        if is_ported(item):
            status = "ported"
        elif reason:
            status = "waived"
        else:
            status = "pending"
        items.append(
            {
                "document": item.document,
                "variant": variant,
                "key": key,
                "kind": item.kind,
                "target_type": item.target_type,
                "status": status,
                "reason": reason if status == "waived" else None,
                "batch": batch_of(item) if status == "pending" and item.kind == "Style" else ("resources" if status == "pending" else None),
            }
        )
    compact = []
    compact_keys = {key for document in port if document.path.startswith("DensityStyles/") for (_, key) in document.keys}
    for key, item in theme.compact.items():
        reason = w.waiver_for(waivers, item)
        status = "ported" if key in compact_keys or item.ident in claims else ("waived" if reason else "pending")
        compact.append({"document": item.document, "key": key, "kind": item.kind, "status": status, "reason": reason if status == "waived" else None})

    superseded = Counter(previous.document for previous, _ in theme.superseded)

    # The items each waiver covers (an item counts for the first waiver that names it).
    waiver_counts = []
    for document, key, pattern, variant, reason in waivers:
        covered = [
            item
            for item in items
            if item["status"] == "waived" and item["reason"] == reason and document in ("*", item["document"])
        ]
        waiver_counts.append({"document": document, "key": key, "variant": variant, "reason": reason, "items": len(covered)})
    deviations = read_deviations()

    # Checks of the port on its own.
    unresolved = []
    for document in port:
        for reference in sorted(document.references):
            if reference not in all_port_keys and reference not in PROVIDED_KEYS:
                unresolved.append({"document": document.path, "key": reference})
    # The compact density is a dictionary of its own that the theme looks up first: its keys
    # replace the keys of the theme on purpose.
    duplicates = []
    for (variant, key), documents in sorted(port_keys.items()):
        theme_documents = [d for d in documents if not d.startswith("DensityStyles/")]
        density_documents = [d for d in documents if d.startswith("DensityStyles/")]
        for group in (theme_documents, density_documents):
            if len(group) > 1:
                duplicates.append({"key": key, "variant": variant, "documents": group})

    ferroui = []
    for entry in controls["ferroui"]:
        themes = entry["themes"]
        present = [t for t in themes if t in all_port_keys]
        if not themes:
            status = "ported" if entry["batch"] == "F" or os.path.exists(os.path.join(REPOSITORY, w.PORT_CRATE, "Controls", entry["document"])) else "pending"
        else:
            status = "ported" if len(present) == len(themes) else ("partial" if present else "pending")
        name = entry["document"][:-5]
        port_document = os.path.join(w.PORT_CRATE, "Controls", entry["document"])
        ferroui.append(
            dict(
                entry,
                status=status,
                deviations=len(deviations.get(name, [])),
                date=commit_date(port_document) if os.path.exists(os.path.join(REPOSITORY, port_document)) else "",
            )
        )

    fluent_documents = sorted(name for name in os.listdir(FLUENT_CONTROLS) if name.endswith(".xaml") and name != "FluentControls.xaml")
    mapped = {entry["document"] for entry in controls["ferroui"]}
    unmapped = [name for name in fluent_documents if name not in mapped]

    return {
        "reference": {"repository": "https://github.com/microsoft/microsoft-ui-xaml", "commit": w.REFERENCE_COMMIT},
        "documents": [path for path, _ in theme.documents] + w.DENSITY,
        "items": sorted(items, key=lambda i: (i["document"], i["variant"], i["key"])),
        "compact": compact,
        "superseded": dict(sorted(superseded.items())),
        "port_documents": [document.path for document in port],
        "unresolved_references": unresolved,
        "duplicate_keys": duplicates,
        "ferroui_controls": ferroui,
        "unmapped_fluent_documents": unmapped,
        "batches": controls["batches"],
        "waivers": waiver_counts,
        "deviations": {section: len(ids) for section, ids in deviations.items()},
        "winui_targets": controls["winui"],
        "native_additions": [dict(entry, theme_document_sha256={
            path: hashlib.sha256(Path(REPOSITORY, w.PORT_CRATE, path).read_bytes()).hexdigest()
            for path in entry["theme_documents"]
        }) for entry in controls.get("native_additions", [])],
    }


def summary_row(name, counts):
    total = sum(counts.values())
    done = counts.get("ported", 0) + counts.get("waived", 0)
    percent = f"{100 * done / total:.0f}%" if total else "-"
    if total and done < total and percent == "100%":
        percent = f"{100 * done / total:.1f}%"
    return f"| {name} | {total} | {counts.get('ported', 0)} | {counts.get('waived', 0)} | {counts.get('pending', 0)} | {percent} |"


def render_tracking(data):
    lines = ["# WinUI theme port: tracking", ""]
    lines.append(
        "Generated by `scripts/winui-theme/status.py` (do not edit); the design and the conventions are in "
        "[../winui-theme.md](../winui-theme.md). The reference is the merged theme of a WinUI 3 application in "
        f"microsoft-ui-xaml at commit `{data['reference']['commit']}`: every resource key and style of every source document, "
        "per theme dictionary, with the definitions a later document replaces left out (they are counted under \"superseded\"). "
        "Done is ported plus waived."
    )
    lines.append("")
    by_status = Counter(item["status"] for item in data["items"])
    resources = Counter(item["status"] for item in data["items"] if item["kind"] != "Style")
    styles = Counter(item["status"] for item in data["items"] if item["kind"] == "Style")
    compact = Counter(item["status"] for item in data["compact"])
    lines += ["## Summary", "", "| Items | Total | Ported | Waived | Pending | Done |", "|---|---|---|---|---|---|"]
    lines.append(summary_row("Resources", resources))
    lines.append(summary_row("Styles", styles))
    lines.append(summary_row("All of the theme", by_status))
    lines.append(summary_row("Compact density", compact))
    lines.append("")
    controls = Counter(entry["status"] for entry in data["ferroui_controls"])
    lines.append(
        f"FerroUI controls (the documents of the Fluent theme): {len(data['ferroui_controls'])}, "
        f"{controls.get('ported', 0)} ported, {controls.get('partial', 0)} partial, {controls.get('pending', 0)} pending."
    )
    lines.append("")
    lines.append(f"Unresolved resource references in the port: {len(data['unresolved_references'])}. Keys defined twice in one scope: {len(data['duplicate_keys'])}.")
    lines.append("")

    additions = data.get("native_additions", [])
    if additions:
        lines += ["## Additive WinUI controls", ""]
        lines.append(
            "These controls use the ordinary `FerroUI.Controls` namespace and preserve existing "
            "Avalonia-compatible control identities. Their native implementation is recorded separately "
            "from the Fluent control-document count and the source resource-key inventory. A matching key "
            "does not establish complete behavioral, platform accessibility or visual parity; resource "
            "lookups alone do not count as source dictionary definitions."
        )
        lines.append("")
        for entry in additions:
            lines += [f"### `{entry['control']}`", ""]
            lines.append(
                f"Implementation: [`{entry['implementation']}`](../../../{entry['implementation']}); "
                f"control-source pin `{entry['source_commit']}`."
            )
            lines.append("")
            if entry["theme_documents"]:
                lines.append("Theme documents: " + ", ".join(
                    f"[`{document}`](../../../src/FerroUI.Themes.WinUI/{document}) "
                    f"(SHA-256 `{entry['theme_document_sha256'][document]}`)"
                    for document in entry["theme_documents"]
                ) + ".")
                lines.append("")
            lines += [entry["coverage"], "", "Remaining: " + entry["remaining"], ""]

    lines += ["## FerroUI controls by batch", ""]
    for batch, title in data["batches"].items():
        members = [entry for entry in data["ferroui_controls"] if entry["batch"] == batch]
        done = sum(1 for entry in members if entry["status"] == "ported")
        lines.append(f"- **{batch}** ({title}): {done} of {len(members)} ported. " + ", ".join(
            f"{entry['document'][:-5]} ({entry['status']})" for entry in members))
    if data["unmapped_fluent_documents"]:
        lines.append("")
        lines.append("Documents of the Fluent theme without an entry in `controls.json`: " + ", ".join(data["unmapped_fluent_documents"]) + ".")
    lines.append("")

    pending_styles = defaultdict(list)
    for item in data["items"]:
        if item["kind"] == "Style" and item["status"] == "pending":
            pending_styles[item["batch"]].append(f"`{item['key']}`")
    lines += ["## Pending styles by batch", ""]
    for batch in list(data["batches"]) + sorted(set(pending_styles) - set(data["batches"])):
        if pending_styles.get(batch):
            lines.append(f"- **{batch}**: " + ", ".join(sorted(set(pending_styles[batch]))))
    lines.append("")

    if data["unresolved_references"]:
        lines += ["## Unresolved references", ""]
        for entry in data["unresolved_references"]:
            lines.append(f"- `{entry['key']}` in `{entry['document']}`")
        lines.append("")
    if data["duplicate_keys"]:
        lines += ["## Keys defined twice", ""]
        for entry in data["duplicate_keys"]:
            lines.append(f"- `{entry['key']}` ({entry['variant'] or 'no theme dictionary'}): " + ", ".join(entry["documents"]))
        lines.append("")

    lines += ["## Waivers", "", "| Document | Key | Items | Reason |", "|---|---|---|---|"]
    for waiver in data["waivers"]:
        key = waiver["key"] if len(waiver["key"]) < 60 else waiver["key"][:57] + "..."
        lines.append(f"| `{waiver['document']}` | `{key}` | {waiver['items']} | {waiver['reason']} |")
    lines.append("")

    lines += ["## By source document", "", "| Document | Total | Ported | Waived | Pending | Done | Superseded |", "|---|---|---|---|---|---|---|"]
    per_document = defaultdict(Counter)
    for item in data["items"]:
        per_document[item["document"]][item["status"]] += 1
    for document in data["documents"]:
        if document in w.DENSITY:
            continue
        counts = per_document.get(document, Counter())
        row = summary_row(f"`{document}`", counts)
        lines.append(row + f" {data['superseded'].get(document, 0)} |")
    lines.append("")

    lines += ["## Pending and waived items", ""]
    lines.append("Per source document; a theme dictionary item is written `Variant/Key`. Waived items list their reason once per document.")
    lines.append("")
    for document in data["documents"]:
        items = [item for item in data["items"] if item["document"] == document] if document not in w.DENSITY else [
            dict(item, variant="") for item in data["compact"] if item["document"] == document]
        pending = [item for item in items if item["status"] == "pending"]
        waived = [item for item in items if item["status"] == "waived"]
        if not pending and not waived:
            continue
        lines.append(f"### `{document}`")
        lines.append("")
        if pending:
            keys = sorted({(item["variant"] + "/" if item["variant"] else "") + item["key"] for item in pending})
            lines.append(f"Pending ({len(keys)}): " + ", ".join(f"`{key}`" for key in keys))
            lines.append("")
        if waived:
            reasons = defaultdict(list)
            for item in waived:
                reasons[item["reason"]].append((item["variant"] + "/" if item["variant"] else "") + item["key"])
            for reason, keys in reasons.items():
                keys = sorted(set(keys))
                shown = ", ".join(f"`{key}`" for key in keys[:40]) + (f", and {len(keys) - 40} more" if len(keys) > 40 else "")
                lines.append(f"Waived ({len(keys)}): {shown}. Reason: {reason}")
                lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def render_mapping(data):
    lines = ["#### FerroUI controls", "", "| FerroUI control document | Default control themes | WinUI source | Batch | State |", "|---|---|---|---|---|"]
    for entry in data["ferroui_controls"]:
        themes = ", ".join(f"`{theme}`" for theme in entry["themes"]) or "(keyed themes only)"
        lines.append(f"| `{entry['document']}` | {themes} | {entry['winui']} | {entry['batch']} | {entry['status']} |")
    lines += ["", "#### WinUI styles", ""]
    lines.append("Every target type of a style of the merged WinUI theme, the FerroUI control its implicit style themes, and the batch. A type that is not listed has no FerroUI control; its styles are waived (`waivers.json`).")
    lines += ["", "| WinUI target type | FerroUI control | Batch | Note |", "|---|---|---|---|"]
    for target, entry in sorted(data["winui_targets"].items()):
        control = f"`{entry['ferroui']}`" if entry.get("ferroui") else "no FerroUI control"
        lines.append(f"| `{target}` | {control} | {entry['batch']} | {entry.get('note', '')} |")
    styles = defaultdict(list)
    for item in data["items"]:
        if item["kind"] == "Style":
            styles[item["target_type"]].append(item)
    unlisted = sorted(t for t in styles if t not in data["winui_targets"])
    if unlisted:
        lines += ["", "Target types without a FerroUI control (all their styles waived): " + ", ".join(f"`{t}`" for t in unlisted) + "."]
    return "\n".join(lines)


def render_progress(data):
    items = data["items"]
    resources = Counter(item["status"] for item in items if item["kind"] != "Style")
    styles = Counter(item["status"] for item in items if item["kind"] == "Style")
    controls = Counter(entry["status"] for entry in data["ferroui_controls"])
    deviations = data["deviations"]
    general = deviations.get("General", 0) + deviations.get("Resources", 0)
    lines = ["# WinUI theme port: progress", ""]
    lines.append(
        "Generated by `scripts/winui-theme/status.py` (do not edit). The design is in [../winui-theme.md](../winui-theme.md), "
        "every deviation from WinUI 3 in [DEVIATIONS.md](DEVIATIONS.md), the item-by-item tracking in [TRACKING.md](TRACKING.md). "
        "A batch that ports a control adds its deviations to DEVIATIONS.md and regenerates this file in the same commit."
    )
    lines += ["", "## Summary", ""]
    partial = f", {controls.get('partial', 0)} partial" if controls.get("partial") else ""
    lines.append(
        f"- FerroUI controls: {controls.get('ported', 0)} of {len(data['ferroui_controls'])} ported{partial}, "
        f"{controls.get('pending', 0)} pending."
    )
    lines.append(
        f"- Resource keys of the WinUI theme (counted per theme dictionary): {resources.get('ported', 0)} of "
        f"{sum(resources.values())} ported, {resources.get('waived', 0)} waived, {resources.get('pending', 0)} pending."
    )
    lines.append(
        f"- Styles of the WinUI theme: {styles.get('ported', 0)} of {sum(styles.values())} ported, "
        f"{styles.get('waived', 0)} waived, {styles.get('pending', 0)} pending."
    )
    lines.append(
        f"- Waivers: {len(data['waivers'])} entries covering {sum(w['items'] for w in data['waivers'])} items "
        "(`scripts/winui-theme/waivers.json`)."
    )
    lines.append(
        f"- Deviations: {sum(deviations.values())} ({general} general and of the resources, "
        f"{sum(deviations.values()) - general} of controls)."
    )
    lines.append(
        f"- Unresolved resource references: {len(data['unresolved_references'])}; keys defined twice: "
        f"{len(data['duplicate_keys'])}."
    )
    lines += ["", "## Controls", "", "| FerroUI control | State | Batch | Deviations | Date |", "|---|---|---|---|---|"]
    for entry in sorted(data["ferroui_controls"], key=lambda e: e["document"]):
        name = entry["document"][:-5]
        count = entry["deviations"]
        link = f"[{count}](DEVIATIONS.md#{anchor(name)})" if count else "0"
        lines.append(f"| {name} | {entry['status']} | {entry['batch']} | {link} | {entry['date'] or '-'} |")
    known = {e["document"][:-5] for e in data["ferroui_controls"]} | {"General", "Resources"}
    extra = sorted(set(deviations) - known)
    if extra:
        lines += [
            "",
            "Other documents with deviations (themes of classes the Fluent theme does not style by type): "
            + ", ".join(f"[{name}](DEVIATIONS.md#{anchor(name)}) ({deviations[name]})" for name in extra)
            + ".",
        ]
    return "\n".join(lines) + "\n"


def render_counterparts(data):
    lines = ["| FerroUI control | Batch | State | Built from |", "|---|---|---|---|"]
    for entry in data["ferroui_controls"]:
        if entry["winui"].startswith("No "):
            lines.append(f"| {entry['document'][:-5]} | {entry['batch']} | {entry['status']} | {entry['winui']} |")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--reference", help="the checkout of microsoft-ui-xaml")
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    data = evaluate(w.reference_root(arguments.reference))

    outputs = {
        os.path.join(DOCS, "TRACKING.md"): render_tracking(data),
        os.path.join(DOCS, "tracking.json"): json.dumps(data, indent=1, sort_keys=False) + "\n",
    }
    outputs[PROGRESS] = render_progress(data)
    if os.path.exists(DEVIATIONS):
        text = open(DEVIATIONS, encoding="utf-8").read()
        begin, end = text.find(COUNTERPARTS_BEGIN), text.find(COUNTERPARTS_END)
        if begin >= 0 and end > begin:
            outputs[DEVIATIONS] = text[: begin + len(COUNTERPARTS_BEGIN)] + "\n\n" + render_counterparts(data) + "\n\n" + text[end:]
    if os.path.exists(DESIGN):
        text = open(DESIGN, encoding="utf-8").read()
        begin, end = text.find(MAPPING_BEGIN), text.find(MAPPING_END)
        if begin >= 0 and end > begin:
            outputs[DESIGN] = text[: begin + len(MAPPING_BEGIN)] + "\n\n" + render_mapping(data) + "\n\n" + text[end:]

    failed = False
    for path, text in outputs.items():
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if current == text:
            continue
        if arguments.check:
            print(f"stale: {os.path.relpath(path, REPOSITORY)}", file=sys.stderr)
            failed = True
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as file:
                file.write(text)
            print(f"wrote {os.path.relpath(path, REPOSITORY)}")

    statuses = Counter(item["status"] for item in data["items"])
    print(f"items: {dict(statuses)}; unresolved references: {len(data['unresolved_references'])}; duplicate keys: {len(data['duplicate_keys'])}")
    if arguments.check and (data["unresolved_references"] or data["duplicate_keys"]):
        failed = True
    if failed:
        sys.exit(1)


if __name__ == "__main__":
    main()
