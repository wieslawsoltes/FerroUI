"""Generate the editor's compressed simple-case tables from pinned Unicode data."""

import argparse
import hashlib
from pathlib import Path


SOURCE_SHA256 = "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c"
TARGET = Path(__file__).resolve().parents[2] / "src/FerroUI.Edit.Core/unicode_case/data.rs"


def runs(entries):
    index = 0
    while index < len(entries):
        start, delta = entries[index]
        end = start
        stride = 1
        if index + 1 < len(entries):
            next_point, next_delta = entries[index + 1]
            if next_delta == delta and next_point - start == 2:
                stride = 2
        index += 1
        while index < len(entries) and entries[index] == (end + stride, delta):
            end += stride
            index += 1
        yield start, end, stride, delta


def generate(source):
    upper, lower, letters = [], [], []
    for line in source.decode("utf-8").splitlines():
        fields = line.split(";")
        point = int(fields[0], 16)
        for table, field in [(upper, fields[12]), (lower, fields[13])]:
            if field:
                mapped = int(field, 16)
                if (point > 0xffff) != (mapped > 0xffff):
                    raise ValueError(f"Case mapping changes UTF-16 length at U+{point:04X}")
                table.append((point, mapped - point))
        if fields[2] == "Lu" and point <= 0xffff:
            letters.append((point, 0))

    output = [
        "// Generated by scripts/edit-port/generate_case_data.py from UnicodeData 17.0.0.",
        "// Unicode data copyright and permission notice appear in this crate's NOTICE.md.",
        "",
        "// Inclusive start and end, source stride, and signed target delta.",
    ]
    for name, entries in [("UPPER", upper), ("LOWER", lower)]:
        output.append(f"pub(super) const {name}: &[(u32, u32, u32, i32)] = &[")
        output.extend(
            f"    (0x{start:x}, 0x{end:x}, {stride}, {delta}),"
            for start, end, stride, delta in runs(entries)
        )
        output.extend(["];", ""])
    output.extend([
        "// BMP uppercase letters (general category Lu), used for UTF-16 case inversion.",
        "pub(super) const UPPERCASE_LETTERS: &[(u16, u16, u16)] = &[",
    ])
    output.extend(
        f"    (0x{start:x}, 0x{end:x}, {stride}),"
        for start, end, stride, _ in runs(letters)
    )
    output.extend(["];", ""])
    return "\n".join(output)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("unicode_data", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = args.unicode_data.read_bytes()
    if hashlib.sha256(source).hexdigest() != SOURCE_SHA256:
        parser.error("expected the pinned Unicode 17.0.0 UnicodeData.txt")
    table = generate(source)
    if args.check:
        if TARGET.read_text(encoding="utf-8") != table:
            parser.error("the checked-in casing tables are out of date")
    else:
        print(table, end="")


if __name__ == "__main__":
    main()
