"""Extract collation-ignorable scalars and prefix boundaries from ICU root data."""

import argparse
import hashlib
import re
from itertools import groupby
from pathlib import Path


SOURCE_SHA256 = "d7cdfab860bf94c6f470c1fae39b81619a12f3a51f80d7cad1ba08404dec3de6"
TARGET = Path(__file__).resolve().parents[2] / "src/FerroUI.Edit.Core/completion/collation_ignorables.rs"


def generate(source):
    table = source.decode("utf-8")
    # A singleton with exactly one empty collation element has no weight at
    # any level. Prefix mappings, contractions and expansions stay excluded.
    ignorable = re.findall(r"^([0-9A-F]+);[ \t]*\[,,\][ \t]*(?:#.*)?$", table, re.MULTILINE)
    # A prefix stops before the next primary element. A secondary accent
    # without a primary weight is part of the preceding collation element.
    secondary = re.findall(r"^([0-9A-F]+);[ \t]*\[, [0-9A-F][0-9A-F ]*,", table, re.MULTILINE)
    output = [
        "// Generated by scripts/edit-port/generate_collation_ignorables.py from ICU 78.1 FractionalUCA.txt.",
        "// Unicode data copyright and permission notice appear in this crate's NOTICE.md.",
        "",
    ]
    for entries, constant in [(ignorable, "IGNORABLE"), (secondary, "SECONDARY_WITHOUT_PRIMARY")]:
        points = sorted({int(entry, 16) for entry in entries})
        output.append(f"const {constant}: &[(u32, u32)] = &[")
        for _, run in groupby(enumerate(points), key=lambda indexed: indexed[1] - indexed[0]):
            group = [point for _, point in run]
            output.append(f"    (0x{group[0]:x}, 0x{group[-1]:x}),")
        output.extend(["];", ""])
    output.extend([
        "pub(super) fn contains(character: char) -> bool {",
        "    in_ranges(IGNORABLE, character)",
        "}",
        "",
        "pub(super) fn has_secondary_without_primary(character: char) -> bool {",
        "    in_ranges(SECONDARY_WITHOUT_PRIMARY, character)",
        "}",
        "",
        "fn in_ranges(ranges: &[(u32, u32)], character: char) -> bool {",
        "    let point = u32::from(character);",
        "    let index = ranges.partition_point(|&(_, end)| end < point);",
        "    ranges.get(index).is_some_and(|&(start, _)| start <= point)",
        "}",
        "",
    ])
    return "\n".join(output)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("fractional_uca", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = args.fractional_uca.read_bytes()
    if hashlib.sha256(source).hexdigest() != SOURCE_SHA256:
        parser.error("expected the pinned ICU 78.1 FractionalUCA.txt")
    table = generate(source)
    if args.check:
        if TARGET.read_text(encoding="utf-8") != table:
            parser.error("the checked-in collation-ignorable table is out of date")
    else:
        print(table, end="")


if __name__ == "__main__":
    main()
