#!/usr/bin/env python3
"""Generate Material resources from the pinned AndroidX token extraction.

No network access is needed. Use --check in CI. The reference data records the
upstream revision; numeric values are never inferred from the WinUI theme.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
THEME = ROOT / "src/FerroUI.Themes.Material"
DATA = json.loads(Path(__file__).with_name("reference-tokens.json").read_text())
COMPATIBILITY = json.loads(Path(__file__).with_name("compatibility-map.json").read_text())
HEADER = """<!-- Generated by scripts/material-theme/generate.py.
  AndroidX Compose Material3 1.5.0-beta02, e4d933c98df7baa7ea2b83eea6e086915961e0ff.
  Token definitions: Copyright The Android Open Source Project; Apache-2.0.
  See NOTICE.md. Do not edit generated values by hand. -->
<ResourceDictionary xmlns="https://github.com/ferroui"
                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"
                    xmlns:sys="using:System"
                    x:ClassModifier="internal">
"""


def resource(kind: str, key: str, value: str | float, indent: str = "  ") -> str:
    return f'{indent}<{kind} x:Key="{key}">{value}</{kind}>\n'


def colors() -> str:
    result = HEADER + "  <ResourceDictionary.ThemeDictionaries>\n"
    for variant, name in (("Default", "dark"), ("Dark", "dark"), ("Light", "light")):
        result += f'    <ResourceDictionary x:Key="{variant}">\n'
        scheme = dict(DATA[name])
        if name == "light": scheme.update(DATA["expressive_light_overrides"])
        for role, value in scheme.items():
            result += resource("Color", f"Material{role}Color", value, "      ")
            result += f'      <SolidColorBrush x:Key="Material{role}Brush" Color="{{DynamicResource Material{role}Color}}" />\n'
            for state, opacity in (("Hover", .08), ("Focus", .10), ("Pressed", .10), ("Dragged", .16)):
                result += f'      <SolidColorBrush x:Key="Material{role}{state}Brush" Color="{{DynamicResource Material{role}Color}}" Opacity="{opacity}" />\n'
        for key, role, opacity in (("DisabledContainer", "OnSurface", .10), ("DisabledContent", "OnSurfaceVariant", .38), ("DisabledOnSurface", "OnSurface", .38), ("DisabledOutline", "OnSurface", .12), ("OutlinedButtonDisabledOutline", "OutlineVariant", .10), ("ChipDisabledContainer", "OnSurface", .12), ("SegmentedButtonDisabledOutline", "Outline", .12), ("DisabledField", "OnSurface", .04), ("TextFieldDisabledContainer", "OnSurface", .04), ("ModalScrim", "Scrim", .32)):
            result += f'      <SolidColorBrush x:Key="Material{key}Brush" Color="{{DynamicResource Material{role}Color}}" Opacity="{opacity}" />\n'
        result += "    </ResourceDictionary>\n"
    return result + "  </ResourceDictionary.ThemeDictionaries>\n</ResourceDictionary>\n"


def typography() -> str:
    tokens = DATA["tokens"]["TypeScaleTokens"]
    result = HEADER + resource("FontFamily", "MaterialFontFamily", "fonts:MaterialRoboto#Roboto, Roboto, $Default")
    weights = {"WeightRegular": "Normal", "WeightMedium": "Medium", "WeightBold": "Bold"}
    for role in (key[:-4] for key in tokens if key.endswith("Size")):
        size, height, tracking = (re.sub(r"\.sp$|sp$", "", str(tokens[role + suffix])) for suffix in ("Size", "LineHeight", "Tracking"))
        weight = weights[tokens[role + "Weight"].split(".")[-1]]
        for suffix, value in (("FontSize", size), ("LineHeight", height), ("LetterSpacing", tracking)):
            result += resource("x:Double", f"Material{role}{suffix}", value)
        result += resource("FontWeight", f"Material{role}FontWeight", weight)
        result += f'''  <ControlTheme x:Key="Material{role}" TargetType="TextBlock">
    <Setter Property="FontFamily" Value="{{DynamicResource MaterialFontFamily}}" />
    <Setter Property="Foreground" Value="{{DynamicResource MaterialOnSurfaceBrush}}" />
    <Setter Property="FontSize" Value="{size}" />
    <Setter Property="LineHeight" Value="{height}" />
    <Setter Property="LetterSpacing" Value="{tracking}" />
    <Setter Property="FontWeight" Value="{weight}" />
    <Setter Property="TextWrapping" Value="Wrap" />
  </ControlTheme>
'''
    return result + "</ResourceDictionary>\n"


def metrics() -> str:
    result = HEADER
    for key, radius in (("None", 0), ("ExtraSmall", 4), ("Small", 8), ("Medium", 12), ("Large", 16), ("LargeIncreased", 20), ("ExtraLarge", 28), ("ExtraLargeIncreased", 32), ("ExtraExtraLarge", 48), ("Full", 9999)):
        result += resource("CornerRadius", f"MaterialShape{key}", radius)
    for key, value in (("MinimumTouchTarget",48), ("IconSize",24), ("ButtonHeight",40), ("TextFieldHeight",56), ("SearchBarHeight",56), ("NavigationBarHeight",64), ("NavigationBarTallHeight",80), ("NavigationRailWidth",96), ("NavigationRailNarrowWidth",80), ("NavigationDrawerWidth",360), ("ListItemHeight",56), ("ListItemTwoLineHeight",72), ("ListItemThreeLineHeight",88), ("HoverStateOpacity",.08), ("FocusStateOpacity",.10), ("PressedStateOpacity",.10), ("DraggedStateOpacity",.16), ("DisabledContentOpacity",.38), ("DisabledContainerOpacity",.10)):
        result += resource("x:Double", f"Material{key}", value)
    # Android elevation is a physical z-distance; these two-shadow fallbacks are
    # explicit cross-renderer approximations, not a claim of Android shadow parity.
    shadows = ["0 0 0 0 Transparent", "0 1 2 0 #4D000000, 0 1 3 1 #26000000", "0 1 2 0 #4D000000, 0 2 6 2 #26000000", "0 1 3 0 #4D000000, 0 4 8 3 #26000000", "0 2 3 0 #4D000000, 0 6 10 4 #26000000", "0 4 4 0 #4D000000, 0 8 12 6 #26000000"]
    for level, (elevation, shadow) in enumerate(zip((0,1,3,6,8,12), shadows)):
        result += resource("x:Double", f"MaterialElevation{level}", elevation)
        result += resource("BoxShadows", f"MaterialElevation{level}BoxShadow", shadow)
        result += f'  <StaticResource x:Key="MaterialElevationLevel{level}" ResourceKey="MaterialElevation{level}BoxShadow" />\n'
    # Motion values are replaced by MaterialTheme with analytic spring easings
    # before attaching the theme. These permit independent document previews.
    for role, duration in (("FastEffects",.15),("DefaultEffects",.25),("SlowEffects",.35),("FastSpatial",.35),("DefaultSpatial",.5),("SlowSpatial",.7)):
        result += resource("sys:TimeSpan", f"MaterialMotion{role}Duration", f"0:0:{duration}")
        result += f'  <CubicEaseOut x:Key="MaterialMotion{role}Easing" />\n'
    result += resource("x:Boolean", "MaterialReducedMotion", "False")
    return result + "</ResourceDictionary>\n"


def scheme_rs() -> str:
    roles = list(DATA["light"])
    result = '''// Generated by scripts/material-theme/generate.py. AndroidX token provenance: NOTICE.md.
//! Complete Material color roles and immutable light/dark schemes.
//! Accepts complete Android/Material Theme Builder palettes without approximating HCT in RGB.
use ferroui_base::controls::ResourceDictionary;
use ferroui_base::media::{Color, IBrush};
use ferroui_base::media::immutable::ImmutableSolidColorBrush;
use ferroui_base::metadata::into_markup_value;
use ferroui_base::Ref;
use std::rc::Rc;

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
#[repr(usize)]
pub enum MaterialColorRole {
'''
    result += "".join(f"    {r},\n" for r in roles) + "}\n\nimpl MaterialColorRole {\n"
    result += f"    pub const ALL: [Self; {len(roles)}] = [\n" + "".join(f"        Self::{r},\n" for r in roles) + "    ];\n"
    result += "    pub const fn name(self) -> &'static str { match self {\n" + "".join(f'        Self::{r} => "{r}",\n' for r in roles) + "    } }\n}\n\n"
    result += f'''#[derive(Clone, Debug, PartialEq, Eq)]
pub struct MaterialColorScheme {{
    colors: [Color; {len(roles)}],
}}

impl MaterialColorScheme {{
    /// All roles are required, in MaterialColorRole::ALL order.
    pub const fn new(colors: [Color; {len(roles)}]) -> Self {{ Self {{ colors }} }}
    pub fn color(&self, role: MaterialColorRole) -> Color {{ self.colors[role as usize] }}
    pub fn set_color(&mut self, role: MaterialColorRole, color: Color) {{ self.colors[role as usize] = color; }}
    pub fn with_color(mut self, role: MaterialColorRole, color: Color) -> Self {{ self.set_color(role, color); self }}
'''
    for variant in ("light", "dark"):
        result += f"    pub const fn {variant}() -> Self {{ Self {{ colors: [\n"
        result += "".join(f'        Color::from_uint32(0xFF{DATA[variant][r][1:]}), // {r}\n' for r in roles)
        result += "    ] } }\n"
    result += "    /// Native MaterialExpressiveTheme light baseline, including its four tone-30 container foregrounds.\n"
    result += "    pub const fn expressive_light() -> Self {\n        let mut scheme = Self::light();\n"
    for role, color in DATA["expressive_light_overrides"].items():
        result += f"        scheme.colors[MaterialColorRole::{role} as usize] = Color::from_uint32(0xFF{color[1:]});\n"
    result += "        scheme\n    }\n"
    result += '''    /// A fresh dictionary permits atomic replacement: no frame observes half a palette.
    pub fn resources(&self) -> Ref<ResourceDictionary> {
        let dictionary = ResourceDictionary::new();
        for role in MaterialColorRole::ALL {
            let color = self.color(role);
            dictionary.set(format!("Material{}Color", role.name()), into_markup_value(color));
            self.add_brush(&dictionary, &format!("Material{}Brush", role.name()), role, 1.0);
            for (state, opacity) in [("Hover", 0.08), ("Focus", 0.10), ("Pressed", 0.10), ("Dragged", 0.16)] {
                self.add_brush(&dictionary, &format!("Material{}{state}Brush", role.name()), role, opacity);
            }
        }
        for (key, role, opacity) in [
            ("MaterialDisabledContainerBrush", MaterialColorRole::OnSurface, 0.10),
            ("MaterialDisabledContentBrush", MaterialColorRole::OnSurfaceVariant, 0.38),
            ("MaterialDisabledOnSurfaceBrush", MaterialColorRole::OnSurface, 0.38),
            ("MaterialDisabledOutlineBrush", MaterialColorRole::OnSurface, 0.12),
            ("MaterialOutlinedButtonDisabledOutlineBrush", MaterialColorRole::OutlineVariant, 0.10),
            ("MaterialChipDisabledContainerBrush", MaterialColorRole::OnSurface, 0.12),
            ("MaterialSegmentedButtonDisabledOutlineBrush", MaterialColorRole::Outline, 0.12),
            ("MaterialDisabledFieldBrush", MaterialColorRole::OnSurface, 0.04),
            ("MaterialTextFieldDisabledContainerBrush", MaterialColorRole::OnSurface, 0.04),
            ("MaterialModalScrimBrush", MaterialColorRole::Scrim, 0.32),
        ] { self.add_brush(&dictionary, key, role, opacity); }
        install_compatibility(self, &dictionary);
        dictionary
    }
    fn add_brush(&self, dictionary: &Ref<ResourceDictionary>, key: &str, role: MaterialColorRole, opacity: f64) {
        let brush: Rc<dyn IBrush> = Rc::new(ImmutableSolidColorBrush::with_opacity(self.color(role), opacity));
        dictionary.set(key, into_markup_value(brush));
    }
}
impl Default for MaterialColorScheme { fn default() -> Self { Self::light() } }
'''
    result += '\nfn install_compatibility(scheme: &MaterialColorScheme, dictionary: &Ref<ResourceDictionary>) {\n'
    for key, entry in COMPATIBILITY.items():
        role, opacity = entry['role'], float(entry['opacity'])
        if entry['kind'] == 'Brush':
            result += f'    scheme.add_brush(dictionary, "{key}", MaterialColorRole::{role}, {opacity});\n'
        else:
            result += f'    {{ let c = scheme.color(MaterialColorRole::{role}); dictionary.set("{key}", into_markup_value(Color::from_argb((c.a as f64 * {opacity}).round() as u8, c.r, c.g, c.b))); }}\n'
    result += '}\n'
    return result


def compatibility() -> str:
    result = HEADER
    # Color/brush aliases belong to each runtime color-scheme dictionary. A root
    # brush would shadow that dictionary and share one mutable color across windows
    # requesting different variants. Only variant-independent metrics live here.
    for key, kind, value in (
        ('ContentControlThemeFontFamily','FontFamily','fonts:MaterialRoboto#Roboto, Roboto, $Default'),
        ('ControlContentThemeFontSize','x:Double',14), ('ContentControlFontSize','x:Double',14),
        ('ControlCornerRadius','CornerRadius',12), ('OverlayCornerRadius','CornerRadius',12),
        ('ButtonPadding','Thickness','24,0'), ('ButtonBorderThemeThickness','Thickness','0'),
        ('TextControlThemeMinHeight','x:Double',56), ('ComboBoxMinHeight','x:Double',56),
        ('ListViewItemMinHeight','x:Double',56), ('MenuFlyoutItemMinHeight','x:Double',48),
        ('MenuFlyoutItemMinWidth','x:Double',112), ('TextControlThemePadding','Thickness','16,16'),
        ('FlyoutPresenterBorderThickness','Thickness','0'), ('FlyoutPresenterCornerRadius','CornerRadius',12),
        ('ThemeShadowFlyoutMargin','Thickness','8,4,8,12'), ('ThemeShadowSubMenuMargin','Thickness','8,4,8,12'),
        ('ThemeShadowToolTipMargin','Thickness','4'),
    ): result += resource(kind, key, value)
    for key, level in (('ThemeShadowFlyoutBoxShadow',2),('ThemeShadowSubMenuBoxShadow',2),('ThemeShadowToolTipBoxShadow',0)):
        result += f'  <StaticResource x:Key="{key}" ResourceKey="MaterialElevation{level}BoxShadow" />\n'
    return result + '</ResourceDictionary>\n'


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files = {"Resources/MaterialColors.xaml": colors(), "Resources/MaterialTypography.xaml": typography(), "Resources/MaterialMetrics.xaml": metrics(), "Resources/MaterialCompatibility.xaml": compatibility(), "color_scheme.rs": scheme_rs()}
    stale = []
    for name, content in files.items():
        path = THEME / name
        if args.check:
            if not path.exists() or path.read_text() != content: stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale: raise SystemExit("Stale Material generated files: " + ", ".join(stale))
    print(f"Material reference {DATA['upstream_release']}: {len(files)} generated files {'verified' if args.check else 'written'}")


if __name__ == "__main__": main()
