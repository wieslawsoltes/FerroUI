#!/usr/bin/env python3
"""Regenerate the embedded Gallery catalog from its immutable upstream source."""

import argparse
import hashlib
import json
import re
from pathlib import Path
import subprocess

SOURCE_COMMIT = "14061eeac21c38ae99f302edf3d9136d4f652c4c"


def literal(value):
    hashes = "#"
    while '"' + hashes in value:
        hashes += "#"
    return 'r' + hashes + '"' + value + '"' + hashes


def generate(source):
    commit = subprocess.check_output(["git", "-C", str(source), "rev-parse", "HEAD"], text=True).strip()
    if commit != SOURCE_COMMIT:
        raise ValueError(f"Expected Gallery {SOURCE_COMMIT}, found {commit}")
    dirty = subprocess.run(["git", "-C", str(source), "diff", "--quiet", "HEAD", "--", "catalog/windows-samples.json", "WinUIGallery"], check=False)
    if dirty.returncode != 0:
        raise ValueError("Pinned Gallery catalog/source files have local changes; restore the snapshot before generating")
    catalog_path = source / "catalog/windows-samples.json"
    catalog = json.loads(catalog_path.read_text(encoding="utf-8-sig"))
    metadata_path = source / "WinUIGallery/SampleSupport/Data/ControlInfoData.json"
    metadata = json.loads(metadata_path.read_text(encoding="utf-8-sig"))
    items = {item["UniqueId"]: item for group in metadata["Groups"] for item in group["Items"]}
    lines = [
        "// Generated by generate_catalog.py; do not edit by hand.",
        "// Source: microsoft/WinUI-Gallery@" + SOURCE_COMMIT,
        "// Catalog SHA-256: " + hashlib.sha256(catalog_path.read_bytes()).hexdigest(),
        "// Control metadata SHA-256: " + hashlib.sha256(metadata_path.read_bytes()).hexdigest(),
        "// Copyright (c) Microsoft Corporation. Licensed under the MIT License; see NOTICE.md.",
        "use crate::catalog::{CatalogEntry, DocumentationLink, SampleDefinition};",
        "#[rustfmt::skip]",
        "pub const SOURCE_COMMIT: &str = " + literal(SOURCE_COMMIT) + ";",
        "#[rustfmt::skip]",
        "pub static CATALOG: &[CatalogEntry] = &[",
    ]
    controls = sorted(catalog["controls"], key=lambda item: (item["gallery"]["group"]["title"], item["name"]))
    for item in controls:
        gallery = item["gallery"]
        original = items[gallery["uniqueId"]]
        image = original.get("ImagePath") or "ms-appx:///Assets/ControlImages/Placeholder.png"
        if not image.startswith("ms-appx:///"):
            raise ValueError(f"Unexpected image URI: {image}")
        lines.append("    CatalogEntry {")
        for key, value in [
            ("id", gallery["uniqueId"]), ("title", item["name"]),
            ("category", gallery["group"]["title"]), ("description", item["description"]),
            ("subtitle", original["Subtitle"]),
            ("image_uri", "ferres://WinUIGallery/" + image.removeprefix("ms-appx:///")),
            ("source", gallery["page"]), ("code_behind", gallery["codeBehind"]),
            ("search_index", " ".join([gallery["uniqueId"], item["name"], item["description"], gallery["group"]["title"], *item.get("curatedKeywords", [])]).lower()),
        ]:
            lines.append(f"        {key}: {literal(value)},")
        lines.append("        docs: &[")
        for link in item.get("docs", []):
            lines.append("            DocumentationLink { title: " + literal(link["title"]) + ", uri: " + literal(link["uri"]) + " },")
        lines.append("        ], samples: &[")
        for sample in item["samples"]:
            path = sample["gallery"]["source"]
            # The upstream catalog exports a preview after removing substitution
            # tokens. The source viewer and migration input retain the original
            # snippet sections so unresolved dependencies are never hidden.
            sections = {}
            section = None
            for line in (source / path).read_text(encoding="utf-8-sig").splitlines(keepends=True):
                if line.rstrip() in ("--- header", "--- xaml", "--- c#"):
                    section = line.rstrip()[4:]
                    sections[section] = []
                elif section is not None:
                    sections[section].append(line)
            lines.append("            SampleDefinition {")
            for key, value in [
                ("header", sample["header"]), ("source", path),
                ("source_sha256", hashlib.sha256((source / path).read_bytes()).hexdigest()),
                ("xaml", "".join(sections.get("xaml", [])).rstrip("\r\n")),
                ("code", "".join(sections.get("c#", [])).rstrip("\r\n")),
            ]:
                lines.append(f"                {key}: {literal(value)},")
            imports = sample.get("xmlnsImports", [])
            if isinstance(imports, dict):
                imports = [f'xmlns:{key}="{value}"' for key, value in imports.items()]
            lines.append("                namespace_imports: &[" + ", ".join(literal(value) for value in imports) + "],")
            lines.append("            },")
        lines.append("        ],\n    },")
    lines.append("];\n")
    return "\n".join(lines)


def generate_cats(source):
    path = source / "WinUIGallery/Samples/AutoSuggestBox/AutoSuggestBoxPage.xaml.cs"
    text = path.read_text(encoding="utf-8-sig")
    block = text[text.index("private List<string> Cats"):text.index("public AutoSuggestBoxPage()")]
    cats = re.findall(r'"([^"\n]+)"', block)
    if len(cats) != 97:
        raise ValueError("The pinned cat collection changed unexpectedly")
    lines = [
        "// Generated by generate_catalog.py; do not edit by hand.",
        "// Source: WinUIGallery/Samples/AutoSuggestBox/AutoSuggestBoxPage.xaml.cs",
        "// Source SHA-256: " + hashlib.sha256(path.read_bytes()).hexdigest(),
        "// Copyright (c) Microsoft Corporation; see NOTICE.md for the MIT license.",
        "pub(crate) const CATS: &[&str] = &[",
    ]
    lines.extend("    " + json.dumps(cat, ensure_ascii=False) + "," for cat in cats)
    lines.append("];\n")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("upstream", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = {"catalog_data.rs": generate(args.upstream), "cat_data.rs": generate_cats(args.upstream)}
    for name, generated in outputs.items():
        target = Path(__file__).parent / name
        if args.check:
            if not target.exists() or target.read_text() != generated:
                raise SystemExit(f"{name} differs; run generate_catalog.py without --check")
        else:
            target.write_text(generated)
    if args.check:
        print("Gallery catalog is reproducible: 126 pages, 350 source samples and 97 cat names")


if __name__ == "__main__":
    main()
