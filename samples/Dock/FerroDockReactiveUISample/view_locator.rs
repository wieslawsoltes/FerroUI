use ferrodock_model::core::IDockable;
use ferroui_base::{
    data::core::{ValueType, ValueTypes},
    BoxedValue, Ref,
};
use ferroui_controls::{
    templates::{IDataTemplate, ITemplateWithParam},
    Control, TextBlock,
};
use std::rc::{Rc, Weak};
/// The original sample's exact-type data template and static view factories.
pub struct ViewLocator {
    this: Weak<Self>,
}
impl PartialEq for ViewLocator {
    fn eq(&self, other: &Self) -> bool {
        std::ptr::eq(self, other)
    }
}
impl ViewLocator {
    /// Creates the original locator without runtime reflection or type discovery.
    pub fn new() -> Rc<Self> {
        Rc::new_cyclic(|this| Self { this: this.clone() })
    }
    /// Gets this instance as the original data-template interface.
    pub fn as_data_template(&self) -> Rc<dyn IDataTemplate> {
        self.this.upgrade().expect("the source locator is alive")
    }
    fn factory(data: &BoxedValue) -> Option<fn() -> Ref<Control>> {
        let dockable = ValueTypes::try_cast(data, ValueType::of::<Rc<dyn IDockable>>());
        let source = dockable
            .as_ref()
            .and_then(|value| value.downcast_ref::<Rc<dyn IDockable>>())
            .map(|model| model.clone().boxed_reference());
        // These are the exact factories generated by the source's pinned 0.1.0
        // convention: replace ViewModel with View, accepting direct user controls.
        macro_rules! factories {
            ($($model:ty=>$view:ty),*$(,)?)=>{$(
                if data.is::<Rc<$model>>() || source.as_ref().is_some_and(|value|value.is::<Rc<$model>>()) {
                    return Some(||<$view>::new().upcast());
                }
            )*};
        }
        factories!(
            crate::view_models::documents::DocumentViewModel=>crate::views::documents::DocumentView,
            crate::view_models::tools::Tool1ViewModel=>crate::views::tools::Tool1View,
            crate::view_models::tools::Tool2ViewModel=>crate::views::tools::Tool2View,
            crate::view_models::tools::Tool3ViewModel=>crate::views::tools::Tool3View,
            crate::view_models::tools::Tool4ViewModel=>crate::views::tools::Tool4View,
            crate::view_models::tools::Tool5ViewModel=>crate::views::tools::Tool5View,
            crate::view_models::tools::Tool6ViewModel=>crate::views::tools::Tool6View,
            crate::view_models::tools::Tool7ViewModel=>crate::views::tools::Tool7View,
            crate::view_models::tools::Tool8ViewModel=>crate::views::tools::Tool8View,
            crate::view_models::views::DashboardViewModel=>crate::views::views::DashboardView,
            crate::view_models::views::HomeViewModel=>crate::views::views::HomeView,
        );
        if data.is::<Rc<crate::view_models::MainWindowViewModel>>() {
            // The ORIGINAL generator emits this missing-view factory. Its
            // convention requests MainWindowView, which the source does not define.
            return Some(|| {
                let text = TextBlock::new();
                text.set_text(Some(
                    "Not Found: FerroDockReactiveUISample.Views.MainWindowView",
                ));
                text.upcast()
            });
        }
        None
    }
}
impl ITemplateWithParam<Option<BoxedValue>, Option<Ref<Control>>> for ViewLocator {
    fn build(&self, data: &Option<BoxedValue>) -> Option<Ref<Control>> {
        let data = data.as_ref()?;
        let factory = Self::factory(data).unwrap_or_else(|| {
            panic!(
                "Unable to create view for type: {}",
                ValueTypes::to_display_string(Some(data))
            )
        });
        Some(factory())
    }
}
impl IDataTemplate for ViewLocator {
    fn match_(&self, data: Option<&BoxedValue>) -> bool {
        data.is_some_and(|value| {
            ValueTypes::try_cast(value, ValueType::of::<Rc<dyn IDockable>>()).is_some()
                || Self::factory(value).is_some()
        })
    }
    fn as_any(&self) -> Option<&dyn std::any::Any> {
        Some(self)
    }
}
ferroui_base::ferro_markup_type!(class ViewLocator {
    namespace:"FerroDockReactiveUISample",this:Rc<ViewLocator>,handles:[ViewLocator,Rc<ViewLocator>,Option<Rc<ViewLocator>>],interfaces:[Rc<dyn IDataTemplate>],constructors:[()=>ViewLocator::new],
});
