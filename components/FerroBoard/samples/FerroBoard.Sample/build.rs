fn main() {
    ferroui_build::Build::from_env()
        .type_system(ferroui_build::TypeSystem::Model)
        .compile_group(ferroui_build::XamlGroup::new("compiled_app").class_document("App.xaml"))
        .compile_group(
            ferroui_build::XamlGroup::new("compiled_main_window").class_document("MainWindow.xaml"),
        )
        .compile_group(
            ferroui_build::XamlGroup::new("compiled_main_view").class_document("MainView.xaml"),
        )
        .compile_group(
            ferroui_build::XamlGroup::new("compiled_settings_panel")
                .class_document("SettingsPanel.xaml"),
        )
        .compile_group(
            ferroui_build::XamlGroup::new("compiled_shared_engine").documents(&[(
                "examples/SharedEngine.xaml",
                include_str!("examples/SharedEngine.xaml"),
            )]),
        )
        .compile_group(
            ferroui_build::XamlGroup::new("compiled_settings_views").documents(&[
                (
                    "views/settings/FieldToggle.xaml",
                    include_str!("views/settings/FieldToggle.xaml"),
                ),
                (
                    "views/settings/FieldSlider.xaml",
                    include_str!("views/settings/FieldSlider.xaml"),
                ),
                (
                    "views/settings/FieldCombo.xaml",
                    include_str!("views/settings/FieldCombo.xaml"),
                ),
                (
                    "views/settings/Header.xaml",
                    include_str!("views/settings/Header.xaml"),
                ),
                (
                    "views/settings/DataButtons.xaml",
                    include_str!("views/settings/DataButtons.xaml"),
                ),
                (
                    "views/settings/Footer.xaml",
                    include_str!("views/settings/Footer.xaml"),
                ),
                (
                    "views/settings/Languages.xaml",
                    include_str!("views/settings/Languages.xaml"),
                ),
            ]),
        )
        .run();
}
