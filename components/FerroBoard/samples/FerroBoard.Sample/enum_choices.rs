    pub fn value(self, settings: &KeyboardSettings) -> i32 {
        match self {
            Self::ThemeMode => settings.theme_mode().0,
            Self::OneHandedMode => settings.one_handed_mode().0,
            Self::SmartbarLayout => settings.smartbar_layout().0,
            Self::SpaceBarMode => settings.space_bar_mode().0,
            Self::UtilityKeyAction => settings.utility_key_action().0,
            Self::HintMode => settings.hint_mode().0,
            Self::SwipeUp => settings.swipe_up().0,
            Self::SwipeDown => settings.swipe_down().0,
            Self::SwipeLeft => settings.swipe_left().0,
            Self::SwipeRight => settings.swipe_right().0,
            Self::SpaceBarSwipeUp => settings.space_bar_swipe_up().0,
            Self::SpaceBarLongPress => settings.space_bar_long_press().0,
            Self::DeleteKeySwipeLeft => settings.delete_key_swipe_left().0,
            Self::EmojiSkinTone => settings.emoji_skin_tone().0,
        }
    }
    pub fn set_value(self, settings: &KeyboardSettings, value: i32) {
        match self {
            Self::ThemeMode => settings.set_theme_mode(ThemeMode(value)),
            Self::OneHandedMode => settings.set_one_handed_mode(OneHandedMode(value)),
            Self::SmartbarLayout => settings.set_smartbar_layout(SmartbarLayout(value)),
            Self::SpaceBarMode => settings.set_space_bar_mode(SpaceBarMode(value)),
            Self::UtilityKeyAction => settings.set_utility_key_action(UtilityKeyAction(value)),
            Self::HintMode => settings.set_hint_mode(KeyHintMode(value)),
            Self::SwipeUp => settings.set_swipe_up(SwipeAction(value)),
            Self::SwipeDown => settings.set_swipe_down(SwipeAction(value)),
            Self::SwipeLeft => settings.set_swipe_left(SwipeAction(value)),
            Self::SwipeRight => settings.set_swipe_right(SwipeAction(value)),
            Self::SpaceBarSwipeUp => settings.set_space_bar_swipe_up(SwipeAction(value)),
            Self::SpaceBarLongPress => settings.set_space_bar_long_press(SwipeAction(value)),
            Self::DeleteKeySwipeLeft => settings.set_delete_key_swipe_left(SwipeAction(value)),
            Self::EmojiSkinTone => settings.set_emoji_skin_tone(EmojiSkinTone(value)),
        }
    }
    pub fn selected_index(self, settings: &KeyboardSettings) -> i32 {
        self.items()
            .iter()
            .position(|(_, v)| *v == self.value(settings))
            .map_or(-1, |i| i as i32)
    }
    pub fn select(
        self,
        settings: &KeyboardSettings,
        index: i32,
        refreshing: bool,
    ) -> Result<(), ChoiceIndexError> {
        if refreshing || index < 0 {
            return Ok(());
        }
        let (_, value) = self.items().get(index as usize).ok_or(ChoiceIndexError {
            index,
            count: self.items().len(),
        })?;
        self.set_value(settings, *value);
        Ok(())
    }
