//! The public Rust paths the framework crates record for their registered
//! types (the generated `rust_paths.rs` of each crate), checked from outside
//! the crates. Not a test of upstream.
//!
//! `rust_paths_check.rs` names every recorded path as generated code would:
//! rustc compiling it proves the paths are public, and
//! `recorded_paths_name_the_registered_types` that each names the type it is
//! recorded for. `rust_paths_check_is_up_to_date` keeps the file equal to
//! what the registries hold; to regenerate it:
//!
//! ```text
//! cargo test -p ferroui-markup-xaml-tests --lib emitter::rust_paths_tests::regenerate_rust_paths_check -- --ignored --exact
//! ```

use ferroui_base::metadata::MarkupType;
use ferroui_base::TypeInfo;

use super::rust_paths_check;
use crate::support::app::xaml_test_base;

const CHECK_PATH: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/emitter/rust_paths_check.rs");

/// The text of `rust_paths_check.rs` for what the registries hold.
fn check_file() -> String {
    let mut classes = TypeInfo::all_rust_paths();
    classes.sort_by_key(|(_, path)| *path);
    let mut types = MarkupType::all_rust_paths();
    types.sort_by_key(|(_, path, _)| *path);
    let mut text = String::new();
    text.push_str("// @generated by emitter::rust_paths_tests::regenerate_rust_paths_check. Do not edit.\n");
    text.push_str("//! Every public Rust path the framework crates record, named from outside them.\n\n");
    text.push_str("/// The classes with a recorded path, by that path.\n");
    text.push_str("pub fn classes() -> Vec<(&'static ::ferroui_base::TypeInfo, &'static str)> {\n    vec![\n");
    for (_, path) in &classes {
        text.push_str(&format!("        (<::{path} as ::ferroui_base::StaticType>::TYPE, {path:?}),\n"));
    }
    text.push_str("    ]\n}\n\n");
    text.push_str("/// The markup types with a recorded path, by that path (a contract as `dyn`).\n");
    text.push_str("pub fn markup_types() -> Vec<(&'static ::ferroui_base::metadata::MarkupType, &'static str, bool)> {\n    vec![\n");
    for (_, path, is_trait) in &types {
        let dyn_ = if *is_trait { "dyn " } else { "" };
        text.push_str(&format!(
            "        (<{dyn_}::{path} as ::ferroui_base::metadata::MarkupTyped>::MARKUP, {path:?}, {is_trait}),\n"
        ));
    }
    text.push_str("    ]\n}\n");
    text
}

#[test]
fn rust_paths_check_is_up_to_date() {
    let _base = xaml_test_base();
    let expected = check_file();
    assert!(
        include_str!("rust_paths_check.rs") == expected,
        "emitter/rust_paths_check.rs is not what the registries hold. Regenerate it:\n  cargo test -p \
         ferroui-markup-xaml-tests --lib emitter::rust_paths_tests::regenerate_rust_paths_check -- --ignored --exact"
    );
}

#[test]
#[ignore = "writes emitter/rust_paths_check.rs; run it to regenerate the checked-in file"]
fn regenerate_rust_paths_check() {
    let _base = xaml_test_base();
    std::fs::write(CHECK_PATH, check_file()).expect("emitter/rust_paths_check.rs can be written");
}

#[test]
fn recorded_paths_name_the_registered_types() {
    let _base = xaml_test_base();
    let classes = rust_paths_check::classes();
    let types = rust_paths_check::markup_types();
    for (class, path) in &classes {
        assert_eq!(class.rust_path(), Some(*path), "{path} names {}", class.full_name());
    }
    for (markup, path, is_trait) in &types {
        assert_eq!(markup.rust_path(), Some(*path), "{path} names {}", markup.full_name());
        assert_eq!(markup.rust_path_is_trait(), *is_trait, "{path} names a trait: {is_trait}");
    }
    println!("{} classes and {} markup types have a public Rust path", classes.len(), types.len());
    assert!(!classes.is_empty() && !types.is_empty());
}
