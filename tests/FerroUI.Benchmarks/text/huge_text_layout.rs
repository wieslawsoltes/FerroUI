pub struct HugeTextLayout {
    wrap: bool,
    trim: bool,
    many_small_strings: Vec<String>,
    /// The texts in UTF-16, as the strings of upstream are: a layout takes
    /// them without transcoding.
    many_small_texts: Vec<ReadOnlyMemory<u16>>,
    text: ReadOnlyMemory<u16>,
    emojis_text: ReadOnlyMemory<u16>,
    /// Disposed when the benchmark is dropped (the fields drop in the order
    /// of their declaration).
    _app: UnitTestApplicationScope,
}

impl HugeTextLayout {
    fn random_string(rand: &mut Random, length: i32) -> String {
        const CHARS: &[u8] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789&?%$@";
        (0..length).map(|_| char::from(CHARS[rand.next_max(CHARS.len() as i32) as usize])).collect()
    }

    pub fn new(wrap: bool, trim: bool) -> Self {
        let mut rand = Random::new(SEED);
        let many_small_strings: Vec<String> = (0..1000)
            .map(|_| {
                let length = rand.next_range(2, 15);
                Self::random_string(&mut rand, length)
            })
            .collect();

        let mut test_services = TestServices::styled_window();

        if USE_SKIA {
            test_services = test_services
                .with_text_shaper_impl(Rc::new(HarfBuzzTextShaper::new()))
                .with_font_manager_impl(Rc::new(FontManagerImpl::new()));
        }

        let app = UnitTestApplication::start(test_services);

        let many_small_texts =
            many_small_strings.iter().map(|text| ReadOnlyMemory::<u16>::from_str(text)).collect();

        Self {
            wrap,
            trim,
            many_small_strings,
            many_small_texts,
            text: ReadOnlyMemory::<u16>::from_str(TEXT),
            emojis_text: ReadOnlyMemory::<u16>::from_str(EMOJIS_TEXT),
            _app: app,
        }
    }

    pub fn build_text_layout(&self) -> TextLayout {
        self.make_layout(&self.text)
    }

    pub fn build_emojis_text_layout(&self) -> TextLayout {
        self.make_layout(&self.emojis_text)
    }

    pub fn build_many_small_texts(&self) -> Vec<TextLayout> {
        let mut results = Vec::with_capacity(self.many_small_texts.len());

        for text in &self.many_small_texts {
            results.push(self.make_layout(text));
        }

        results
    }

    pub fn virtualize_text_blocks(&self) {
        let mut blocks: Vec<Ref<TextBlock>> = Vec::with_capacity(10);
        for _ in 0..10 {
            let block = TextBlock::new();
            block.set_width(120.0);
            block.set_height(32.0);
            blocks.push(block);
        }

        let mut j = 0;
        for string in &self.many_small_strings {
            blocks[j].set_text(Some(string.as_str()));
            blocks[j].measure(Size::new(200.0, 200.0));

            j = if j < blocks.len() - 1 { j + 1 } else { 0 };
        }
    }

    fn make_layout(&self, text: &ReadOnlyMemory<u16>) -> TextLayout {
        let wrapping = if self.wrap { TextWrapping::WrapWithOverflow } else { TextWrapping::NoWrap };
        let trimming = if self.trim { <dyn TextTrimming>::character_ellipsis() } else { <dyn TextTrimming>::none() };
        let layout = TextLayout::from_utf16(
            text.clone(),
            Typeface::default_typeface(),
            TextLayoutOptions {
                font_size: 12.0,
                foreground: Some(Brushes::black()),
                max_width: 120.0,
                text_trimming: Some(trimming),
                text_wrapping: wrapping,
                ..TextLayoutOptions::default()
            },
        );
        layout.dispose();
        layout
    }
}

pub fn register(registry: &mut Registry) {
    let mut class = registry.class("text", "HugeTextLayout").min_iteration_time(150);
    for wrap in [false, true] {
        for trim in [false, true] {
            let parameters = format!("Wrap={wrap}, Trim={trim}");
            class.benchmark(
                "build_text_layout",
                parameters.clone(),
                move || HugeTextLayout::new(wrap, trim),
                |b| b.build_text_layout(),
            );
            class.benchmark(
                "build_emojis_text_layout",
                parameters.clone(),
                move || HugeTextLayout::new(wrap, trim),
                |b| b.build_emojis_text_layout(),
            );
            class.benchmark(
                "build_many_small_texts",
                parameters.clone(),
                move || HugeTextLayout::new(wrap, trim),
                |b| b.build_many_small_texts(),
            );
            class.benchmark(
                "virtualize_text_blocks",
                parameters,
                move || HugeTextLayout::new(wrap, trim),
                |b| b.virtualize_text_blocks(),
            );
        }
    }
}

