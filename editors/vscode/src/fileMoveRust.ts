import { readFile, realpath } from 'node:fs/promises';
import * as path from 'node:path';
import * as vscode from 'vscode';
import type { FileMoveRustResolution, GeneratedRustRename } from './fileMoveProtocol';
import { workspaceSourceUri } from './workspacePaths';

export async function resolveFileMoveRust(renames: readonly GeneratedRustRename[], signal?: AbortSignal): Promise<FileMoveRustResolution[]> {
    const generated = new Set(await Promise.all(renames.map(async rename => path.dirname(await physicalFile(vscode.Uri.parse(rename.uri, true))))));
    const resolutions: FileMoveRustResolution[] = [];
    for (const rename of renames) {
        signal?.throwIfAborted();
        const uri = vscode.Uri.parse(rename.uri, true);
        const source = await vscode.workspace.openTextDocument(uri);
        const position = new vscode.Position(rename.position.line, rename.position.character);
        const declaration = new vscode.Range(position, position.translate(0, rename.oldName.length));
        if (source.isDirty || !declaration.isEqual(source.validateRange(declaration)) || source.getText(declaration) !== rename.oldName) {
            throw new Error('Rebuild the package XAML schema to refresh the generated Rust declaration.');
        }
        const version = source.version;
        const edit = await vscode.commands.executeCommand<vscode.WorkspaceEdit | undefined>(
            'vscode.executeDocumentRenameProvider', uri, position, rename.newName,
        );
        signal?.throwIfAborted();
        if (source.isClosed || source.version !== version) throw new Error('The generated Rust declaration changed. Review the move again.');
        let verified = false;
        const documents: FileMoveRustResolution['documents'] = [];
        const declarationFile = await physicalFile(uri);
        for (const [file, edits] of edit?.entries() ?? []) {
            const physical = await physicalFile(file);
            if (generated.has(path.dirname(physical))) {
                if (physical === declarationFile) {
                    verified ||= edits.some(item => item.range.isEqual(declaration) && item.newText === rename.newName);
                }
                continue;
            }
            const authored = await workspaceSourceUri(file);
            if (!authored || !authored.path.toLowerCase().endsWith('.rs')) {
                throw new Error('The Rust rename reaches outside the authored workspace. Open the consumer packages before reviewing this move.');
            }
            const key = authored.toString();
            const live = vscode.workspace.textDocuments.find(document => !document.isClosed && document.uri.toString() === key);
            const version = live?.isDirty ? live.version : -1;
            const saved = version < 0 ? await readFile(authored.fsPath, 'utf8') : undefined;
            const bom = saved?.startsWith('\uFEFF') ? 1 : 0;
            if (saved !== undefined && live && (live.isDirty || live.getText() !== saved.slice(bom))) {
                throw new Error('The Rust reference buffer changed. Review the move again.');
            }
            const position = (point: vscode.Position) => ({
                line: point.line, character: point.character + (point.line === 0 ? bom : 0),
            });
            documents.push({ uri: key, version, edits: edits.map(item => ({
                range: { start: position(item.range.start), end: position(item.range.end) },
                newText: item.newText,
            })) });
        }
        if (!verified) {
            throw new Error(`Rust could not resolve ${rename.oldName} in the generated XAML module. Wait for rust-analyzer to load this Cargo target and try again.`);
        }
        resolutions.push({ rename, documents });
    }
    return resolutions;
}

export function isCompiledXamlRust(document: vscode.TextDocument): boolean {
    return document.lineAt(0).text.startsWith('// @generated by the Rust emitter of ferroui-markup-xaml-loader ');
}

async function physicalFile(uri: vscode.Uri): Promise<string> {
    if (uri.scheme !== 'file') throw new Error('The Rust rename requires file-backed source.');
    const file = await realpath(uri.fsPath);
    return process.platform === 'win32' ? file.toLowerCase() : file;
}
