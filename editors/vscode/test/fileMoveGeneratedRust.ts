import { strict as assert } from 'node:assert';
import * as vscode from 'vscode';
import type { FileMovePlan } from '../src/fileMoveProtocol';
import type { ProjectMetadata } from '../src/reloadProcess';
import type { McpFixture } from './mcp';
import { until } from './wait';

export async function verifyGeneratedRustMove({ invoke, content }: McpFixture): Promise<void> {
    const root = vscode.Uri.joinPath(vscode.workspace.workspaceFolders![0].uri, 'Generated XAML move');
    const uri = (file: string) => vscode.Uri.joinPath(root, file);
    const write = (file: string, value: string) => vscode.workspace.fs.writeFile(uri(file), Buffer.from(value));
    const directory = uri('target/schema');
    const generated = uri('target/schema/xaml/views.rs');
    const manifest = uri('Cargo.toml');
    const library = uri('lib.rs');
    const from = 'Views/Card.xaml';
    const to = 'Views/Archive/Customer.xaml';
    const oldName = 'build_views_card_xaml';
    const newName = 'build_views_archive_customer_xaml';
    const source = `const LABEL: &str = "🎨"; use views::${oldName} as card;\r\nconst CARD: &str = include_str!("${from}");\r\nfn user() { card(); unrelated::${oldName}(); }\r\n`;
    const expected = source.replace(`views::${oldName}`, `views::${newName}`).replace(from, to);
    const generatedSource = `// @generated by the Rust emitter of ferroui-markup-xaml-loader (rust_emitter::generate_file).\npub fn ${oldName}() {}\n`;
    await vscode.workspace.fs.createDirectory(uri('Views/Archive'));
    await vscode.workspace.fs.createDirectory(uri('target/schema/xaml'));
    await Promise.all([
        write('Cargo.toml', '[package]\nname="generated-xaml-move"\nversion="0.1.0"\nedition="2024"\n[lib]\npath="lib.rs"\n'),
        write('build.rs', `use ferroui_build::{Build, XamlGroup};\nfn main() { Build::from_env().compile_group(XamlGroup::new("views").documents(&[("${from}", include_str!("${from}"))])).run(); }\n`),
        write('lib.rs', source), write(from, '<Border xmlns="https://github.com/ferroui" />'),
        write('target/schema/xaml/views.rs', generatedSource),
        write('target/schema/generated_xaml_move.xamlmeta', JSON.stringify({ name: 'generated_xaml_move', crate_name: 'generated_xaml_move', documents: [], dependencies: [] })),
        write('target/schema/xaml-symbols.json', JSON.stringify({
            version: 1, manifest: manifest.fsPath, groups: [{ module: 'views', kind: 'documents', discovery_root: null, members: [{ key: from, symbol: oldName, public: true }] }],
        })),
    ]);
    const extension = vscode.extensions.getExtension<{ publishProjectMetadata(metadata: ProjectMetadata): void }>('FerroUI.ferroui')!;
    (await extension.activate()).publishProjectMetadata({ manifest: manifest.fsPath, directories: [directory.fsPath], package: 'generated-xaml-move' });
    const document = await vscode.workspace.openTextDocument(library);
    const provider = vscode.languages.registerRenameProvider({ language: 'rust', scheme: 'file', pattern: new vscode.RelativePattern(directory, 'xaml/views.rs') }, {
        provideRenameEdits(file, at, name) {
            assert.equal(file.uri.fsPath, generated.fsPath);
            assert.equal(file.getText(new vscode.Range(at, at.translate(0, oldName.length))), oldName);
            assert.equal(name, newName);
            const edit = new vscode.WorkspaceEdit();
            edit.replace(generated, new vscode.Range(at, at.translate(0, oldName.length)), name);
            const start = document.getText().indexOf(oldName);
            edit.replace(library, new vscode.Range(document.positionAt(start), document.positionAt(start + oldName.length)), name);
            return edit;
        },
    });
    try {
        const relative = (file: string) => vscode.workspace.asRelativePath(uri(file), false).replaceAll('\\', '/');
        const args = { path: relative(from), destination: relative(to) };
        const plan = content<FileMovePlan>(await invoke('ferroui_workspace_plan_xaml_move', args));
        assert.equal(plan.generatedRust?.[0].oldName, oldName);
        assert.equal(plan.documents.find(item => item.edit.uri.endsWith('/lib.rs'))?.after, expected);
        assert.ok(plan.documents.every(item => !item.edit.uri.endsWith('/xaml/views.rs')));
        await vscode.window.showTextDocument(document);
        content(await invoke('ferroui_workspace_move_xaml', { ...args, review: plan.review }));
        assert.equal(document.getText(), expected);
        assert.equal((await vscode.workspace.openTextDocument(generated)).getText(), generatedSource);
        const exists = (file: string) => vscode.workspace.fs.stat(uri(file)).then(() => true, () => false);
        assert.ok(await exists(to));
        await vscode.commands.executeCommand('undo');
        await until(async () => document.getText() === source && await exists(from) && !await exists(to));
        await vscode.commands.executeCommand('redo');
        await until(async () => document.getText() === expected && await exists(to) && !await exists(from));
        console.log('Generated XAML Rust references used the rename provider and shared the file move Undo and Redo');
    } finally {
        provider.dispose();
    }
}
